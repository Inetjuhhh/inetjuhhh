## 's Avonds

De meeste dagjesmensen vertrekken rond zes uur. Wij bleven, en liepen bij zonsondergang over de brug terug, met Mont-Saint-Michel achter ons, oranje gekleurd door de zon en daarna verlicht door honderden lampjes. Dan voel je pas echt hoe bijzonder deze plek is.

Op het eiland eet je de beroemde **omelet van Mère Poulard**: een luchtige, schuimige omelet die in koperen pannen boven een houtvuur wordt gebakken. Het is erg duur, en eigenlijk gewoon een omelet. Maar we zijn op huwelijksreis, dus we deden het toch.
