Je ziet hem al van kilometers ver: een kegelvormig eiland met een middeleeuws stadje tegen de hellingen en een abdij met een spitse toren erbovenop. **Mont-Saint-Michel** staat in een enorme baai op de grens van Normandië en Bretagne, en is na Parijs de meest bezochte plek van Frankrijk.

## De brug of het wad

Tegenwoordig loop je over een lange, moderne loopbrug naar het eiland, of neem je de pendelbus. Maar er is ook een andere manier: te voet door de baai, bij eb, zoals de pelgrims vroeger deden. Dat mag alleen met een erkende gids, en dat heeft een reden.

## De tocht

We vertrokken uit **Genêts**, aan de overkant van de baai, met een groep van twintig mensen en onze gids Thibault. Schoenen uit, broek opgerold, en lopen maar. Het is zeven kilometer, zo'n tweeënhalf uur.

De bodem van de baai is van alles tegelijk: hard en ribbelig zand, zachte modder waar je tot je enkels in wegzakt, en stukken waar je tot je knieën door stromend water loopt. En dan is er het **drijfzand**. Thibault liet het zien: hij sprong op een stuk zand dat er heel gewoon uitzag, en zakte langzaam weg tot zijn knieën. "Niet in paniek raken," zei hij, "en jezelf plat naar achteren laten vallen." Daarna mocht iedereen het proberen. Ik zakte tot mijn dijen weg, en moest door Bas en een Duitse man worden uitgetrokken.

