## De abdij

Bovenaan staat de **abdij**, gebouwd vanaf de tiende eeuw. Ze is als een taart in lagen tegen de rots gebouwd, met zalen, kerken en gangen boven op elkaar. Het mooiste vond ik het **klooster**: een binnentuin met een galerij van 137 sierlijke zuiltjes, helemaal bovenin, alsof hij in de lucht hangt. Door de bogen aan één kant zie je alleen lucht en zee.

