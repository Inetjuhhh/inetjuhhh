## Pointe du Hoc

Een paar kilometer westelijker ligt **Pointe du Hoc**, een rotspunt met kliffen van dertig meter hoog. Hier klommen Amerikaanse Rangers op D-Day met touwladders en enterhaken naar boven, om de Duitse kanonnen uit te schakelen. Van de 225 mannen waren er na twee dagen nog 90 in staat om te vechten.

Het terrein ziet er nog steeds uit als een maanlandschap: enorme bomkraters, overwoekerd met gras, en de resten van betonnen bunkers. Je kunt er gewoon tussendoor lopen. In een van de bunkers zie je nog de inslagen van kogels in het beton.

