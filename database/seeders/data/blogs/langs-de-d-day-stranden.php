## D-Day

Op 6 juni 1944 begon de grootste invasie over zee uit de geschiedenis. Ruim 156.000 Amerikaanse, Britse, Canadese en andere geallieerde soldaten landden op vijf stranden langs de Normandische kust, met de codenamen **Utah**, **Omaha**, **Gold**, **Juno** en **Sword**. Duizenden van hen kwamen die dag om.

We hadden er een hele dag voor uitgetrokken, en dat was eigenlijk te weinig.

## Omaha Beach

Op **Omaha Beach** viel het grootste aantal slachtoffers. De Duitsers zaten hier hoog op de heuvels in bunkers, en de Amerikaanse soldaten moesten honderden meters open strand over, onder vuur. Je kent de beelden misschien uit de film *Saving Private Ryan*.

Nu is het een breed, rustig zandstrand. Er waren families met windschermen, kinderen met schepjes en emmertjes, en een man die zijn hond uitliet. Bij de vloedlijn staat een groot stalen kunstwerk, **Les Braves**, ter nagedachtenis van de soldaten. Ik stond er met mijn voeten in het water en probeerde me voor te stellen hoe het hier geweest moest zijn. Dat lukt niet. Gelukkig maar, eigenlijk.

## De Amerikaanse begraafplaats

Boven Omaha Beach, in **Colleville-sur-Mer**, ligt de **Normandy American Cemetery**. Er liggen 9.388 soldaten begraven, onder witte marmeren kruisen en davidsterren, in eindeloze, kaarsrechte rijen op een perfect gemaaid grasveld. Op elke grafsteen staat een naam, een eenheid, een staat en een datum. Veel van de jongens waren negentien of twintig.

