India is geen land dat je bezoekt. India is een land dat je overkomt. Dat zei een Engelse backpacker tegen ons op onze eerste avond in Delhi en ik heb er drie weken lang aan moeten denken. Het is druk, luid, chaotisch, soms frustrerend en vaak overweldigend. Maar het is ook het meest kleurrijke, gastvrije en verrassende land waar ik ooit ben geweest.

Deze reis maakten we jaren geleden, maar Rajasthan is zo'n tijdloze bestemming dat ik denk dat de meeste tips nog steeds kloppen. Dit was onze route.

## Onze route in het kort

- **Jaipur** (4 nachten)
- **Pushkar** (3 nachten)
- **Jodhpur** (3 nachten)
- **Jaisalmer** (4 nachten, waarvan 1 in de woestijn)
- **Udaipur** (5 nachten)

Tussen de steden reisden we met de trein en twee keer met een nachtbus. De laatste keer met een privéchauffeur, omdat er geen goede verbinding was.

## Jaipur: de roze stad

Jaipur heet de roze stad omdat de oude stad in 1876 roze werd geschilderd ter ere van het bezoek van de Prins van Wales. Inmiddels is het meer terracotta dan roze, maar het blijft een bijzonder gezicht.

De **Hawa Mahal**, het Paleis van de Winden, is waarschijnlijk het bekendste gebouw van de stad: een gevel met 953 kleine raampjes, waardoor de vrouwen van het hof vroeger ongezien het straatleven konden bekijken. Tip: bekijk hem vanaf het dakterras van een van de koffietentjes aan de overkant. Daar heb je het beste uitzicht.

Het **Amber Fort** ligt een kwartier buiten de stad op een heuvel. Het is enorm, met binnenplaatsen, spiegelzalen en eindeloze gangen. De Sheesh Mahal, de spiegelzaal, is werkelijk prachtig: duizenden kleine stukjes spiegel in het plafond die bij kaarslicht zouden schitteren als een sterrenhemel.

## Pushkar: even op adem komen

Na het lawaai van Jaipur was **Pushkar** een verademing. Het is een kleine, heilige stad rond een meer, met tientallen *ghats* (trappen naar het water) waar pelgrims zich wassen. Vlees en alcohol zijn in de hele stad verboden. Het tempo ligt laag en we deden er drie dagen bijna niks, behalve chai drinken, wandelen en naar de zonsondergang kijken vanaf de Savitri-tempel op de heuvel.

Let op bij de ghats: er lopen mannen rond die je een bloem in je hand drukken en je vervolgens een "puja" (gebed) laten doen, waarna ze een flinke donatie vragen. Vriendelijk nee zeggen is prima.

## Jodhpur: de blauwe stad

Vanuit het **Mehrangarh Fort**, dat hoog op een rots boven de stad uittorent, zie je pas echt waarom Jodhpur de blauwe stad heet. De oude stad ligt aan je voeten als een zee van blauwe huisjes. Het fort is volgens mij het mooiste van heel Rajasthan, en de audiotour is echt een aanrader: vol verhalen over maharadja's, oorlogen en tragische liefdes.

Eet in Jodhpur een **makhaniya lassi** bij Shri Mishrilal Hotel bij de klokkentoren: een dikke, romige yoghurtdrank met saffraan en kardemom. Ik droom er nog weleens van.

## Jaisalmer: de gouden stad en de woestijn

Jaisalmer ligt diep in de Tharwoestijn, vlak bij de grens met Pakistan. Het fort van gele zandsteen rijst uit de woestijn op als een zandkasteel en er wonen nog steeds duizenden mensen in. Dat maakt het heel levendig, maar het fort heeft ook last van het toerisme: het rioolsysteem kan de vele gasthuizen niet aan. We kozen daarom bewust voor een hotel buiten de muren.

Het hoogtepunt was een **kamelensafari** met een overnachting in de woestijn. Laat in de middag vertrokken we met een kleine groep op kamelen de duinen in. Ik zal niet liegen: een kameel is geen comfortabel vervoermiddel. Maar toen we bij zonsondergang op een duin zaten, onze gids op een vuurtje chapati's bakte en de sterren één voor één verschenen, was ik alle pijn vergeten. We sliepen onder de blote hemel, in een dikke deken, met alleen de geluiden van de kamelen om ons heen.

## Udaipur: de romantiek

We sloten af in **Udaipur**, de stad van de meren, en volgens velen de meest romantische stad van India. En dat is niet overdreven. Witte paleizen weerspiegelen in het **Pichola-meer**, er zijn talloze dakterrassen met uitzicht op het water en 's avonds klinkt er muziek uit de havelis.

Wat je moet doen:

- Bezoek het **City Palace**, het grootste paleizencomplex van Rajasthan.
- Neem een boottocht over het meer bij zonsondergang.
- Ga naar een avondvoorstelling met traditionele dans in **Bagore ki Haveli**.
- Volg een workshop miniatuurschilderen. Ik heb er een klein olifantje geschilderd dat nog steeds in onze woonkamer hangt.

> Zittend op een dakterras in Udaipur, met een kop chai en het meer dat roze kleurde in het laatste licht, wist ik dat ik ooit terug zou komen.

## Praktische tips voor Rajasthan

1. **Boek treinen ruim van tevoren** via de website of app van IRCTC, of laat je hotel het regelen. De populaire treinen zitten vaak vol.
2. **Draag bedekkende kleding**, zeker als vrouw. Een lichte broek en een shirt met mouwen zijn in de meeste situaties prima, en een sjaal is altijd handig.
3. **Onderhandel**, op markten en met riksjachauffeurs. Begin op ongeveer de helft van de vraagprijs.
4. **Neem tijd**. Rajasthan is groot, de afstanden zijn lang en het reizen is vermoeiend. Liever minder plekken en langer blijven.
5. **Eet vegetarisch**. De vegetarische keuken van Rajasthan is fantastisch en je loopt minder risico op een gevoelige maag.

Drie weken was eigenlijk te kort. Maar dat is waarschijnlijk precies wat iedereen over India zegt.
