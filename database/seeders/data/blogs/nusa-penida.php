## Snorkelen met manta's

Het hoogtepunt kwam op dag twee: snorkelen bij **Manta Point**. Al na vijf minuten zwom er een reuzenmanta onder me door, met een spanwijdte van minstens drie meter. Langzaam, zwevend, alsof hij vloog. Daarna nog een, en nog een. Ik heb zo hard in mijn snorkel gegild dat ik water binnenkreeg.

## Nusa Penida in het kort

- **Hoe lang**: twee nachten. Een dagtrip vanaf Bali kan, maar dan zit je de hele dag in een auto.
- **Vervoer**: neem een auto met chauffeur, tenzij je een ervaren scooterrijder bent.
- **Vroeg op**: bij Kelingking is het vanaf tien uur heel druk.
