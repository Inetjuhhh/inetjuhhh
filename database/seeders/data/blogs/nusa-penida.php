## Diamond Beach

Aan de oostkust ligt **Diamond Beach**, misschien wel het mooiste strand van het eiland: wit zand, turquoise water en spitse rotsen in zee. Je komt er via een trap die in de rots is uitgehakt. In 2018 was die net klaar, en we hadden het strand bijna voor onszelf.

