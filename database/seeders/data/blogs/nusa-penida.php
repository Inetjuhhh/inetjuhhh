## Broken Beach en Angel's Billabong

Een stukje verderop ligt **Broken Beach**: een ronde baai, omringd door kliffen, waar de zee via een natuurlijke stenen boog naar binnen stroomt. Er vlakbij ligt **Angel's Billabong**, een natuurlijk zwembad in de rotsen met helder groen water. Bij eb kun je erin zwemmen, maar pas op met hoge golven.

