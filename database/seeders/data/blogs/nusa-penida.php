## Hoe je er komt

Nusa Penida ligt ten zuidoosten van Bali. Vanuit Sanur vertrekken elk uur snelle boten, die er een halfuur over doen. De zee kan ruw zijn, dus neem een reisziektetabletje en ga achterin zitten. Er is geen haven met een steiger: je springt bij aankomst gewoon tot je knieën in het water, met je tas boven je hoofd.

## De wegen

Op Nusa Penida huurt iedereen een scooter of een auto met chauffeur. Wij hadden het eerst geprobeerd met de scooter, maar na tien minuten hebben we dat plan bijgesteld. De wegen waren in 2018 echt verschrikkelijk: steile hellingen met losse stenen, gaten zo groot als een badkuip, en stukken die eigenlijk een rivierbedding waren. We zagen meerdere toeristen met verband om hun knieën en ellebogen.

We namen voor 600.000 roepia (35 euro) een auto met chauffeur, Komang. Beste beslissing van de reis.

