## De stad

Eerst het goede nieuws: Phnom Penh is een leuke stad. Hij ligt op de plek waar de Tonle Sap uitkomt in de Mekong, en langs de rivier loopt een lange boulevard waar 's avonds de hele stad samenkomt om te sporten, te eten en te kletsen. Er zijn groepen vrouwen die aerobics doen op harde muziek, kinderen die met een plastic bal voetballen, monniken die selfies maken.

Het **Koninklijk Paleis** is prachtig, met gouden daken die omhoog krullen als vlammen. In de Zilveren Pagode ligt de vloer vol met meer dan vijfduizend zilveren tegels, en staat een Boeddha van smaragd en een van negentig kilo goud met bijna tienduizend diamanten.

## Tuol Sleng

Maar dan. In 1975 namen de Rode Khmer onder leiding van Pol Pot de macht over. Ze dreven de hele bevolking van Phnom Penh de stad uit, het platteland op. Ze wilden een communistische boerenstaat, zonder steden, geld, scholen of religie. In vier jaar tijd stierven bijna twee miljoen Cambodjanen, een kwart van de bevolking: door honger, dwangarbeid, ziektes en executies.

Een middelbare school midden in de stad werd **S-21**, een gevangenis waar zo'n twintigduizend mensen werden ondervraagd en gemarteld. Het is nu het **Tuol Sleng Genocide Museum**. De klaslokalen zijn nog zoals ze waren: ijzeren bedden, kettingen en de muren vol met zwart-witfoto's van de gevangenen. Mannen, vrouwen, kinderen. Ze kijken je aan.

We liepen met een audiotour door de gebouwen. Bas en ik zeiden twee uur lang bijna niks tegen elkaar.

## Choeung Ek

Daarna reden we met een tuktuk naar **Choeung Ek**, vijftien kilometer buiten de stad: een van de vele "killing fields". Het is nu een rustig, groen terrein met bomen en een meertje. Maar overal zie je kuilen in de grond, massagraven. Na de regen komen er nog steeds botten en stukjes kleding naar boven.

In het midden staat een witte stoepa met glazen wanden, waarin achtduizend schedels zijn opgestapeld. Ze zijn gesorteerd op leeftijd en geslacht.

