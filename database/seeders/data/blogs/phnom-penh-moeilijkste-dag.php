## Daarna

's Avonds zaten we aan de rivier, met een biertje, tussen de families en de joggers. Een jongetje van een jaar of zes kwam ons een armbandje verkopen, en daarna vooral heel veel vragen stellen. Hoe oud we waren, of we kinderen hadden, waarom niet, of we voetbal leuk vonden.

