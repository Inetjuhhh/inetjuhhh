Na drie dagen eten (en een kilo erbij) namen we de nachtbus naar Arequipa. Peruaanse langeafstandsbussen zijn verrassend luxe: grote stoelen die bijna plat gaan, een dekentje en een warme maaltijd. Morgen staat er een vulkaan voor de deur.
