## Een culinaire wandeling door de oude stad

Het historische centrum van Lima is Unesco-werelderfgoed, met de **kathedraal**, het presidentieel paleis en houten balkons uit de koloniale tijd. We maakten er een eetwandeling met een gids, Lucía, die ons liet zien dat de Peruaanse keuken eigenlijk een mix is van allerlei culturen:

- **Chifa**: Chinees-Peruaans eten, meegebracht door Chinese arbeiders in de negentiende eeuw. Probeer *arroz chaufa*, de Peruaanse nasi.
- **Nikkei**: Japans-Peruaans, met sushi met aji-peper en tiradito, een soort ceviche in sashimistijl.
- **Anticuchos**: spiesjes van gegrild runderhart, een erfenis van Afrikaanse slaven. Klinkt eng, smaakt fantastisch.
- **Lomo saltado**: geroerbakte biefstuk met ui, tomaat en... patat. Waarom niet?
- **Picarones**: gefrituurde donuts van zoete aardappel en pompoen, met siroop.

