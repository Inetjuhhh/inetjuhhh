Toen we vertelden dat we drie dagen in Lima zouden blijven, kregen we van iedereen dezelfde reactie: "Waarom? Daar is niks." Een grijze stad onder een deken van mist (de *garúa*), druk en chaotisch. Allemaal waar. Maar Lima heeft één ding wat bijna geen andere stad heeft: het eten.

## Ceviche

We begonnen waar je in Lima moet beginnen: bij een **cevichería**. Ceviche is het nationale gerecht van Peru: rauwe vis, een paar minuten gemarineerd in limoensap met rode ui, koriander en aji-peper. Je krijgt er zoete aardappel en grote, geroosterde maïskorrels (*cancha*) bij. Het sap dat overblijft heet *leche de tigre*, tijgermelk, en wordt ook apart geserveerd in een glaasje. Het schijnt goed te zijn tegen een kater.

Ceviche eet je alleen tussen de middag. Peruanen vinden het raar om 's avonds rauwe vis te eten, omdat die dan niet meer vers van de markt komt. We aten de beste in een eenvoudig restaurantje in Surquillo, waar de eigenaar ons na afloop een shotje pisco gaf.

## Miraflores en Barranco

