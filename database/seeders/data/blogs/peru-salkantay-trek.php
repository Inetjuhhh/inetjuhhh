Lang voordat er kinderen waren, voordat we een huis met een tuin hadden en voordat mijn ideale vakantie bestond uit een zwembad en een goed boek, liepen mijn vriend en ik in vijf dagen naar Machu Picchu. Het is inmiddels jaren geleden, maar ik denk er nog steeds bijna elke week aan. Toen ik laatst de foto's terugvond op een oude harde schijf, wist ik: hier moet een blog over komen.

## Waarom de Salkantay en niet de Inca Trail?

De klassieke Inca Trail is de bekendste route naar Machu Picchu. Er mogen maar een beperkt aantal mensen per dag op en de vergunningen zijn vaak maanden van tevoren uitverkocht. Wij waren te laat. Gelukkig is de Salkantay trek een geweldig alternatief: langer, hoger, ruiger en volgens velen zelfs mooier. Je hebt geen vergunning nodig en je loopt door een enorme variatie aan landschappen, van besneeuwde bergtoppen tot tropisch nevelwoud.

We boekten de tocht via een klein lokaal bureau in Cusco. Voor ongeveer 550 dollar per persoon hadden we een gids, een kok, muildieren voor de bagage, alle maaltijden, de overnachtingen, een entreeticket voor Machu Picchu en de trein terug naar Cusco.

## Eerst acclimatiseren

Cusco ligt op 3.400 meter hoogte. Op de eerste dag liep ik een trap op en moest ik halverwege gaan zitten omdat ik geen lucht kreeg. Dat is normaal, maar het laat wel zien hoe belangrijk het is om eerst te wennen aan de hoogte. We bleven vier dagen in Cusco en de Heilige Vallei voordat we vertrokken.

Wat hielp:

- Rustig aan doen, veel water drinken en geen alcohol de eerste dagen.
- **Coca-thee**. Het smaakt een beetje naar groene thee met hooi, maar het helpt echt tegen hoofdpijn.
- Wandelen naar de ruïnes rond Cusco, zoals Sacsayhuamán, als training.

## Dag 1: naar het Humantay-meer

Om vier uur 's ochtends werden we opgehaald. Na een busrit van een paar uur begonnen we bij Soraypampa met lopen. De eerste dag was meteen een flinke: een steile klim naar het **Humantay-meer** op 4.200 meter. Het water is onwerkelijk turquoise en ligt aan de voet van een gletsjer. Ik moest elke twintig stappen even stilstaan, maar boven was ik alle pijn vergeten.

We sliepen die nacht in kleine glazen hutjes met uitzicht op de Salkantay-berg. Het vroor buiten. Binnen lagen we in onze slaapzakken met een kruik warm water die de kok had gevuld. Ik heb zelden zo'n sterrenhemel gezien.

## Dag 2: de Salkantay-pas

Dit was de dag waar iedereen tegen opzag. Vanaf het kamp klommen we in een paar uur naar de **Salkantay-pas op 4.630 meter**, het hoogste punt van de tocht. Het pad zigzagt omhoog langs rotsen en sneeuw. De lucht is zo ijl dat elke stap moeite kost.

Onze gids Wilber liep de hele tijd achter de groep, vertelde verhalen over de berggoden van de Inca's en zong af en toe een liedje in het Quechua. Toen we boven kwamen, legde hij een kleine offergave neer van cocabladeren en vroeg hij ons hetzelfde te doen, als dank aan *Apu Salkantay*. Ik ben niet religieus, maar daar, met de gletsjer recht voor me en mijn hart dat nog in mijn keel bonsde, voelde het heel passend.

> Daarna ging het alleen nog maar naar beneden. Bijna tweeduizend meter in één middag. Mijn knieën hebben het me nooit vergeven.

## Dag 3: het nevelwoud

Wat ik niet had verwacht, is hoe snel het landschap verandert. 's Ochtends hadden we nog sneeuw gezien, en een dag later liepen we door een groen, vochtig oerwoud vol bloemen, kolibries en bananenbomen. We kwamen langs kleine boerderijen waar koffie werd verbouwd en mochten bij een van de families zelf bonen branden en malen.

Aan het eind van de dag gingen we naar de warmwaterbronnen van **Cocalmayo** bij Santa Teresa. Na drie dagen lopen in een bad van 38 graden liggen met uitzicht op de bergen: dat is pure luxe.

## Dag 4: langs het spoor naar Aguas Calientes

De vierde dag is de makkelijkste. Vanaf Hidroeléctrica loop je ongeveer drie uur langs het spoor naar **Aguas Calientes**, het dorp aan de voet van Machu Picchu. Het pad is vlak en loopt door een dichtbegroeide vallei. Af en toe komt er een trein voorbij en moet je even opzij. Als je goed omhoog kijkt, zie je hoog op de berg al de eerste terrassen van Machu Picchu.

## Dag 5: Machu Picchu

We stonden om half vier op om als eersten bij de bus te staan. Toen we om zes uur door de poort liepen, hing er dichte mist over de ruïnes. We zagen helemaal niets. Een beetje teleurgesteld gingen we op een muurtje zitten wachten.

En toen gebeurde het. Langzaam, alsof iemand een gordijn opentrok, trok de mist op en verscheen de stad. De terrassen, de tempels, de beroemde piek van Huayna Picchu erachter. Iedereen om ons heen was stil. Ik moet eerlijk zeggen dat ik een traantje heb weggepinkt.

## Praktische tips

- **Neem je eigen wandelschoenen mee** en loop ze van tevoren goed in. Ik had blaren op dag twee.
- **Laagjes**. Van vriespunt tot dertig graden in drie dagen.
- **Contant geld** voor fooien. Het is gebruikelijk om de gids, kok en muildierdrijvers aan het eind iets te geven.
- **Boek Machu Picchu-tickets op tijd**, zeker als je een specifiek circuit of de klim naar Huayna Picchu wilt doen.
- **Insectenwerend middel** voor dag drie en vier. De zandvliegjes zijn meedogenloos.

Ik weet niet of ik deze tocht nu nog zou doen. Mijn knieën zeggen nee, mijn hart zegt ja. Misschien over een jaar of tien, met de kinderen. Dan mogen zij de rugzak dragen.
