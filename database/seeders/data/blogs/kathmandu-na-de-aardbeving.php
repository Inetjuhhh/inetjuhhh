## Swayambhunath

Op een heuvel aan de westkant van de stad ligt **Swayambhunath**, beter bekend als de Apentempel. Je beklimt 365 treden (ja, ik heb ze geteld) en wordt onderweg in de gaten gehouden door brutale makaken. Boven heb je uitzicht over de hele vallei van Kathmandu. Het stoepa-complex is een mix van boeddhisme en hindoeïsme, zoals zoveel in Nepal: monniken en sadhoes lopen er gewoon naast elkaar.

## Durbar Square

Op **Kathmandu Durbar Square**, het oude koninklijke plein, was de schade het grootst. Een aantal tempels was helemaal ingestort, andere stonden in de steigers. Maar het leven ging door: duiven, marktkraampjes, mensen die op de tempeltrappen zaten te kletsen. In het **Kumari Ghar** woont de levende godin, een meisje dat tot haar eerste menstruatie als godin wordt vereerd. Als je geluk hebt, verschijnt ze even voor het raam. Wij hadden geen geluk.

