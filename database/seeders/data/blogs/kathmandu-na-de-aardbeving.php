## Bhaktapur

Een dag later namen we de bus naar **Bhaktapur**, een middeleeuwse stad op een half uur rijden. Ook hier veel schade, maar het oude centrum met zijn pagodes, houtsnijwerk en pottenbakkersplein is nog prachtig. Probeer er de **juju dhau**: "koning van de yoghurts", in een aardewerken schaaltje. Romig, zoet en een beetje zuur.

