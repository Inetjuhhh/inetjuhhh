Na drie weken India vlogen we van Varanasi naar Kathmandu. Een vlucht van een uur, en toch voelde het als een andere wereld. Het verkeer was minder, de toeters waren zachter en iedereen begroette ons met handen tegen elkaar en een "namaste".

## Na de aardbeving

Op 25 april 2015 kwamen bij een aardbeving met een kracht van 7,8 bijna negenduizend mensen om het leven. Hele dorpen in de bergen werden verwoest, en ook in Kathmandu stortten huizen en eeuwenoude tempels in. Anderhalf jaar later zag je het nog overal: scheuren in muren, houten balken die gevels overeind hielden, lege plekken waar ooit een tempel stond.

We twijfelden of we wel moesten gaan. Maar iedereen die we spraken was er heel duidelijk over: kom vooral. Toerisme is een van de grootste inkomstenbronnen van Nepal, en na de aardbeving bleven de toeristen weg. Juist nu hadden de guesthouses, gidsen en restaurants bezoekers nodig.

## Boudhanath

De **Boudhanath-stoepa** is een van de grootste boeddhistische stoepa's ter wereld, en een centrum voor Tibetaanse vluchtelingen. Hij was bij de aardbeving beschadigd en net opnieuw ingewijd toen wij er waren, helemaal wit gekalkt, met de beroemde ogen van Boeddha die vanaf de top in vier richtingen kijken.

We liepen met de pelgrims mee, met de klok mee rond de stoepa, langs de gebedsmolens. 's Avonds zaten we op een dakterras met een kop gemberthee en keken we naar de gebedsvlaggen die wapperden in de wind.

