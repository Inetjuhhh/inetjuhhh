Als je mij vraagt waarom ik zo van Thailand houd, dan is het antwoord simpel: het eten. Nergens ter wereld heb ik zo vaak achter elkaar zo lekker gegeten voor zo weinig geld. En nergens is dat zo duidelijk als in Bangkok, waar je op elke straathoek wel iets vindt dat sist, dampt of geurt naar knoflook en citroengras.

Deze keer waren we met z'n tweeën, voor een bruiloft van vrienden, en dat betekende: eten wat we wilden, wanneer we wilden. We verbleven vijf nachten in de stad en hebben bewust bijna nooit in een restaurant gegeten. Dit zijn de plekken en gerechten waar we steeds weer naar terugkeerden.

## Yaowarat: Chinatown na zonsondergang

Overdag is Yaowarat Road gewoon een drukke straat met goudwinkels en apotheken. Maar zodra de zon ondergaat, verandert het in één lange openluchtkeuken. Kraampjes worden opgezet, neonborden gaan aan en overal staan rijen plastic tafeltjes op de stoep.

Wat je hier moet proberen:

- **Gegrilde zeevruchten** bij de grote kramen op de hoek met Soi Phadung Dao. Kies je eigen garnalen of inktvis en laat ze ter plekke grillen.
- **Kuay jab nam sai**, een peperige soep met opgerolde rijstnoedels. Bij Nai Ek Roll Noodles staat altijd een rij, maar die gaat snel.
- **Geroosterde kastanjes** voor onderweg.
- **Bua loy**, kleine rijstballetjes in warme kokosmelk, als toetje.

Tip: ga er op een doordeweekse avond heen en neem de MRT naar station Wat Mangkon. Op maandag zijn veel kraampjes dicht.

## Jay Fai: de omelet met een Michelinster

Ja, we hebben het gedaan. We hebben drie uur in de rij gestaan voor een krabomelet. Jay Fai is een oudere dame met een skibril op die al tientallen jaren boven een houtskoolvuur staat te koken en in 2018 een Michelinster kreeg. De omelet is enorm, krokant van buiten en tot de rand gevuld met dikke stukken krab.

Was het die wachttijd waard? Eerlijk gezegd: het was een unieke ervaring en de omelet was echt heel lekker. Maar met ongeveer 1.500 baht is hij ook de duurste maaltijd van onze hele reis geweest. Als je weinig tijd hebt in Bangkok, zou ik het overslaan. Als je het verhaal wilt kunnen vertellen: ga vroeg, schrijf je naam op de lijst en ga intussen ergens anders iets drinken.

## Overwinningsmonument: boat noodles

Bij het Victory Monument vind je Boat Noodle Alley, een rijtje eettentjes langs een kanaal. Vroeger werden deze noedels vanuit bootjes verkocht, vandaar de naam. De kommetjes zijn heel klein, zo'n drie happen, en kosten rond de 20 baht per stuk. Het is de bedoeling dat je er een stapel van eet. Wij kwamen met z'n tweeën op veertien kommetjes en dat vond de eigenaar duidelijk een beetje teleurstellend.

## Or Tor Kor Market: de nette versie

Wil je even geen chaos? Dan is de Or Tor Kor Market naast het Chatuchak-weekendmarktterrein perfect. Het is een overdekte, superschone markt met het mooiste fruit dat ik ooit heb gezien. Hier aten we de beste **mango sticky rice** van de reis: kleefrijst met zoute kokosroom en een mango die zo rijp was dat hij bijna uit elkaar viel. Ook de curry's en kant-en-klare gerechten achterin zijn een aanrader.

## Onze vaste ontbijt- en lunchgerechten

Naast de bekende plekken aten we vooral bij de kraampjes in de straten rond ons hotel in de wijk Ari. Dit waren onze favorieten:

- **Khao man gai**: gepocheerde kip op rijst die in kippenbouillon is gekookt, met een pittige gembersaus. Ideaal ontbijt.
- **Pad kra pao**: gehakt gewokt met heilige basilicum en chili, met een gebakken ei erop. Bestel het *phet nit noi* (een beetje pittig), tenzij je echt wat gewend bent.
- **Som tam**: papajasalade met limoen, vissaus en pinda's. Fris en vurig tegelijk.
- **Jok**: rijstepap met gember en een zacht ei, perfect na een lange avond.

## Praktische tips voor streetfood in Bangkok

Veel mensen zijn bang om ziek te worden van streetfood. Wij zijn in vijf dagen geen moment ziek geweest, en dat komt volgens mij door een paar simpele regels:

1. Eet bij kraampjes waar veel locals zitten. Veel doorloop betekent vers eten.
2. Kies gerechten die voor je ogen worden gekookt of gewokt.
3. Neem altijd wat kleingeld mee. Een briefje van 1.000 baht kunnen ze vaak niet wisselen.
4. Ijs in drankjes is in Bangkok bijna altijd fabrieksijs en dus veilig. Herkenbaar aan het gat in het midden.

Gemiddeld gaven we per persoon zo'n 300 tot 400 baht per dag uit aan eten, inclusief drankjes en fruit. Omgerekend is dat ongeveer tien euro. De omelet van Jay Fai niet meegerekend, natuurlijk.

