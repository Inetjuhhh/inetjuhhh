## Waarom Costa Rica?

Sam wordt over twee weken vijf. Hij is nu oud genoeg om echt dingen te onthouden, om zelf een stuk te wandelen, en hij is (net als zijn ouders) gek op dieren. Al maanden kijkt hij elke avond voor het slapen naar natuurfilmpjes. Zijn lievelingsdier: de luiaard. "Omdat hij net zo langzaam is als papa 's ochtends."

Costa Rica is een klein land, ongeveer zo groot als Nederland en België samen, maar met **zes procent van alle dier- en plantensoorten ter wereld**. Een kwart van het land is beschermd natuurgebied. Er zijn vulkanen, nevelwouden, regenwouden, stranden aan twee oceanen, en je ziet overal dieren: luiaards, apen, toekans, kikkers, schildpadden, krokodillen.

Daarnaast:

- **Het is veilig** en goed georganiseerd, ook voor gezinnen.
- **Je kunt er goed zelf rondrijden** met een huurauto.
- **Er zijn geen grote gezondheidsrisico's** die je met een kind zorgen moeten baren, al laten we ons natuurlijk goed informeren bij de GGD.
- **Het is eind december droog seizoen** aan de Pacifische kant.
- **"Pura vida"**: het motto van het land, dat zoiets betekent als "het pure leven", en dat gebruiken de Costa Ricanen als groet, als bedankje en als antwoord op "hoe gaat het?". Dat klinkt als iets voor ons.

