## Kerst in de tropen

We vieren dit jaar kerst en oud en nieuw in Costa Rica. Dat vonden we best een grote stap: kerst is bij ons altijd met de familie, met mijn moeders gourmetstel en de kerstboom bij mijn ouders. Maar de opa's en oma's vonden het een prachtig idee. Mijn moeder vroeg alleen of ze wel videobellen mocht op eerste kerstdag. Natuurlijk, mam.

Sam wil weten of de kerstman ook in Costa Rica komt, en hoe hij dan door de jungle moet vliegen. Daar denken we nog even over na.

