In 2015 kwamen we met de nachttrein in **Chiang Mai** aan. Dit keer namen we het vliegtuig: een uur vliegen in plaats van dertien uur in de trein. Sam had graag in het stapelbed van de trein geslapen, zei hij. Volgende keer, beloofden we.

Chiang Mai is een fijne stad met een kind: rustiger dan Bangkok, iets koeler (zeker 's avonds, in januari) en met veel groen. We huurden een huisje met een tuin net buiten de oude stad, in de wijk **Nimman**, met een speeltuin om de hoek.

## De oude stad

We liepen weer door de **oude stad**, binnen de gracht en de oude stadsmuur. Sam vond vooral de gracht interessant, met de vissen, de schildpadden en een man die met een hengel stond te vissen. We bezochten weer **Wat Chedi Luang**, en stonden weer bij die enorme half ingestorte chedi. Bas keek rond of Pong er nog was, de jonge monnik met wie we toen praatten. Die was er niet meer, natuurlijk. Maar er zat een andere jonge monnik, die Sam een armbandje gaf van wit katoen, voor geluk.

