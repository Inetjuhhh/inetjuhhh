## Doi Inthanon

Op onze laatste dag reden we met een chauffeur naar **Doi Inthanon**, de hoogste berg van Thailand (2.565 meter). Boven was het maar twaalf graden, en Sam had voor het eerst die reis een trui aan. In het nevelwoud vol mossen en orchideeën zagen we kleine, felgekleurde vogeltjes, die volgens onze gids alleen hier voorkomen.

