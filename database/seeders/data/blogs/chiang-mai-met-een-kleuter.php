## Wat Umong

Een tempel die we de vorige keer hadden gemist: **Wat Umong**, een bostempel aan de voet van de berg Doi Suthep. Het bijzondere: hij is gebouwd met **tunnels**. Lange, smalle gangen van baksteen onder een heuvel, met nisjes waarin Boeddhabeelden staan, verlicht door kaarsjes. Voor een kind van drie is dat een echt avontuur. Sam liep met een zaklampje voorop. "Kom maar mama, ik weet de weg."

Buiten is een groot bos met boomtakken waar spreuken aan hangen, een vijver met duizenden meervallen en schildpadden die je mag voeren, en een rustige, bijna betoverende sfeer.

## De kookles

De kookschool van toen bestond niet meer. Maar we vonden een andere, op een boerderijtje buiten de stad, met een **kinderprogramma**. Sam kreeg een eigen schortje, een eigen houten werkbankje en een eigen kok, Bee. Hij mocht kruiden plukken in de tuin, zelf een mango sticky rice maken en, zijn favoriet, **loempia's rollen**. Ze waren een beetje lek. Ze waren heerlijk. Hij heeft ze trots aan iedereen in de groep laten proeven.

Bas maakte weer zijn groene currypasta. Bee zei dat die erg goed was. Bas heeft het de rest van de dag nog vier keer herhaald.

## En de olifanten?

Dat is de vraag die we het vaakst krijgen. Rond Chiang Mai zijn tientallen olifantenkampen. Tien jaar geleden kon je er nog overal op olifanten rijden. Gelukkig is dat aan het veranderen, maar veel "sanctuaries" zijn nog steeds minder diervriendelijk dan ze beweren: olifanten die kunstjes doen, die worden vastgeketend of die je met een groep van twintig mensen moet wassen.

Wij kozen voor een bezoek aan een opvangcentrum waar je de olifanten **alleen van een afstand bekijkt**, zonder ze aan te raken of te wassen. Je loopt met een gids mee door het bos, en ziet ze eten, in de modder rollen en met elkaar spelen. Sam vond het, eerlijk gezegd, iets minder spannend dan de varanen van Lumphini. Maar het voelde goed.

