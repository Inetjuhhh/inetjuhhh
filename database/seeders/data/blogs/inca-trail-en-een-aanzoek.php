## De Inca Trail

De klassieke **Inca Trail** is een pad van 42 kilometer dat de Inca's vijfhonderd jaar geleden aanlegden van de Heilige Vallei naar Machu Picchu. Je mag hem alleen lopen met een erkende organisatie, en er mogen maar vijfhonderd mensen per dag op (inclusief dragers en gidsen). De vergunningen zijn maanden van tevoren uitverkocht. Wij boekten in november.

Onze groep bestond uit twaalf mensen, met een gids, Wilber, een kok en veertien dragers. De dragers zijn ongelooflijk: ze lopen met 25 kilo op hun rug, op sandalen gemaakt van oude autobanden, en rennen je voorbij om je tent al op te zetten voor je aankomt.

## Dag 1 en 2: Dead Woman's Pass

De eerste dag is een opwarmertje: langs de rivier, langs kleine Inca-ruïnes en boerderijtjes. De tweede dag is de zwaarste: van 3.000 naar **4.215 meter**, naar de pas die **Warmiwañusca** heet, Dode Vrouw. (Je hoopt dat het niet naar een wandelaar is vernoemd.) Duizenden stenen treden, de lucht wordt steeds dunner, en je lopen wordt steeds langzamer.

Toen ik boven aankwam, stond de hele groep te klappen. Ik huilde. Alweer. Bas zei niets, maar gaf me een lange knuffel. Hij liep de hele dag al vreemd voorzichtig met zijn rugzak.

## Dag 3: de mooiste dag

Dag drie is volgens Wilber de mooiste, en dat klopte. Het pad gaat door nevelwoud, langs orchideeën, door een tunnel die de Inca's in de rots hebben uitgehakt, en langs de ene ruïne na de andere: **Runkurakay**, **Sayacmarca**, **Phuyupatamarca** (de stad boven de wolken). En op het eind van de middag **Wiñay Wayna**, "eeuwig jong": steile terrassen tegen een berghelling, met een tempel en baden. We hadden het bijna voor onszelf.

