## Dag 4: de Zonnepoort

Om half vier 's ochtends werden we gewekt. Op dag vier wacht iedereen in het donker bij een controlepost tot die om half zes opengaat, en dan loop je het laatste uur naar **Inti Punku**, de **Zonnepoort**. Dat is de oude toegangspoort tot Machu Picchu, op een bergkam erboven.

We kwamen aan terwijl de mist nog in de vallei hing. En toen trok die langzaam weg, en lag het daar: **Machu Picchu**, in het eerste zonlicht, met de spitse top van Huayna Picchu erachter. Precies zoals op de foto's, en toch totaal anders.

