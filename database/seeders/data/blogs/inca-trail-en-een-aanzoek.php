Ik draaide me om naar Bas om te zeggen hoe mooi het was. Maar hij stond niet meer naast me. Hij zat op één knie, met een klein houten doosje in zijn hand. Het doosje dat hij al vier dagen in zijn rugzak droeg, dat hij in Cusco drie keer had gecontroleerd en dat hij in Miraflores al bijna had laten zien, bij het beeld van het zoenende stel, maar toen vond hij het daar te kitscherig.

"Wil je met me trouwen?"

Ik heb ja gezegd. Of eigenlijk zei ik eerst "Echt?", toen "Ja!", en toen "Sta op, je knie wordt nat." De hele groep stond om ons heen te juichen, en een Amerikaanse vrouw uit een andere groep had het allemaal gefilmd. Ze stuurde het ons later op.

## Machu Picchu

Daarna liepen we met Wilber nog drie uur door Machu Picchu zelf. De Tempel van de Zon, de Intihuatana-steen, de terrassen, de lama's die tussen de toeristen door grazen. Ik heb er eerlijk gezegd weinig van onthouden. Ik keek de hele tijd naar de ring om mijn vinger.

