Angkor Wat stond al jaren op mijn lijstje. En toen ik er eindelijk stond, om half zes 's ochtends, samen met een paar duizend andere mensen die allemaal hun telefoon omhoog hielden, dacht ik heel even: was dit het nou? Gelukkig bleek dat moment het enige drukke van onze drie dagen in Angkor. Met een beetje planning kun je deze enorme tempelstad namelijk prima op een rustige manier beleven.

## Eerst wat achtergrond

Angkor was tussen de negende en vijftiende eeuw de hoofdstad van het Khmer-rijk. Het gebied is gigantisch: meer dan vierhonderd vierkante kilometer met honderden tempels, waarvan Angkor Wat de bekendste en grootste is. Je uitvalsbasis is de stad **Siem Reap**, die zo'n zeven kilometer verderop ligt.

## Tickets

Voor Angkor heb je een Angkor Pass nodig. Je kunt kiezen uit drie varianten:

- **1 dag**: 37 dollar
- **3 dagen** (binnen 10 dagen te gebruiken): 62 dollar
- **7 dagen** (binnen een maand): 72 dollar

Wij namen de driedaagse pas en dat raad ik iedereen aan. Eén dag is echt te weinig en na drie dagen ben je wel klaar met tempels, eerlijk gezegd. Koop je pas online of bij het officiële ticketkantoor, niet bij iemand op straat.

## Vervoer: tuktuk, fiets of e-bike

We huurden de eerste twee dagen een tuktuk met chauffeur, Sokha, die we via ons guesthouse hadden geregeld. Voor de standaardroute betaalden we zo'n 18 dollar per dag, voor de verder gelegen tempels iets meer. Sokha wachtte geduldig bij elke tempel, had altijd koude flesjes water in een koelbox en gaf ons tips over wanneer we waar moesten zijn om de drukte te ontwijken.

De derde dag huurden we elektrische fietsen. Dat was een geweldige manier om op eigen tempo rond te rijden, al is het in de middaghitte wel zwaar.

## Dag 1: de kleine cirkel, maar dan andersom

De meeste tours en tuktuks volgen dezelfde route: zonsopkomst bij Angkor Wat, daarna de Bayon en dan Ta Prohm. Met als gevolg dat alle drukte zich als één grote golf door het park verplaatst. Sokha raadde ons aan om het precies andersom te doen.

Na de zonsopkomst bij Angkor Wat, waar we ons toch maar tussen de menigte hadden gewurmd, gingen we niet naar binnen, maar reden we meteen door naar **Ta Prohm**. Dit is de tempel waar enorme boomwortels zich over de muren hebben gedrapeerd, bekend van de film Tomb Raider. Om zeven uur waren we er bijna alleen. Het was stil, op wat vogels na, en het ochtendlicht viel tussen de bomen door op de stenen. Magisch.

Daarna gingen we door naar **Banteay Kdei** en **Srah Srang**, en pas rond het middaguur, toen de meeste groepen terug naar hun hotel gingen voor de lunch, liepen we Angkor Wat zelf binnen. De galerijen met de lange reliëfs waren heerlijk rustig.

## Dag 2: de Bayon en Angkor Thom

**Angkor Thom** is een ommuurde stad binnen het complex, met in het midden de **Bayon**: een tempel met meer dan tweehonderd stenen gezichten die je vanuit alle hoeken aankijken. Het is de meest bijzondere plek die ik in Angkor heb gezien. Je dwaalt door gangen en over trappen en overal waar je kijkt, glimlacht er weer een gezicht naar je.

Tip: ga laat in de middag, rond vier uur. Het licht is dan warm en de dagtripgroepen zijn al vertrokken voor zonsondergang bij Phnom Bakheng.

## Dag 3: verder weg

Op de laatste dag reden we naar twee tempels buiten het centrale gebied:

- **Banteay Srei**, een kleine tempel van roze zandsteen met zulke fijn gesneden versieringen dat het lijkt op kantwerk. Ongeveer drie kwartier rijden.
- **Beng Mealea**, een overwoekerde ruïne midden in de jungle, waar je over ingestorte muren en via houten looppaden doorheen klautert. Hier voelden we ons echt even ontdekkingsreizigers.

Voor deze tempels heb je wel een auto of tuktuk nodig, want ze liggen te ver om te fietsen.

> Het mooiste moment van onze drie dagen? Een oude monnik in een oranje gewaad die in Beng Mealea op een omgevallen steen zat te mediteren, terwijl het zonlicht door het bladerdak viel.

## Siem Reap

Siem Reap zelf is een gezellige stad met een levendige avondmarkt en de beruchte **Pub Street**, waar het bier 50 cent kost en de muziek tot diep in de nacht doorgaat. Niet helemaal ons ding meer, maar we hebben er één avond een paar cocktails gedronken en dat was heel leuk.

Wat ik wel aanraad: ga een avond naar de voorstelling van **Phare, the Cambodian Circus**. Dit is een sociaal project waarbij jongeren uit kansarme gezinnen worden opgeleid tot artiesten. De show is energiek, ontroerend en heel knap gedaan.

## Kort samengevat

1. Neem de driedaagse pas.
2. Draai de standaardroute om.
3. Ga 's middags naar Angkor Wat, als de groepen lunchen.
4. Neem water, zonnebrand en een sarong of sjaal mee: voor sommige tempels moeten je schouders en knieën bedekt zijn.
5. Huur een lokale chauffeur. Je helpt er de lokale economie mee en ze kennen alle trucjes.
