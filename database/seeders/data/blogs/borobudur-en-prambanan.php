## Jogja

We bleven nog drie dagen in Jogja. We bezochten de **kraton**, het paleis van de sultan, het waterkasteel **Taman Sari**, en een batikwerkplaats waar we zelf een doek mochten beschilderen met hete was. De mijne is een beetje mislukt. Hij hangt toch in ons huis.

En we aten **gudeg**, de specialiteit van de stad: jonge jackfruit, uren gestoofd in kokosmelk en palmsuiker. Zoet, zacht en hartig tegelijk. Ik stuurde een foto naar mijn moeder, en zij schreef terug: "Opa zou jaloers zijn."
