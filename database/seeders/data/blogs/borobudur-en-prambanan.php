## Borobudur

Om half vier reden we in een busje met chauffeur door de donkere rijstvelden naar **Borobudur**, het grootste boeddhistische monument ter wereld. Het werd gebouwd rond het jaar 800, raakte een paar eeuwen later in vergetelheid en werd overgroeid door de jungle, en in 1814 herontdekt.

Borobudur is gebouwd als een enorme stenen mandala in negen lagen. Op de onderste lagen vertellen 2.672 reliëfpanelen het leven van Boeddha en de weg naar verlichting. Hoe hoger je komt, hoe abstracter het wordt: bovenaan staan 72 klokvormige stoepa's met daarin elk een Boeddhabeeld, en in het midden één grote, lege stoepa. Het niets. De verlichting.

We zaten bovenaan toen de zon opkwam boven de vulkanen Merapi en Merbabu. De mist hing nog in de dalen, de palmbomen staken erbovenuit, en de stoepa's kleurden langzaam goud. Ik heb er honderd foto's van gemaakt, en geen enkele doet het recht.

