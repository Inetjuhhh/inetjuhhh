## Siësta

Na een ontbijt met nasi goreng (ja, om acht uur 's ochtends, het is hier heel normaal) reden we terug naar Jogja en sliepen we een paar uur. Dat raad ik iedereen aan.

## Prambanan

Aan het eind van de middag reden we naar **Prambanan**, aan de andere kant van de stad. Het is de grootste hindoetempel van Indonesië, gebouwd rond dezelfde tijd als Borobudur. Waar Borobudur breed en laag is, is Prambanan smal en hoog: zes spitse torens, de hoogste 47 meter, gewijd aan Shiva, Vishnu en Brahma.

Op de muren staan reliëfs van het Ramayana, het Indiase epos over prins Rama die zijn vrouw Sita redt uit de handen van de demonenkoning. In het droge seizoen wordt dat verhaal op een openluchtpodium met de tempels als decor opgevoerd als dans, met honderden dansers en een gamelanorkest. Wij keken het die avond, terwijl de tempels achter het podium verlicht werden. Bas viel halverwege bijna in slaap, maar dat lag aan het opstaan om half vier, niet aan de dans.

