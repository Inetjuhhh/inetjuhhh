Onze reis door Indonesië begon in **Yogyakarta**, of Jogja zoals iedereen het hier noemt. Het culturele hart van Java: een stad met een sultan die nog steeds in zijn paleis woont, batikwerkplaatsen in elke straat, en overal studenten op scooters. Mijn opa heeft als jongen op Java gewoond, en ik was nieuwsgierig naar het land waar hij altijd zo weemoedig over vertelde.

