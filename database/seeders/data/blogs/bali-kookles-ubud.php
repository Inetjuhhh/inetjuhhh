Als er één ding is dat ik van elke reis mee naar huis wil nemen, dan zijn het smaken. Een souvenirtje staat na een paar maanden toch stof te verzamelen op een plank, maar een gerecht kun je blijven maken. Daarom boek ik op bijna elke reis een kookles. Op Bali deed ik dat in Ubud, terwijl de rest van het gezin bij het zwembad lag.

## Naar de markt

De les begon om acht uur 's ochtends op de lokale markt van Ubud. Niet het toeristische deel met sarongs en houten beeldjes, maar het gedeelte erachter, waar de Balinezen zelf hun boodschappen doen. Onze kok, Ketut, liep met ons langs de kraampjes en liet ons ruiken aan dingen die ik nog nooit had gezien: verse kurkuma, galanga, *kencur* (een soort wilde gember), salamblaadjes en kleine, ronde Balinese limoenen.

Bij een van de kramen lagen kleine gevlochten bakjes van palmblad met bloemen, rijst en een wierookstokje erin. Dat zijn *canang sari*, offerandes die Balinezen meerdere keren per dag neerleggen voor de goden. Je ziet ze overal: op stoepen, in winkels, op het dashboard van taxi's. Ketut legde uit dat ze voor zijn familie net zo vanzelfsprekend zijn als tandenpoetsen.

## Een keuken tussen de rijstvelden

Na de markt reden we naar het huis van Ketut, een traditionele Balinese *compound* met een huistempel, een paar paviljoens en een open keuken met uitzicht op de rijstvelden. We waren met acht deelnemers en kregen elk een eigen werkplek met een vijzel, een snijplank en een berg ingrediënten.

De basis van bijna alle Balinese gerechten is **base genep**, een kruidenpasta van sjalotten, knoflook, chili, galanga, kurkuma, kencur, citroengras, kemirinoten, koriander, peper en garnalenpasta. Je stampt alles fijn in een stenen vijzel, en dat duurt veel langer dan je denkt. Na twintig minuten had ik een lamme arm, en volgens Ketut was mijn pasta nog steeds "a little bit rough". Thuis gebruik ik dus gewoon een staafmixer. Sorry Ketut.

## Wat we maakten

In ongeveer drie uur kookten we zes gerechten:

1. **Sate lilit**: gehakte vis met kokos en kruidenpasta, om stokjes van citroengras gedrukt en gegrild boven houtskool.
2. **Sambal matah**: een rauwe sambal van sjalot, citroengras en chili. Recept staat hieronder.
3. **Kare ayam**: Balinese kipcurry met kokosmelk.
4. **Pepes ikan**: vis met kruiden, gestoomd in een pakketje van bananenblad.
5. **Urap**: een salade van gekookte groenten met geraspte kokos.
6. **Dadar gulung**: groene pandanpannenkoekjes gevuld met kokos en palmsuiker.

Het leukste vond ik de sate lilit. Het "lilit" betekent omwikkelen, en dat is precies wat je doet: je kneedt het vismengsel met je handen om de stengel citroengras heen. Het mijne leek eerder op een worstje dat van een stokje viel, maar het smaakte geweldig.

## Mijn recept voor sambal matah

Dit is het gerecht dat ik thuis het vaakst maak. Het is fris, pittig en past bij bijna alles: gegrilde vis, kip, rijst of zelfs een gebakken eitje.

Ingrediënten (voor een klein bakje):

- 6 sjalotjes, in dunne ringen
- 2 stengels citroengras, alleen het zachte binnenste, heel fijn gesneden
- 3 tot 5 rode chilipepers, in dunne ringetjes
- 3 limoenblaadjes, heel fijn gesneden
- Sap van 1 limoen
- 1 theelepel garnalenpasta (trassi), geroosterd
- 3 eetlepels kokosolie
- Een flinke snuf zout

Doe de sjalot, het citroengras, de chili en de limoenblaadjes in een kom. Verkruimel de geroosterde trassi erover en voeg zout en limoensap toe. Kneed alles even met je handen, zodat de smaken vrijkomen. Verwarm de kokosolie tot hij net heet is en giet hem over het mengsel. Roer goed door. Klaar!

> Ketut zei: een goede sambal matah maak je met je handen, niet met een lepel. Want de liefde zit in je vingers.

