Ik heb lang nagedacht over hoe ik dit stuk moest beginnen. Varanasi laat zich niet makkelijk samenvatten. Het is een van de oudste steden ter wereld, de heiligste stad van het hindoeïsme, en een plek waar het gewone leven en de dood zo dicht naast elkaar bestaan dat je er stil van wordt.

## De nachttrein

Van Agra namen we de nachttrein naar Varanasi, in de **3AC-klasse**: een wagon met airco en drie bedden boven elkaar. Je krijgt lakens, een deken en een kussen. Het was verrassend comfortabel, al werd ik om vier uur 's nachts gewekt door een man die "chai, chai, chaaai" door het gangpad zong. De trein had vier uur vertraging, wat normaal schijnt te zijn.

## De ghats

Varanasi ligt aan de westoever van de Ganges, en de hele oever bestaat uit **ghats**: brede stenen trappen die afdalen naar het water. Er zijn er meer dan tachtig, elk met een eigen naam en functie. We sliepen in een guesthouse met een dakterras boven Munshi Ghat, en vanaf daar keken we elke ochtend naar het leven beneden ons.

Mannen die zich wassen en hun tanden poetsen. Vrouwen in kleurige sari's die bloemen en kaarsjes in het water zetten. Kinderen die vliegeren. Wasmannen die lakens tegen de stenen slaan. Sadhoes met lange baarden en oranje doeken. En koeien, overal koeien.

