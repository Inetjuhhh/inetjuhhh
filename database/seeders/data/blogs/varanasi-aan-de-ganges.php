## Manikarnika Ghat

Op **Manikarnika Ghat** branden dag en nacht de vuren. Hindoes geloven dat wie hier wordt gecremeerd en wiens as in de Ganges wordt verstrooid, verlost wordt uit de cyclus van wedergeboorte. Families dragen de lichamen in oranje en gouden doeken door de steegjes naar beneden, terwijl ze "Ram naam satya hai" zingen.

Je mag er als buitenstaander bij zijn, maar fotograferen is absoluut niet de bedoeling. We stonden er een half uur op een afstandje. Ik verwachtte dat het naargeestig zou zijn, maar het voelde vooral heel menselijk. Hier is de dood niet weggestopt achter een gordijn in een crematorium.

