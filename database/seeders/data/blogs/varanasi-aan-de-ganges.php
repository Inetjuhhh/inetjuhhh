## Ganga Aarti

Elke avond is er op **Dashashwamedh Ghat** de Ganga Aarti, een vuurceremonie voor de rivier. Zeven jonge priesters in zijden gewaden zwaaien met grote koperen olielampen, op het ritme van bellen en trommels. Er staan honderden mensen op de trappen en in bootjes op het water. Wij zaten in een boot en lieten na afloop een bladbakje met een kaarsje en goudsbloemen te water. Bas deed een wens, maar wilde niet vertellen welke.

## Varanasi in het kort

- **Hoe lang**: minstens drie nachten. Varanasi heeft tijd nodig.
- **Overnachten**: aan de ghats, het liefst met een dakterras.
- **Steegjes**: verdwalen in de smalle straatjes achter de ghats hoort erbij. Google Maps werkt er niet.
- **Lassi**: probeer de lassi bij Blue Lassi, met fruit en een dikke laag room.
