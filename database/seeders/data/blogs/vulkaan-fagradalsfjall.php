## Lava van dichtbij

Op de terugweg liepen we langs de rand van een lavastroom van een paar dagen oud. Het oppervlak was zwart en gestold, maar door de scheuren zag je het nog rood gloeien, en je voelde de hitte op je gezicht. Een parkwachter waarschuwde iedereen die er te dicht bij kwam: onder een korst van een paar centimeter kan nog vloeibare lava zitten.

