Op 19 maart 2021 opende de aarde zich in een dal met de naam **Geldingadalir**, bij de berg **Fagradalsfjall**, op het schiereiland Reykjanes. Het was de eerste uitbarsting op Reykjanes in bijna achthonderd jaar. Het werd al snel de "toeristenvulkaan" genoemd: de uitbarsting was niet explosief, er kwam geen as, en de lava stroomde rustig een dal in waar niemand woonde. Je kon er gewoon naartoe lopen.

Toen we in juni in IJsland aankwamen, was hij nog steeds actief.

## Mag dat wel, zwanger?

Ja, ik heb het aan de verloskundige gevraagd voor we vertrokken. Haar antwoord: niet te dichtbij, blijf uit de rook en neem je tijd. Bas had een uitgebreid plan gemaakt: we gingen 's avonds (minder mensen, en het gloeien zie je beter), we liepen de makkelijkste route, en we zouden omkeren als het niet ging. Ook de wind hielden we in de gaten: de gassen van een vulkaan, vooral zwaveldioxide, kunnen gevaarlijk zijn, en je moet altijd zorgen dat de wind van achteren komt.

## De wandeling

Vanaf de parkeerplaats aan de Suðurstrandarvegur is het een wandeling van een uur of anderhalf, via een pad dat de IJslandse reddingsbrigade speciaal had aangelegd. Het eerste stuk is vlak, daarna gaat het steil omhoog. Ik deed het in mijn eigen tempo, met veel pauzes, en een reep chocola als beloning op elk uitkijkpunt.

En dan kom je boven, en zie je het. Een dal vol zwarte, rokende lava, nog warm. Midden in het dal een kegel van een paar honderd meter hoog, de krater. En om de paar minuten spoot er een fontein van gloeiende lava uit, oranje en rood, tientallen meters de lucht in, met een geluid als een enorme golf die op het strand slaat.

