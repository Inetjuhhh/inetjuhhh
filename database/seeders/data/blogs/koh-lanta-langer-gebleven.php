Ons plan was simpel: vier nachten Koh Lanta, daarna door naar Koh Lipe voor de laatste week. Maar toen we na twee dagen in een hangmat lagen, met Sam spelend in het zand voor ons en een kokosnoot met een rietje in onze hand, keken we elkaar aan en wisten we het allebei. We gaan nergens heen. Het werden er acht.

## Waarom Koh Lanta?

Koh Lanta ligt in de Andamanse Zee, ten zuiden van Krabi. Het is groter en rustiger dan bekende eilanden als Koh Phi Phi of Phuket, met lange zandstranden, weinig grote hotels en een ontspannen sfeer. Er is geen echt uitgaansleven, en dat is voor ons als gezin juist perfect.

Vanuit Khao Sok reden we met een minibusje naar Krabi, en vandaar met nog een busje (inclusief twee korte overtochten met een autoveer) naar het eiland. Een lange reisdag, maar Sam vond de veerboten het hoogtepunt.

## De stranden

Koh Lanta heeft aan de westkust een hele rij stranden, elk met een eigen karakter:

- **Long Beach (Phra Ae)**: lang, breed en gezellig, met veel restaurantjes en bars.
- **Klong Khong**: wat ruiger en relaxter, met regenboogkleurige strandbars en rotsen waar je bij eb kunt zoeken naar krabbetjes.
- **Klong Nin**: rustig, met zacht zand en weinig golven. Ons favoriete strand, en waar we uiteindelijk bleven.
- **Bamboo Bay**: helemaal in het zuiden, klein en verscholen. Een van de mooiste stranden die ik in Thailand heb gezien.

Bij Klong Nin huurden we een simpele bungalow met een veranda, op dertig meter van het water. 's Ochtends ontbeten we met pannenkoekjes met banaan bij het restaurantje van een Thaise familie, en 's avonds keken we met z'n drieën naar de zonsondergang. Sam noemde de eigenares, mevrouw Pim, binnen een dag "oma Pim". Zij noemde hem "Sam-Sam".

## Old Town

Aan de oostkant van het eiland ligt **Lanta Old Town**, een oud vissersdorpje met houten huizen op palen boven het water. Hier woont een mix van Thaise, Chinese en Chao Leh-families (de zeezigeuners). Het is een fijne plek om een middag rond te wandelen, koffie te drinken en verse vis te eten bij een van de restaurantjes aan het water. Sam vond het geweldig om tussen de planken door naar de vissen te kijken.

