## De bruiloft

Bas en ik zouden op 13 juni trouwen. Een feest in een boerderij met honderd gasten, een band, een taart met vier verdiepingen. En daarna drie weken Japan. In maart ging alles dicht, en een voor een vielen de plannen om. De boerderij, de band, de vluchten.

We hebben lang getwijfeld: uitstellen of toch doen? Uiteindelijk besloten we: we trouwen gewoon. Op 4 juli stonden we op het stadhuis, met onze ouders, onze broers en zussen en twee getuigen. Tien mensen, op anderhalve meter. Mijn moeder had een taart gebakken (één verdieping, maar wel de lekkerste), en we hebben 's avonds in de tuin van mijn ouders gegeten onder lampionnetjes. Het grote feest doen we volgend jaar. Of het jaar daarna.

En eerlijk? Het was een van de mooiste dagen van mijn leven.

## Een huwelijksreis dichtbij

Japan zat er niet in. Maar Frankrijk ging in de zomer weer open, en we hadden een auto. Dus pakten we in augustus de koffers en reden we in zes uur naar **Normandië**. Twee weken, zonder vast plan, met een paar overnachtingen in chambres d'hôtes bij Franse families.

## Honfleur

Onze eerste stop was **Honfleur**, een vissersplaatsje aan de monding van de Seine. Rond de oude haven, de **Vieux Bassin**, staan hoge, smalle huizen met leien gevels, en in het water liggen zeilbootjes. Het is zo pittoresk dat het bijna een decor lijkt, en het was al in de negentiende eeuw de favoriete plek van schilders als Monet en Boudin.

We aten mosselen met frietjes op een terras aan de haven, met een fles cider van een boerderij in de buurt. Bas toostte op "mijn vrouw". Ik moet daar nog steeds aan wennen.

## Kaas, cider en appels

Normandië is het land van de koe en de appel. Overal zie je boomgaarden met daaronder grazende koeien, de typische Normandische koe met zijn bruine "bril" om de ogen.

