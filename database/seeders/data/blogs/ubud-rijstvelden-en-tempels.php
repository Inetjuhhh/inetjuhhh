## De rijstvelden

Rond Ubud liggen de beroemde **rijstterrassen**, die eruitzien alsof iemand de heuvels met een groene kam heeft gekamd. De bekendste zijn die van **Tegallalang**, maar die zijn inmiddels behoorlijk druk, met schommels voor Instagram en mensen die tol vragen om over een paadje te lopen.

Wij liepen liever de **Campuhan Ridge Walk** en het pad door de rijstvelden achter het dorpje Penestanan. Je loopt daar gewoon langs de boeren, die tot hun knieën in het water staan te planten. Het irrigatiesysteem, **subak**, is al meer dan duizend jaar oud: water wordt via tempels en kanaaltjes eerlijk over alle velden verdeeld. Het staat op de Unesco-lijst.

## Het Monkey Forest

In het **Sacred Monkey Forest**, midden in Ubud, wonen zo'n zevenhonderd makaken tussen tempels en enorme oude bomen. Het is prachtig, maar wees gewaarschuwd: de apen zijn brutaal. Eentje sprong op Bas' rug en trok zijn zonnebril van zijn hoofd. Hij heeft hem nooit meer teruggezien.

