## De smoothiebowl-kant van Ubud

En dan is er het andere Ubud. Sinds het boek Eat Pray Love trekt de stad mensen aan die zichzelf willen vinden, en dat zie je. Yoga op elke hoek, raw vegan cafés, cacaoceremonies, sound healing. Je kunt er om lachen, en dat deden we ook, maar eerlijk is eerlijk: de smoothiebowls zijn er fantastisch. Ik heb er in een week ongeveer twaalf gegeten.

Ik deed ook een yogales bij de **Yoga Barn**. Bas niet. Hij zat in de tussentijd met Ibu Made's man Wayan op de veranda kretek-sigaretten te ruilen voor stroopwafels.
