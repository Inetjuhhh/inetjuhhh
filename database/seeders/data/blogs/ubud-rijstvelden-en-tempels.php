Na twee nachten zonder slaap op Java kwamen we aan op Bali met maar één wens: een goed bed. In Ubud vonden we een homestay bij een Balinese familie, met een kamer op hun familiecompound. Elke ochtend legde de moeder, Ibu Made, kleine offerbakjes van palmblad met bloemen, rijst en wierook neer: op het altaar, bij de poort, op de motor en voor onze deur.

## Een eiland met een eigen religie

Bali is het enige hindoeïstische eiland van Indonesië, en het hindoeïsme hier is anders dan in India. Elk huis heeft een eigen tempel, elk dorp heeft er minstens drie, en er is bijna elke dag wel ergens een ceremonie. Je ziet processies van vrouwen die torens van fruit op hun hoofd dragen, mannen met witte hoofddoeken en gamelanorkesten die door de straten trekken.

## Tirta Empul

De mooiste tempel die we bezochten, was **Tirta Empul**, een watertempel uit de tiende eeuw. Er borrelt een heilige bron omhoog die via dertig spuiers in lange baden stroomt. Balinezen komen hier om zich ritueel te reinigen: ze lopen in een rij langs de spuiers en houden hun hoofd onder elke straal, met een gebed.

Je mag als bezoeker meedoen, in een sarong en met respect. Wij deden het. Het water was ijskoud, en de man naast me legde geduldig uit bij welke spuiers je wel en niet je hoofd onder houdt (twee zijn er voor de doden).

