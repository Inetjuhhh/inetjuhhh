De laatste week van onze reis brachten we door in het zuiden: eerst in de **Mekongdelta**, en daarna in **Ho Chi Minhstad**, of Saigon, zoals bijna iedereen het nog noemt.

## De Mekongdelta

De Mekong begint in Tibet en stroomt door China, Myanmar, Laos, Thailand en Cambodja voordat hij in het zuiden van Vietnam via negen grote armen (de "Negen Draken") in zee uitkomt. De delta is een enorm, plat, groen gebied vol rivieren en kanalen, rijstvelden, fruitboomgaarden en dorpjes op palen. Een derde van alle rijst van Vietnam komt hier vandaan.

We bleven drie nachten in **Can Tho**, de grootste stad van de delta, in een homestay aan een kanaal, tussen de mango- en longanbomen.

## De drijvende markt

De bekendste attractie van de delta is de drijvende markt van **Cai Rang**. Om vijf uur 's ochtends stapten we in een klein bootje, en voeren we in het eerste licht naar de markt. Daar liggen tientallen grote houten boten voor anker, volgeladen met watermeloenen, ananassen, pompoenen, kool of zoete aardappels. Aan een lange bamboestok bovenin de mast hangt een voorbeeld van wat ze verkopen, zodat je van ver kunt zien wat waar te koop is.

Tussen de grote boten varen kleine bootjes heen en weer, met vrouwen die koffie, noedelsoep en stokbroodjes verkopen aan de handelaren. Wij kochten een kop sterke Vietnamese ijskoffie met gecondenseerde melk, en een ananas die de verkoopster voor ons in een spiraal sneed, aan een stokje. Sam zat in zijn zwemvest op mijn schoot, en at de helft.

