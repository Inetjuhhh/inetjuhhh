## Saigon

Na de rust van de delta was **Saigon** een schok. Negen miljoen inwoners en acht miljoen scooters, hoge glazen kantoortorens naast Franse koloniale gebouwen, rooftopbars en straatkraampjes. Het is snel, druk, warm en fantastisch.

Met Sam deden we het rustig aan. We bezochten:

- **De Ben Thanh-markt**, de grote overdekte markt, met kraampjes vol fruit, stoffen, souvenirs en een hal met eetstalletjes.
- **Het postkantoor**, ontworpen door Gustave Eiffel (ja, die van de toren), met een prachtige hal en nog steeds een schrijver van brieven.
- **De Notre-Dame-kathedraal**, gebouwd van rode bakstenen die helemaal uit Marseille kwamen.
- **Het Oorlogsmuseum**, over de Vietnamoorlog. Daar ging alleen Bas naar binnen; ik bleef met Sam in de tuin, met de tanks en vliegtuigen. Het museum is indrukwekkend, maar met foto's die je je kind niet wilt laten zien.
- **De dierentuin en botanische tuin**, de oudste van Vietnam, met olifanten, giraffen, en heel veel schaduw. Sam vond het het beste uitje van de hele reis.

