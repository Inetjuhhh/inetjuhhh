Kampot is het soort plaats waar je aankomt voor twee nachten en een week later nog steeds bent. Een klein stadje aan een brede rivier, met verbleekte Franse koloniale huizen, een rotonde met een standbeeld van een durian, en een tempo dat alles om je heen een paar standen lager zet.

## De rivier

We sliepen in een bungalow aan de **Preaek Tuek Chhu**, de rivier een paar kilometer stroomopwaarts van het stadje. 's Ochtends sprongen we van de steiger in het water, 's middags lagen we in de hangmat, en bij zonsondergang huurden we een kajak en peddelden we langs de oevers vol palmbomen en vissersbootjes. Er vliegen 's avonds vuurvliegjes boven het water. Echt waar.

## Kampotpeper

Kampot is wereldberoemd om zijn peper. Al in de tijd van de Fransen werd hij geëxporteerd naar de beste restaurants van Parijs. Tijdens de Rode Khmer werden de plantages vernietigd, maar sinds de jaren negentig wordt er weer peper geteeld, op de oude manier, zonder kunstmest.

We fietsten naar **La Plantation**, een biologische peperplantage tussen de heuvels. Een meisje van de plantage liet ons de ranken zien: groene trosjes die rood worden als ze rijp zijn. Daarna proefden we de vier soorten: groen (vers, fris en een beetje citroenig), zwart, rood (zoet, bijna fruitig) en wit. We namen een tas vol mee naar huis. Ik gebruik hem nog steeds.

## Krab in Kep

Op een half uur rijden ligt **Kep**, een vroegere badplaats voor de Franse elite, waar je nog de skeletten ziet van oude villa's die door de jungle worden overwoekerd. Kep heeft één ding wat je niet mag missen: de **krabbenmarkt**.

Vissers komen met manden vol levende blauwe krabben uit zee lopen, die in houten kooien in het water worden bewaard. Je kiest ze uit, en ze worden in een van de restaurantjes aan het water bereid met... je raadt het al: verse groene Kampotpeper. Wij aten er een kilo met z'n tweeën. Met onze handen, met een rol wc-papier op tafel als servet, en met de zon die achter de zee zakte.

