## Bokor

Op onze laatste dag huurden we een scooter en reden we de berg op naar het **Bokor National Park**. De weg is nieuw en kronkelt door de jungle omhoog naar ruim duizend meter. Boven is het opeens koel en mistig. Er staat een spookachtig, verlaten casino uit de jaren twintig, een oude kerk en een enorm Boeddhabeeld dat uitkijkt over de zee.

