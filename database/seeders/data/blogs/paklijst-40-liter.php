Ik geef het eerlijk toe: ik was vroeger zo'n reiziger met een koffer van 23 kilo. Voor een week Spanje. Met vijf paar schoenen, drie boeken waarvan ik er nul las en een föhn, terwijl er in elk hotel een föhn hangt.

Tegenwoordig reis ik alleen nog met handbagage. Een rugzak van 40 liter, en dat is genoeg voor drie weken, en eerlijk gezegd ook voor drie maanden. In deze blog deel ik mijn paklijst en de trucjes die ervoor zorgen dat het allemaal past.

## Waarom zo licht?

- **Je bent flexibeler.** Even een trein pakken, een stuk lopen naar je hotel of een trap op: met een lichte rugzak denk je er niet over na.
- **Je bent sneller.** Geen wachten bij de bagageband en geen stress over kwijtgeraakte koffers.
- **Het scheelt geld.** Bij budgetmaatschappijen betaal je soms meer voor je koffer dan voor je ticket.
- **Je hebt minder keuzestress.** Ik vind het eigenlijk heerlijk om drie weken lang uit vijf shirts te kiezen.

## De rugzak

Ik gebruik een rugzak van 40 liter die precies binnen de handbagagematen van de meeste luchtvaartmaatschappijen valt. Belangrijk vind ik dat hij opent als een koffer (met een rits rondom), zodat je niet alles eruit hoeft te halen om iets onderin te pakken. En een goede heupband, want ook 8 kilo wordt na een uur zwaar.

## Kleding

Dit is de basis voor een warme bestemming. Voor koudere reizen wissel ik een paar items om voor warmere varianten.

- 5 shirts of tops, waarvan 1 met lange mouwen
- 1 dunne trui of vest
- 1 lange, luchtige broek
- 1 korte broek
- 1 jurk die ook als strandjurk werkt
- 1 legging (voor hiken, in het vliegtuig en als pyjama)
- 6 onderbroeken en 3 bh's, waarvan 1 sportbeha
- 4 paar sokken
- 1 bikini
- 1 dunne regenjas
- 1 grote sjaal (als deken, omslagdoek of om je schouders te bedekken in tempels)

Schoenen: ik draag mijn wandelschoenen of sneakers in het vliegtuig en neem verder alleen een paar sandalen mee. Meer is echt niet nodig.

Het geheim: **kies kleding in kleuren die allemaal met elkaar te combineren zijn**. Bij mij is dat zwart, wit, beige en olijfgroen. Dan heb je met tien items al tientallen outfits.

## Toiletspullen

Vloeistoffen mogen in handbagage alleen in flesjes van maximaal 100 milliliter, in een doorzichtig zakje van één liter. Daarom ben ik overgestapt op zoveel mogelijk vaste producten:

- Shampoobar en conditionerbar
- Vaste deodorant
- Tandenborstel en een klein tubetje tandpasta
- Zonnebrand (in een flesje van 100 ml, de rest koop ik ter plekke)
- Een kleine pot dagcrème
- Mascara en een lippenbalsem met kleur, meer make-up heb ik op reis niet nodig
- Een klein EHBO-setje met pleisters, paracetamol, ORS en een middeltje tegen diarree

## Elektronica

- Telefoon met oplader
- Universele wereldstekker met usb-poorten
- Powerbank
- E-reader (vol boeken, maar weegt bijna niks)
- Oortjes met noise cancelling
- Een kleine camera, want ik maak nog steeds graag foto's met een echte camera

## Handige extra's

- **Packing cubes**: zakjes waarin je je kleding rolt. Het houdt alles overzichtelijk en het scheelt echt ruimte.
- **Een opvouwbare tas** voor op de markt of het strand.
- **Een waterfles met filter**, handig in landen waar je het kraanwater niet kunt drinken.
- **Een klein slotje** voor kluisjes in hostels.
- **Waspoeder in een zakje**. Ik was elke paar dagen een paar dingen in de wastafel. Dat duurt vijf minuten en dan kun je met minder kleding af.

## Wat ik níét meer meeneem

- Een föhn
- Meer dan één paar extra schoenen
- "Voor het geval dat"-kleding
- Papieren reisgidsen (ik gebruik apps en blogs, zoals deze 😉)
- Een handdoek, behalve een kleine sneldrogende als ik in hostels slaap

> De vuistregel die ik altijd gebruik: leg alles wat je denkt nodig te hebben op bed, en haal er dan de helft weer af.

