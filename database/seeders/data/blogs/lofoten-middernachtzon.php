## De middernachtzon

Boven de poolcirkel gaat de zon in de zomer weken achter elkaar niet onder. Op de Lofoten van eind mei tot half juli. Om middernacht staat hij laag boven de horizon in het noorden, en kleurt alles goudgeel. Het is prachtig, en heel raar. Je hebt geen idee meer hoe laat het is. We aten soms om negen uur 's avonds, en gingen om één uur slapen.

Voor Sam was het minder fijn. Zijn ritme was na een paar dagen helemaal in de war. We hebben toen een paar dingen gedaan:

- **Het verduisteringsdoek** voor zijn stapelbed, en zilverfolie op de dakluiken (echt waar).
- **Zijn vaste ritueel**: badje (in een emmer), pyjama, flesje, boekje, liedje. Ook als het buiten zonnig is.
- **Veel buiten spelen** overdag, zodat hij moe was.

