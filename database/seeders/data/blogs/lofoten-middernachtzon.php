## De stranden

Wat ik niet had verwacht: de Lofoten hebben de mooiste stranden die ik ooit heb gezien. Wit zand, turquoise water, omringd door bergen. Het lijkt de Caraïben. Maar dan met water van twaalf graden.

Ons favoriete strand was **Haukland**, op het eiland Vestvågøy: een brede baai met fijn wit zand en ondiep water, ideaal voor een peuter. Sam rende er met een emmertje heen en weer naar zee. Bas en ik hebben gezwommen. Heel kort. Met veel geschreeuw.

