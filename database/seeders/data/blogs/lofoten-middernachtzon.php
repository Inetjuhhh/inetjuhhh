## Naar de Lofoten

De **Lofoten** zijn een eilandengroep voor de kust van Noord-Noorwegen, zo'n 150 kilometer boven de poolcirkel. Vanuit **Bodø** neem je de veerboot naar **Moskenes**, een tocht van drie uur over de open zee. Hij zit in de zomer vaak vol, dus we hadden hem vooraf gereserveerd. Het was ruw. Sam vond het geweldig ("Hobbel!"), ik iets minder.

## Reine en Hamnøy

Aan de zuidkant van de Lofoten liggen de bekendste dorpjes: **Reine** en **Hamnøy**. Hier staan de beroemde **rorbuer**: rode houten vissershuisjes op palen in het water, waar vissers vroeger in de winter verbleven tijdens het kabeljauwseizoen. Daarachter rijzen spitse, grillige bergen bijna loodrecht uit de zee op.

Op de rekken bij de haven hangt nog steeds de **stokvis** te drogen: kabeljauw die van februari tot juni in de wind droogt, zonder zout. Het ruikt er... aanwezig. Sam hield zijn neus dicht en zei "Bah!" Daarna wilde hij er toch even aan voelen.

