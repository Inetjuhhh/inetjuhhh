## Naar de canyon

Van Arequipa is het een rit van een uur of vier naar de **Colca Canyon**, over een hoogvlakte van bijna 4.900 meter. Onderweg zagen we wilde vicuña's, alpaca's en lama's, en vrouwen in prachtige geborduurde kleding met hoeden in de vorm van een omgekeerde taart. Op het hoogste punt stopte de bus, en ik voelde mijn hart bonzen na drie stappen. Onze gids gaf ons cocabladeren om op te kauwen. Dat helpt echt.

## Cruz del Cóndor

De volgende ochtend om acht uur stonden we bij **Cruz del Cóndor**, een uitzichtpunt aan de rand van de canyon. Onder ons ging het 1.200 meter recht naar beneden. En toen kwamen ze: de **Andescondors**, de grootste vliegende vogels ter wereld, met een spanwijdte van drie meter. Ze gebruiken de warme lucht die 's ochtends uit de canyon opstijgt, en cirkelen zonder één keer met hun vleugels te slaan langzaam omhoog. Sommigen vlogen zo dicht over ons heen dat we het geruis van hun veren hoorden.

Een condor kan zeventig jaar oud worden en zoekt maar één partner voor het leven. Bas fluisterde: "Net als wij." Ik vond het een beetje raar dat hij dat zei, maar ik dacht er verder niet over na. (Ook dit onthouden.)

