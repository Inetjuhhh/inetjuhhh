## De afdaling

Daarna liepen we de canyon in. Een smal, stoffig zigzagpad, ruim duizend meter naar beneden, naar de **Sangalle-oase** op de bodem: een groen plekje met palmbomen, bungalows en zwembaden met water uit een bron. Het was alsof we in een andere wereld waren beland. We sliepen in een hutje van riet, en 's avonds was het zo donker dat we de Melkweg zagen.

## De klim

En dan de volgende ochtend. Om half vijf, met hoofdlampjes, begonnen we aan de klim terug. 1.100 meter omhoog, op 3.300 meter hoogte. Het is zwaar. Echt zwaar. Ik moest om de vijftig meter stoppen om op adem te komen. Bas liep achter me en zei de hele tijd: "Je doet het goed, je doet het goed."

Na drie uur stonden we boven. Er stond een vrouw met een thermoskan cocathee. Ik heb nog nooit iets lekkerders gedronken.

