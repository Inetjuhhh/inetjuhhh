## Het verhaal

Sjah Jahan liet de Taj Mahal bouwen voor zijn vrouw Mumtaz Mahal, die in 1631 overleed bij de geboorte van hun veertiende kind. Er werkten twintigduizend mensen 22 jaar aan. Het marmer is ingelegd met edelstenen: lapis lazuli, jade, turkoois. Als je met een zaklamp op een bloem schijnt, licht die van binnenuit op.

Later werd Sjah Jahan door zijn eigen zoon afgezet en opgesloten in het fort van Agra. Vanuit zijn gevangenis kon hij de Taj Mahal zien. Hij ligt nu naast zijn vrouw begraven.

## Agra Fort

Na een ontbijt op een dakterras met uitzicht op de Taj gingen we naar **Agra Fort**, een enorm rood fort aan de rivier de Yamuna. Het is een stad op zich, met paleizen, binnenplaatsen en moskeeën. In de **Diwan-i-Khas**, de zaal voor privéaudiënties, staan prachtige marmeren zuilen met ingelegde bloemen. En vanuit de toren waar Sjah Jahan gevangen zat, zie je in de verte de Taj Mahal liggen.

