## Met de trein naar Agra

Vanuit Delhi namen we de **Gatimaan Express**, de snelste trein van India. In iets minder dan twee uur waren we in Agra, en we kregen onderweg ontbijt in een bakje: een omelet, twee sneetjes brood en een kopje chai. Indiase treinen boek je online via de website van de spoorwegen, of (makkelijker) via een app of je hotel. Doe dat ruim op tijd, ze zitten vaak vol.

## Zonsopkomst

De Taj Mahal gaat open bij zonsopkomst, en dat is ook het beste moment. Het is dan koel, nog niet zo druk, en het marmer verandert van kleur: eerst grijsblauw, dan roze, dan goud en uiteindelijk verblindend wit.

We stonden om kwart over vijf bij de oostpoort, en waren lang niet de eersten. Na de beveiligingscheck (geen eten, geen statieven, geen boeken) liepen we door de grote rode poort, en daar was hij. Bas zei niks. Ik ook niet. We stonden er gewoon een paar minuten naar te kijken.

