Vanuit Bangkok namen we de trein van 5.55 uur naar Aranyaprathet, het grensplaatsje aan Thaise kant. Zes uur later liepen we met onze rugzakken over de grens naar Poipet. Een beetje chaotisch: er zijn veel mannen die je willen "helpen" met je visum, voor een flinke meerprijs. Wij hadden ons e-visum vooraf online aangevraagd, en dat scheelde een hoop gedoe. Na een uur stonden we in Cambodja, en nog eens drie uur in een taxi later waren we in Siem Reap.

## Kosal

Bij ons guesthouse ontmoetten we **Kosal**, die ons de komende drie dagen met zijn tuktuk rond zou rijden. Kosal was 28, had een dochtertje van drie en leerde zichzelf Engels met YouTube-filmpjes. Hij wist alles van de tempels, en wist vooral wanneer je waar moest zijn om de grote groepen voor te blijven.

## Dag 1: Angkor Wat bij zonsopkomst

Om half vijf stond Kosal klaar. In het donker reden we naar **Angkor Wat**, het grootste religieuze bouwwerk ter wereld. Bij de vijver voor de tempel stonden al honderden mensen, allemaal met hun telefoon in de aanslag. Maar toen de lucht achter de vijf torens langzaam oranje en roze kleurde, werd het toch even stil.

Kosals tip: ga na de zonsopkomst niet meteen naar binnen, maar eerst ontbijten. Alle groepen lopen direct naar de tempel; als je een uur later gaat, heb je de gangen met de prachtige reliëfs bijna voor jezelf.

## Dag 2: Bayon en Ta Prohm

