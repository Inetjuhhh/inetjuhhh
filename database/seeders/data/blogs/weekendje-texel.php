## Lekker eten op Texel

- **Texels lamsvlees**: het eiland staat bekend om zijn schapen, en die proef je terug op veel menukaarten.
- **Texels Speciaalbier**: de lokale brouwerij in Oosterend. De Skuumkoppe is het bekendst.
- **Poffertjes** bij een van de kramen in De Koog.
- **Vis van de kotter** in Oudeschild, gewoon uit het vuistje.

## Tips voor Texel met kinderen

1. **Neem regenkleding mee**, ook al belooft de weersvoorspelling zon.
2. **Huur fietsen bij aankomst**, er zijn verhuurbedrijven in elk dorp. Reserveer in het hoogseizoen wel van tevoren.
3. **Ga naar het strand bij eb**. Dan zijn er de mooiste plasjes met krabbetjes.
4. **Plan niet te veel**. Het eiland nodigt uit om te luieren.

We gaan zeker terug. Misschien in de herfst, als het nog stiller is en je de vogels hoort trekken.
