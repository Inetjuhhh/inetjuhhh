Soms heb je geen verre reis nodig. Soms is twintig minuten met de boot genoeg. Met Hemelvaart pakten we de auto in, reden naar Den Helder en zaten we binnen het uur op het terras van een strandpaviljoen op Texel. Vier dagen, geen schermen, veel wind in ons haar en zand in werkelijk alles. Heerlijk.

## Overtocht en verblijf

De boot van TESO vaart elk uur vanaf Den Helder en de overtocht duurt maar twintig minuten. Voor de kinderen is dat al een avontuur op zich: ze renden meteen naar het bovendek om naar de meeuwen te kijken. Je hoeft niet te reserveren, maar op drukke dagen kan het druk zijn, dus kom op tijd.

We huurden een klein vakantiehuisje aan de rand van **De Koog**, op fietsafstand van het strand en het dorp. De Koog is het meest toeristische dorp van het eiland, met veel restaurantjes en winkeltjes. Wil je het rustiger, kijk dan in Den Hoorn of Oosterend.

## Dag 1: Ecomare

Onze eerste stop was **Ecomare**, een opvangcentrum voor zeehonden en bruinvissen met een natuurmuseum. De kinderen hadden het hier het allerleukst. We waren precies op tijd voor het voeren van de zeehonden en Noor heeft een kwartier met haar neus tegen het glas gestaan. In het museum kun je zien hoe het eiland is ontstaan en zijn er bakken waarin je zeesterren en krabben mag aanraken.

Tip: koop je kaartjes online, dat scheelt in de rij.

## Dag 2: op de fiets naar de vuurtoren

Texel is perfect om te fietsen. Er zijn meer dan 140 kilometer fietspaden en het eiland is helemaal vlak. Alleen de wind, die is er altijd. En die komt altijd van voren, daar ben ik inmiddels van overtuigd.

We huurden fietsen met een kinderzitje en een trailerbike voor Noor, en Siem fietste zelf. De route naar de **vuurtoren** bij De Cocksdorp is ongeveer twintig kilometer heen, door de duinen en langs de Slufter. Aan het eind van de rit kun je de vuurtoren beklimmen: 118 treden naar boven, met bovenaan een uitzicht over het hele eiland, de Waddenzee en, bij helder weer, Vlieland.

Onderweg stopten we bij **De Slufter**, een natuurgebied waar de zee bij hoogwater via een opening in de duinen naar binnen stroomt. Je kunt er wandelen over vlonders en je ziet er lepelaars, scholeksters en heel veel lamsoor. Siem wilde weten waarom het lamsoor heet als het een plant is. Daar had ik geen antwoord op.

## Dag 3: Oudeschild en een rondvaart

Op zondag gingen we naar **Oudeschild**, een klein havendorpje aan de Waddenkant. Hier staat het museum **Kaap Skil**, met een mooie collectie spullen die zijn opgedoken uit gezonken schepen uit de Gouden Eeuw. Het pronkstuk is een zijden jurk van zo'n 400 jaar oud, die nog bijna helemaal intact is. Zelfs Siem, die musea normaal "saai" vindt, was onder de indruk.

's Middags gingen we mee met een garnalenvisser. Het net werd uitgegooid en na een halfuur weer opgehaald, en we mochten helpen met het sorteren van de vangst: garnalen, krabbetjes, kleine visjes en een zeester. De garnalen werden meteen aan boord gekookt en we pelden ze zelf. Noor vond het "vies maar lekker".

## Dag 4: strand en patat

De laatste dag deden we niets. Nou ja, bijna niets. We liepen naar het strand bij paal 20, bouwden een zandkasteel dat steeds weer werd weggeslagen door de vloed, zochten schelpen en aten patat met mayonaise op een kleedje in de duinen. Het waaide hard, het zonnetje scheen af en toe, en de kinderen waren gelukkig.

