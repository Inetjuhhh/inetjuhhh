## Fika

Zweden is ook het land van de **fika**: een koffiepauze met iets lekkers, meestal halverwege de ochtend en de middag. Het is een heilig moment. In elke stad en elk dorp is wel een *konditori* (banketbakkerij) met kaneelbroodjes (*kanelbullar*), kardemombroodjes en de groene marsepeinen *prinsesstårta*. We deden elke dag fika. Soms twee keer. Sam leerde het woord "bulle" en zei het de rest van de reis bij elke bakkerij die we passeerden.

## Stockholm

We eindigden met drie dagen **Stockholm**, gebouwd op veertien eilanden waar het meer Mälaren in de Oostzee uitkomt. We zetten de camper op een camping buiten de stad, en namen de metro en de veerboten.

- **Gamla Stan**, de oude stad, met smalle straatjes, gele en oranje huizen en het koninklijk paleis.
- **Het Vasamuseum**: een oorlogsschip uit 1628, dat op zijn eerste reis na twintig minuten zonk, en in 1961 bijna volledig intact uit de haven werd gehaald. Sam riep "Boot! Grote boot!" en liep drie rondjes om het schip.
- **Skansen**, het oudste openluchtmuseum ter wereld, met oude Zweedse huizen, boerderijen én een dierentuin met Scandinavische dieren: elanden, beren, wolven, rendieren. Hier zag Sam zijn eerste eland van dichtbij. "Paard!" Ja, schat.
- **Junibacken**, het museum van de verhalen van Astrid Lindgren. Met een treintje rijd je door de wereld van Pippi Langkous, Ronja de Roversdochter en de Gebroeders Leeuwenhart. Sam was nog te klein om het te snappen, maar ik heb er als moeder van genoten.

