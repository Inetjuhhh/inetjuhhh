Vanaf de Lofoten reden we terug naar het zuiden, maar nu door Zweden. Een totaal ander landschap: geen bergen en fjorden, maar bossen. Eindeloze bossen van dennen en berken, met daartussen meren. Duizenden meren. En overal die typische **rode houten huisjes** met witte kozijnen.

## De Inlandsvägen

We reden een groot deel over de **Inlandsvägen**, een weg van ruim 1.000 kilometer door het binnenland van Zweden, van Gällivare in het noorden tot Kristinehamn in het zuiden. Er is bijna geen verkeer. Je rijdt urenlang door het bos, en ziet af en toe een dorpje, een rendier of een eland. Na de drukke, smalle wegen van Noorwegen was het heerlijk. Bas reed met één hand aan het stuur. Sam sliep. Ik las een boek. Voor het eerst in drie weken.

