## Een woestijn aan zee

Cabo de Gata is de droogste plek van Europa: het regent er maar een paar dagen per jaar. Het landschap is kaal, dor en ruig, met cactussen, agaves en dwergpalmen, en bergen van oud vulkanisch gesteente in rood, geel en zwart. Hier zijn spaghettiwesterns opgenomen, en scènes uit *Indiana Jones*. Je voelt je in Mexico, niet in Europa.

