## Snorkelen

Omdat de kust beschermd is, is het water hier heel schoon en zit het vol vis. Bij de rotsen van **San José** en **La Isleta del Moro** zagen we met een simpel snorkelsetje scholen zilveren vissen, zeebrasems en een octopus. Sam had een kindermasker, en lag op Bas' rug te snorkelen. Elke keer als er een vis voorbij kwam, kwam hij proestend boven: "Papa, VIS!"

## Een rustige week

Na twee drukke weken met steden, paleizen en witte dorpen was dit precies wat we nodig hadden. Een week strand, zandkastelen bouwen, ijsjes eten, en 's avonds gegrilde vis bij een van de restaurantjes aan de haven. Sam heeft deze week geleerd om zonder bandjes te drijven (met een zwembroek met drijvers erin). Ik heb drie boeken uitgelezen.

## Terugblik op Andalusië

Drie weken Spanje met een bijna-driejarige. Wat ik hiervan heb geleerd: Spanje is een van de makkelijkste landen om met een klein kind te reizen. Het is dichtbij, kinderen zijn overal welkom, het eten is goed en het ritme met een lange siësta is eigenlijk heel geschikt voor een kind dat nog een middagslaapje doet.

Volgend jaar gaan we weer verder weg. Naar een land waar het voor ons allemaal begon.
