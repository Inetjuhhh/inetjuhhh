## De stranden

- **Playa de los Genoveses**: een brede baai met fijn zand, ondiep water en duinen met pijnbomen. Perfect met kinderen. Je loopt er in twintig minuten vanaf San José naartoe, of je neemt de auto (in de zomer is de weg dicht en is er een pendelbus).
- **Playa de Mónsul**: een strand met een enorme zwarte lavarots in het midden, en een grote zandduin aan de zijkant. Sam is er een uur lang van de duin af gerold.
