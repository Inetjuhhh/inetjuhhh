## Lumphini Park en de varanen

Een van de leukste uitjes met een kind in Bangkok is gratis: **Lumphini Park**, het grote stadspark midden in het zakendistrict. Er is een meer met waterfietsen, een speeltuin, en 's avonds doen honderden mensen aan aerobics op harde muziek. Maar het allerleukste: in het park wonen honderden **varanen**, enorme hagedissen van soms twee meter lang. Ze liggen gewoon op het gras te zonnen, of zwemmen door de vijvers.

Sam was een beetje bang, en tegelijk heel nieuwsgierig. We hielden afstand (ze zijn niet gevaarlijk, maar wel wild), en Sam heeft ze allemaal geteld. Hij kwam tot "tweeëntwintig en nog veel". Daarna moest elke hagedis die hij de rest van de reis zag, een "Lumphini-draak" heten.

