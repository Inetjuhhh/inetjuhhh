## Met een kind in Bangkok: tips

- **Ga met de BTS Skytrain of de MRT**. Er zijn liften op bijna alle stations, en het is koel. De meeste taxi's hebben geen gordels achterin; neem Grab met een kinderzitje als je dat belangrijk vindt.
- **Plan maximaal één ding per dag**, en houd 's middags pauze in het zwembad. De hitte is voor kinderen echt zwaar.
- **SEA LIFE Bangkok Ocean World** en **Children's Discovery Museum** zijn goede plekken als het regent of als het te heet is.
- **Eten op straat** blijft heerlijk, ook met kinderen. Sam at elke dag *khao man gai* (kip met rijst) en mango sticky rice.

