Ons plan was simpel: vijf nachten Koh Lanta, daarna door naar Koh Lipe en Koh Phi Phi. Maar toen we na een paar dagen in een hangmat lagen, met de kinderen spelend in het zand voor ons en een kokosnoot met een rietje in onze hand, keken we elkaar aan en wisten we het allebei. We gaan nergens heen. Het werden er twaalf.

## Waarom Koh Lanta?

Koh Lanta ligt in de Andamanse Zee, ten zuiden van Krabi. Het is groter en rustiger dan bekende eilanden als Koh Phi Phi of Koh Samui, met lange zandstranden, weinig grote hotels en een ontspannen sfeer. Er is geen echt uitgaansleven en dat is voor ons als gezin juist perfect.

Je bereikt het eiland met een minivan vanaf Krabi Airport, inclusief twee korte overtochten met een autoveer. Reken op zo'n drie uur. In het hoogseizoen zijn er ook speedboten vanaf Phuket en Koh Phi Phi.

## De stranden

Koh Lanta heeft aan de westkust een hele rij stranden, elk met een eigen karakter:

- **Long Beach (Phra Ae)**: lang, breed en gezellig, met veel restaurantjes en bars. Goed voor de eerste dagen.
- **Klong Khong**: wat ruiger en relaxter, met de beroemde regenboogkleurige strandbars.
- **Klong Nin**: rustig, met zacht zand en weinig golven. Ons favoriete strand en waar we uiteindelijk bleven.
- **Bamboo Bay**: helemaal in het zuiden, klein en verscholen. Een van de mooiste stranden die ik in Thailand heb gezien.

Bij Klong Nin huurden we een simpele bungalow met een veranda, op dertig meter van het water. 's Ochtends ontbeten we met pannenkoekjes met banaan bij het restaurantje van een Thaise familie, en 's avonds keken we met z'n vieren naar de zonsondergang.

## Old Town

Aan de oostkant van het eiland ligt **Lanta Old Town**, een oud vissersdorpje met houten huizen op palen boven het water. Hier woont een mix van Thaise, Chinese en Chao Leh-families (de zeezigeuners). Het is een fijne plek om een middag rond te wandelen, koffie te drinken en verse vis te eten bij een van de restaurantjes aan het water. De kinderen vonden het geweldig om tussen de planken door naar de vissen te kijken.

## Snorkelen bij Koh Rok

Het hoogtepunt van ons verblijf was een dagtrip naar **Koh Rok**, twee kleine eilandjes in het Mu Ko Lanta Nationaal Park, zo'n uur varen met de speedboot. Het water was zo helder dat je vanaf de boot de koralen kon zien. Siem en Noor snorkelden voor het eerst echt in open zee, met een zwemvest en een masker, en ze zagen papegaaivissen, een schildpad en een hele school kleine zilveren visjes die om ze heen draaiden.

Noor kwam boven met een rood hoofd en riep door haar snorkel: "MAMA, NEMO!" Het was inderdaad een anemoonvisje. Ik denk dat ze het nooit meer vergeet.

> Er zijn momenten op reis die je wilt bevriezen. Dat moment, met Noor die proestend haar snorkel uit haar mond trok, was er een van.

## Wat we nog meer deden

- **Een kookles** bij Time for Lime, waar de kinderen zelf loempia's mochten rollen.
- **Bij de olifantenopvang**? Nee, bewust niet. Veel "sanctuaries" zijn helaas niet zo diervriendelijk als ze beweren. Doe goed je onderzoek als je dit wilt.
- **De Lanta Animal Welfare** bezoeken, een opvang voor zwerfhonden en -katten. Je kunt er een rondleiding krijgen en zelfs een hond uitlaten op het strand. De kinderen waren er niet weg te slaan.
- **Een scooter huren** en het eiland rondrijden. De weg naar het zuiden is heuvelachtig, met prachtige uitzichtpunten.
- **Het nationaal park** in het zuiden, met een vuurtoren, een kort junglepad en brutale apen. Hou je eten goed vast.

## Koh Lanta met kinderen: tips

1. **Ga in het droge seizoen**, van november tot april. In het regenseizoen zijn veel restaurants en resorts dicht en is de zee ruw.
2. **Kies een accommodatie aan een rustig strand**, zoals Klong Nin of Kantiang Bay. De golven zijn daar kalmer.
3. **Neem reef-safe zonnebrand mee**. Het koraal zal je dankbaar zijn, en het is in het nationaal park verplicht.
4. **Plan losjes**. Misschien wil je ook langer blijven.

