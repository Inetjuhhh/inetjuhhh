Je kunt in een uur van Hanoi naar Hué vliegen. Wij deden er veertien uur over. En ik zou het zo weer doen.

De Reunification Express, de spoorlijn die Hanoi met Ho Chi Minhstad verbindt, is al meer dan tachtig jaar de ruggengraat van Vietnam. De treinen zijn niet snel en ook niet heel luxe, maar je ziet het land op een manier die je vanuit een vliegtuig nooit ziet. Dorpjes, rijstvelden, waterbuffels, kerkhoven midden tussen de akkers en, als je geluk hebt, een zonsopkomst boven zee.

## Tickets boeken

We boekten onze tickets een week van tevoren via de officiële website van de Vietnamese spoorwegen. Dat ging prima, al is de site niet de meest gebruiksvriendelijke. Er zijn ook tussenpersonen die tickets verkopen met een kleine toeslag, wat handig kan zijn als je op het laatste moment boekt.

Je kunt kiezen uit verschillende klassen:

- **Hard seat**: houten bankjes. Alleen voor de echte doorzetters.
- **Soft seat**: een gewone stoel met airco. Prima voor korte stukken overdag.
- **Hard sleeper**: een coupé met zes bedden, drie hoog aan elke kant.
- **Soft sleeper**: een coupé met vier bedden en een deur die dicht kan.

Wij kozen een soft sleeper in de SE1, die om 22.00 uur vertrekt en rond 12.00 uur de volgende dag in Hué aankomt. Een bed kostte ongeveer 1.100.000 dong per persoon, zo'n veertig euro.

## De reis zelf

Station Hanoi is chaotisch op de manier waarop alles in Hanoi chaotisch is: veel lawaai, veel mensen, maar eigenlijk werkt alles prima. Een medewerker keek naar onze tickets, wees naar een wagon en daar gingen we.

Onze coupé deelden we met een Vietnamese oma en haar kleindochter van een jaar of twintig. De oma sprak geen woord Engels, maar binnen tien minuten had ze ons een zak lychees in handen gedrukt en wilde ze precies weten waar we vandaan kwamen. De kleindochter vertaalde. Toen we uitlegden dat Nederland onder zeeniveau ligt, keek oma ons aan alsof we haar in de maling namen.

Slapen in de trein is wennen. Het bed is smal, de trein schokt en remt op de raarste momenten, en ergens rond drie uur 's nachts liep er iemand door de gang die heel hard noedelsoep aanbood. Toch heb ik verrassend goed geslapen. Neem wel oordopjes en een oogmasker mee, want het licht in de gang blijft de hele nacht aan.

## Het mooiste stuk

Het beste moment kwam de volgende ochtend. Na Đồng Hới begint het landschap te veranderen. De rijstvelden worden groener, je ziet de bergen dichterbij komen en af en toe glinstert de zee door de bomen. Ik zat met een kop oploskoffie uit het restauratierijtuig bij het raam en kon mijn ogen er niet van af houden.

> Er is iets heel rustgevends aan reizen in een tempo waarin je de wereld nog echt voorbij ziet komen.

## Hué: de oude keizerstad

Hué was van 1802 tot 1945 de hoofdstad van Vietnam en de stad ademt nog steeds die geschiedenis. We bleven drie nachten en dat was precies goed.

De **Keizerlijke Citadel** is enorm. Een groot deel is in de oorlog verwoest, maar er wordt al jaren gerestaureerd en de herbouwde paleizen en poorten zijn prachtig. Ga vroeg in de ochtend, want na tienen wordt het heet en druk. Trek ook een hele middag uit voor de **keizerlijke graftomben** buiten de stad. De tombe van Tự Đức ligt in een rustig park met een vijver vol lotusbloemen, die van Khải Định is juist overdadig, met muren vol mozaïek van porselein en glas.

En het eten! Hué heeft een eigen keuken die veel pittiger is dan in de rest van het land. Probeer zeker:

- **Bún bò Huế**: een pittige noedelsoep met rundvlees en citroengras. Veel lekkerder dan pho, als je het mij vraagt.
- **Bánh khoái**: een krokante pannenkoek met garnalen en een dikke pindasaus.
- **Bánh bèo**: kleine gestoomde rijstkoekjes met gedroogde garnalen, die je met een lepeltje uit schaaltjes eet.

## Verder naar Hội An

Van Hué naar Hội An kun je ook de trein nemen, maar wij kozen voor een **easy rider**: een lokale motorrijder die je achterop meeneemt over de beroemde Hải Vân-pas. Onze bagage ging met een busje mee. De pas kronkelt langs de kust met uitzichten die echt niet normaal zijn, en onderweg stopten we bij een verlaten bunker, een strand en een klein restaurantje waar we de meest verse vis ooit aten. Maar dat verhaal bewaar ik voor de volgende blog.
