## Avonden in Pai

Elke avond is er een avondmarkt in de hoofdstraat. We aten er gegrilde maïs, roti met banaan en Nutella, en kleine zakjes met gebakken kwarteleitjes. Daarna zaten we in een barretje met kussens op de grond naar livemuziek te luisteren. Bas speelde mee op een djembé die hij van iemand had geleend. Hij was er minder goed in dan in curry maken.

Op de laatste avond zaten we op de rand van de canyon en keken we hoe de zon achter de bergen zakte. Bas zei dat hij wel in Pai zou kunnen wonen. Ik zei dat hij dat ook over Chiang Mai had gezegd. Hij zei dat dat ook waar was.

