## Mijn eerste keer op een scooter

In Pai huurt iedereen een scooter, want alles ligt net te ver om te lopen. Bas had ervaring, ik niet. Na een half uur oefenen op een stil weggetje (en één keer bijna de berm in) durfde ik het aan. We reden naar:

- **Pai Canyon**: smalle zandstenen richels met diepe kloven aan weerszijden. Prachtig bij zonsondergang, maar niks voor mensen met hoogtevrees. Ik bleef op het brede stuk.
- **De Memorial Bridge**: een oude ijzeren brug uit de Tweede Wereldoorlog, gebouwd door Japanse soldaten.
- **Lod Cave**: een grot waar je met een bamboevlot doorheen vaart, met een gids met een gaslamp. Er hangen duizenden vleermuizen.
- **De warmwaterbronnen** van Tha Pai, waar we in het warme water lagen tot onze vingers rimpelig waren.

