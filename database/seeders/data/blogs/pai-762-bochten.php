Er zijn T-shirts te koop met de tekst "I survived the road to Pai". Ik dacht eerst dat het een grapje was. Na drie uur in een minibusje dat met volle snelheid de bergen in slingerde, wilde ik er een kopen en hem nooit meer uittrekken.

## De weg

Pai ligt zo'n 130 kilometer ten noordwesten van Chiang Mai, maar de weg erheen heeft 762 bochten. De minibusjes doen er drie uur over en de chauffeurs rijden alsof ze een rally winnen. Halverwege stopten we bij een tankstation waar ik bleek op een bankje zat, terwijl Bas vrolijk een zak chips at.

Mijn tip: neem een reisziektepil een half uur van tevoren, ga voorin zitten als het kan en kijk naar de horizon. En eet geen chips.

## Het dorp

Pai zelf is een klein dorp in een groene vallei, vol guesthouses, koffietentjes en mensen met harembroeken en dreadlocks. Er hangt een sfeer van "we hebben alle tijd", en die steekt aan. We hadden drie nachten gepland en bleven er zes.

We sliepen in een bamboebungalow aan de rand van het dorp, met een hangmat op de veranda en uitzicht op de rijstvelden. 's Ochtends hing de mist laag over de velden en hoorde je alleen hanen en het geklater van het riviertje.

