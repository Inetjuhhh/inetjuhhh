## Vatnajökull

Na Vík wordt het landschap leger. Je rijdt urenlang door zwarte vlaktes van zand en lava, en dan zie je hem: **Vatnajökull**, de grootste gletsjer van Europa. Een enorme witte ijskap, waarvan de tongen tot vlak bij de weg komen. We liepen een stukje bij de gletsjertong van **Svínafellsjökull**, een ijsmassa met diepe blauwe spleten.

## Jökulsárlón

En dan, het hoogtepunt: **Jökulsárlón**, de gletsjerlagune. Hier breken blokken ijs af van de gletsjer, en drijven ze langzaam door de lagune naar zee. Sommige zijn zo groot als een huis, andere hebben het formaat van een koelkast. Ze zijn wit, doorschijnend, of diepblauw, en sommige hebben zwarte strepen van vulkanische as.

Tussen de ijsbergen zwemmen zeehonden. Ze liggen op de schotsen te zonnen, of steken nieuwsgierig hun kop boven water. Een van hen bleef een tijdje naar ons kijken. Ik zweer dat hij lachte.

