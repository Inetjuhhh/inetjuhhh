De **Ringweg**, de weg die helemaal om IJsland heen loopt, is in het zuiden misschien wel het mooiste stuk weg van Europa. Aan de ene kant de zee, aan de andere kant groene kliffen met watervallen, en daarboven gletsjers. Wij reden in vijf dagen van Hella tot Jökulsárlón en terug, met elke dag maar een paar uur in de auto.

## Seljalandsfoss

De eerste waterval waar je langs komt, is meteen een van de mooiste: **Seljalandsfoss**, zestig meter hoog. Het bijzondere is dat je er via een pad achterlangs kunt lopen. Je wordt wel nat, dus doe een regenjas aan. Bas heeft het gedaan. Ik heb, met een buik van 29 weken en een glad pad, op een afstandje toegekeken.

Een paar honderd meter verder ligt een verstopte waterval: **Gljúfrabúi**, in een kloof. Je moet over stenen door een beekje lopen om hem te zien, en dan sta je opeens in een grot met een waterval die van boven naar beneden valt.

## Skógafoss

**Skógafoss** is breder, krachtiger en indrukwekkender: een gordijn van water van 25 meter breed en 60 meter hoog. Je kunt er heel dichtbij komen. Volgens een legende verborg de eerste Viking die zich hier vestigde een kist met goud achter de waterval. Rechts van de waterval loopt een trap met 527 treden naar boven. Die heb ik overgeslagen.

