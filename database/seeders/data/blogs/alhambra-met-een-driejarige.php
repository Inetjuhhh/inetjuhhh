## Het Generalife

Na de paleizen liepen we naar het **Generalife**, de zomertuinen van de sultans, op een heuvel ernaast. Hier mag een kind lekker rennen: tussen de rozen, de cipressen en de fonteinen. In de **Patio de la Acequia** spuiten aan beide kanten van een lange vijver kleine fonteintjes in een boog over het water. Sam heeft er zijn handen een half uur onder gehouden.

## Truc 3: houd een pauze

Halverwege zijn we gewoon op een bankje in de schaduw gaan zitten, met een broodje, een appel en een filmpje op de telefoon. Twintig minuten. Daarna konden we er allemaal weer tegenaan.

## Het Albaicín

's Middags, na de siësta, liepen we door het **Albaicín**, de oude Moorse wijk tegenover het Alhambra. Smalle, steile straatjes met witte huizen, bloempotten aan de gevels en verborgen tuinen achter hoge muren. Kinderwagen vergeten, draagzak mee.

Bij zonsondergang gingen we naar het **Mirador de San Nicolás**, een plein met het beroemdste uitzicht op het Alhambra. Het paleis kleurt rood in het laatste licht (Alhambra betekent "de rode"), met de witte bergen erachter. Er zaten honderden mensen, er speelde iemand flamencogitaar, en Sam danste. Hij kreeg applaus.

