Het **Alhambra** ligt op een heuvel boven **Granada**, met de besneeuwde toppen van de Sierra Nevada op de achtergrond. Het was het paleis en de vesting van de **Nasriden**, de laatste islamitische dynastie in Spanje, tot 1492. Met zijn zalen vol stucwerk, tegels, bogen en fonteinen is het een van de mooiste gebouwen ter wereld.

En het is ook enorm. Je loopt er zo vier uur rond. Met een peuter van bijna drie is dat een uitdaging. Hier is hoe we het deden.

## Truc 1: koop ruim op tijd tickets

Het Alhambra is elke dag uitverkocht, vaak weken van tevoren. Er mogen maar een beperkt aantal mensen per dag in, en in de **Nasridische paleizen** krijg je een tijdslot van een half uur. Kom je te laat, dan mag je er niet meer in. Wij boekten zes weken van tevoren, voor een tijdslot om negen uur 's ochtends: Sam is dan nog fris, en het is nog niet zo warm.

## Truc 2: maak er een verhaal van

We vertelden Sam dat we naar een **echt sultanspaleis** gingen, waar vroeger een sultan woonde met heel veel prinsen en prinsessen. En dat er ergens in het paleis twaalf leeuwen waren, en dat hij ze moest vinden. Die hele ochtend was hij op zoek naar leeuwen. Elke tegel, elke zuil, elke fontein werd geïnspecteerd.

## De paleizen

Het eerste deel van de **Nasridische paleizen** is het **Mexuar**, de zaal waar recht werd gesproken. Daarna de **Hof van de Mirten**, met een lange vijver waarin de toren van Comares weerspiegelt, en de **Zaal van de Ambassadeurs**, met een koepel van houtsnijwerk met achtduizend stukjes cederhout die de zeven hemelen voorstellen.

En dan, eindelijk: de **Hof van de Leeuwen**. Een binnenplaats met 124 slanke marmeren zuilen, en in het midden een fontein gedragen door **twaalf stenen leeuwen**. Sam bleef staan, keek, en begon hardop te tellen. "Een, twee, drie, vier, ... veel!" Hij vond ze. Het was het hoogtepunt van zijn dag. En van de mijne.

