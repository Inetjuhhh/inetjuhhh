## Kanoën en zwemmen

Overdag kanoden we door de baaien, langs de rotswanden met lianen die tot in het water hingen. Sam zat voorin en "peddelde" mee met een kinderpeddel. We zagen een groep **makaken** die van boom tot boom sprongen, een **neushoornvogel** met een enorme gele snavel die over ons heen vloog, en een slang in het water (een ongevaarlijke waterslang, zei de gids, maar ik heb toch een stukje harder gepeddeld).

Het water van het meer is warm, groen en helder. We zwommen urenlang. 's Avonds lagen we op het terras naar de sterren en de vuurvliegjes te kijken.

## De gibbons

De mooiste wekker die we ooit hebben gehad: om zes uur 's ochtends begonnen de **gibbons** te roepen. Een lang, hoog, golvend geluid dat over het meer echode, van de ene groep naar de andere. Sam werd wakker, ging rechtop zitten en zei: "Wie zingt er?"

De gids nam ons mee op een vroege boottocht, en we zagen ze: een familie van vier witte gibbons, hoog in een boom aan de rand van het water, slingerend aan hun lange armen.

## De grot

Op de tweede dag maakten we een junglewandeling naar de **Coral Cave**, een grot met prachtige druipstenen die eruitzien als koraal. Het pad is ongeveer een half uur door de jungle, met boomwortels en modder. Sam liep het grootste deel zelf, en de rest op Bas' schouders. In de grot hingen honderden kleine vleermuizen aan het plafond. Sam fluisterde de hele tijd, "om ze niet wakker te maken".

