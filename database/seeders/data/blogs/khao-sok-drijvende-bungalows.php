## Is het geschikt voor kinderen?

Ja, als je je kind goed in de gaten houdt en een beetje avontuurlijk bent. Het is eenvoudig: geen airco, een koude douche, een toilet dat je doortrekt met een emmer. Het eten is simpel maar lekker (veel rijst, curry, vis uit het meer en fruit). Maar het is ook een van de bijzonderste plekken waar we ooit hebben geslapen.

Sam vraagt nog steeds of we teruggaan naar "het huisje op het water".
