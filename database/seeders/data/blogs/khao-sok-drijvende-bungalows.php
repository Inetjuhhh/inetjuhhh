Tussen de Golf van Thailand en de Andamanse Zee ligt het **Nationaal Park Khao Sok**: een van de oudste regenwouden ter wereld, ouder dan de Amazone. Er leven tijgers (al zie je die nooit), olifanten, gibbons, neushoornvogels en de **Rafflesia**, de grootste bloem ter wereld, die naar rottend vlees ruikt.

In het midden van het park ligt het **Cheow Lan-meer**, een stuwmeer van 165 vierkante kilometer, met kalksteenrotsen die tot bijna duizend meter hoog uit het water steken. Daar sliepen we twee nachten, op een drijvend vlot.

## De bungalows

Vanaf de dam van **Ratchaprapha** voer je met een longtailboot een uur over het meer, tussen de rotsen door, naar een van de **raft houses**: rijen eenvoudige bamboe bungalows op vlotten, aan elkaar vastgemaakt, in een baai midden in de jungle. Er is geen weg, nauwelijks bereik, en stroom alleen 's avonds een paar uur.

Ons huisje had een matras op de vloer, een klamboe, en een terrasje waar je zo vanaf je bed het meer in kon springen. Sam vond het het mooiste hotel ooit. We hadden hem een zwemvest gegeven dat hij de hele dag aanhield, ook in bed (bijna).

