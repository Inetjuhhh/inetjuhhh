## Koh Nang Yuan

Op onze laatste dag namen we een longtailboot naar **Koh Nang Yuan**: drie eilandjes die met elkaar verbonden zijn door zandbanken. Je betaalt een kleine toegangsprijs en mag geen plastic flessen meenemen. We klommen naar het uitzichtpunt en keken neer op het witte zand en het turquoise water aan twee kanten. Het is de bekendste ansichtkaart van Thailand, en terecht.

