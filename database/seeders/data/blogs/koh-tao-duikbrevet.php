Koh Tao is een klein eiland in de Golf van Thailand, en het is wereldberoemd om één ding: het is een van de goedkoopste plekken ter wereld om te leren duiken. Bijna iedereen die er aankomt, gaat er een cursus doen. Wij dus ook.

## Hoe je er komt

Vanuit het noorden namen we de nachttrein naar Chumphon, en vandaar de catamaran naar Koh Tao. De combinatie trein plus boot kun je in één keer boeken en kostte ons ongeveer 1.000 baht per persoon. De overtocht duurde anderhalf uur, en de zee was gelukkig rustig.

## De Open Water-cursus

We kozen een kleine duikschool aan **Sairee Beach**, het langste strand van het eiland. De Open Water Diver-cursus duurt vier dagen en kostte toen 9.000 baht per persoon (ongeveer 240 euro), inclusief een kamer.

- **Dag 1**: theorie en filmpjes. Heel veel filmpjes.
- **Dag 2**: oefenen in het zwembad. Masker leegblazen, je ademautomaat terugvinden, zwemmen zonder masker. Het voelt allemaal heel onnatuurlijk.
- **Dag 3 en 4**: vier duiken in zee, de laatste tot achttien meter diep.

Op de tweede zeeduik ging het bij mij mis. Op twaalf meter moest ik mijn masker afzetten en weer opzetten, en op het moment dat er water in mijn neus kwam, wilde mijn hele lichaam naar boven. Onze instructeur Jess pakte rustig mijn handen, keek me aan en deed langzaam voor: inademen, uitademen. Na een halve minuut, die voelde als tien, lukte het. Bas zag het allemaal gebeuren en stak trots zijn duim op.

