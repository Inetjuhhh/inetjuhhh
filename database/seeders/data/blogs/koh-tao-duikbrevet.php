## Wat we zagen

Na het examen (geslaagd, allebei!) maakten we nog twee "fun dives". Bij **Japanese Gardens**, vlak bij het eilandje Koh Nang Yuan, zagen we koralen in alle kleuren, kogelvissen, een murene die zijn kop uit een spleet stak en, het allermooiste, een **karetschildpad** die rustig langs ons heen zwom alsof wij er niet waren. Onder water hoor je alleen je eigen ademhaling. Ik had het nooit zo verwacht, maar het is de meest vredige plek die ik ken.

