## Een maand Thailand: terugblik

Vier weken, zes bedden, twee nachttreinen, één duikbrevet en ontelbaar veel pad thai. Morgen vliegen we vanaf Bangkok naar huis. Het eerste wat Bas zei toen we gisteravond op het strand zaten: "Waar gaan we volgend jaar heen?"

