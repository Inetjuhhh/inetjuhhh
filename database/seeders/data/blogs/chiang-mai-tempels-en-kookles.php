De nachttrein van Bangkok naar Chiang Mai is een avontuur op zich. Om zes uur 's avonds vertrok hij van Hua Lamphong, en een paar uur later kwam er een conducteur langs die met een paar handige bewegingen onze zitbank omtoverde tot een stapelbed, met schone lakens en een gordijntje. Bas sliep binnen tien minuten. Ik lag nog een uur door het raampje naar voorbijschietende dorpjes te kijken.

Om half acht 's ochtends rolden we Chiang Mai binnen. Het was er heerlijk koel, "maar" 22 graden.

## De oude stad

Het oude centrum van Chiang Mai is een vierkant, omringd door een gracht en restanten van de oude stadsmuur. Binnen die muren staan meer dan dertig tempels. We huurden een fiets bij ons guesthouse en reden er gewoon een beetje doorheen, zonder plan.

Onze favoriet was **Wat Chedi Luang**, met een enorme half ingestorte chedi uit de vijftiende eeuw. Er staan olifanten van steen langs de zijkanten, en monniken in oranje gewaden lopen er tussendoor. Op het terrein kun je meedoen aan een "monk chat": een uurtje praten met jonge monniken die hun Engels willen oefenen. We spraken met Pong, negentien jaar, die ons vroeg of het waar was dat er in Nederland meer fietsen dan mensen zijn.

