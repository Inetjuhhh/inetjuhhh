## De nachtmarkten

Op zondagavond verandert de hoofdstraat van de oude stad in de **Sunday Walking Street**: kilometers kraampjes met handwerk, zeepjes in de vorm van bloemen, en eten, eten, eten. We aten er onze eerste **khao soi**, het gerecht van Noord-Thailand: een romige kokoscurry met eiernoedels, kip en een handje gefrituurde noedels erbovenop. Daarna nog een, want we konden niet kiezen tussen kip en rund.

