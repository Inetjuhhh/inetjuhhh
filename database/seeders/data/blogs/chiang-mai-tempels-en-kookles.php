## Doi Suthep

Op de heuvel boven de stad ligt **Wat Phra That Doi Suthep**, de bekendste tempel van het noorden. Je bereikt hem met een rode songthaew (een pick-up met bankjes achterin), en daarna beklim je 306 treden langs twee lange slangen van glasmozaïek. Boven staat een gouden chedi die in de middagzon bijna pijn doet aan je ogen. En op een heldere dag kijk je uit over heel Chiang Mai.

## Kookles

Het hoogtepunt van onze week was een kookles bij een kookschool op een boerderijtje buiten de stad. We begonnen op de markt, waar onze kok Noi ons uitlegde wat galangal is (een soort pittige gember), hoe je kaffirlimoenblaadjes herkent en waarom er zeven soorten aubergines bestaan. Daarna kookten we vijf gerechten: tom kha kai, pad thai, groene curry (met zelfgestampte currypasta!), loempia's en mango sticky rice.

Bas, die thuis nauwelijks een ei kan bakken, bleek een natuurtalent. Zijn currypasta was beter dan de mijne, en dat zei Noi ook nog eens hardop.

