## Het feest

's Avonds kregen we een poncho en een geborduurde rok aan, en gingen we met de hele familie naar het dorpshuis. Daar was een "feest" voor de gasten: een bandje met fluiten en gitaren, en dansen. Het is een beetje opgezet voor de toeristen, maar de families dansen gewoon mee, en Juan liet me niet los tot ik buiten adem was. Op 3.900 meter hoogte is dansen topsport.

Daarna liepen we in het donker terug, onder de helderste sterrenhemel die ik ooit heb gezien.

## Taquile

De volgende ochtend namen we afscheid van Mamá Rosa (met een knuffel die ik niet snel vergeet) en voeren we naar **Taquile**. Dit eiland is beroemd om zijn textiel: hier breien de mannen, niet de vrouwen. Aan de kleur en de vorm van hun mutsen kun je zien of iemand getrouwd is of niet. Vrijgezellen dragen een wit puntje, getrouwde mannen een helemaal rode muts.

