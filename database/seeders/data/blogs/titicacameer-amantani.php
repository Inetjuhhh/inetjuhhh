Het **Titicacameer** ligt op 3.812 meter hoogte op de grens van Peru en Bolivia. Het is zo groot dat het eruitziet als een zee: helder, diepblauw water, met aan de horizon de besneeuwde toppen van de Boliviaanse Andes. Volgens de Inca's is hier de wereld begonnen: de zonnegod Inti zou zijn kinderen hier uit het water hebben laten opstijgen.

Vanuit **Puno** maakten we een tweedaagse boottocht over het meer.

## De drijvende eilanden van de Uros

Eerste stop: de **Uros-eilanden**. Ze zijn helemaal gemaakt van *totora*, een rietsoort die in het meer groeit. Het volk van de Uros woont al eeuwen op deze zelfgebouwde eilanden. Ze vlechten dikke blokken van de wortels van het riet, en stapelen daar laag na laag riet op. Elke paar weken moet er een nieuwe laag bij, omdat het onderste riet wegrot. Het voelt als lopen op een waterbed.

Eerlijk is eerlijk: het is erg toeristisch geworden. Je wordt verwelkomd met een liedje, krijgt een demonstratie en wordt daarna vriendelijk maar dringend naar de handwerkkraampjes geleid. Maar het blijft bijzonder om te zien hoe mensen hier leven.

## Amantaní

Na nog drie uur varen kwamen we aan op **Amantaní**, een eiland waar zo'n vierduizend mensen wonen, verdeeld over tien dorpjes. Er zijn geen auto's, geen hotels en (in 2019) nauwelijks elektriciteit. De families op het eiland ontvangen om de beurt reizigers in hun huis. Het geld gaat rechtstreeks naar de gemeenschap.

Wij sliepen bij **Mamá Rosa** en haar man Juan, met hun drie kinderen. Hun huis was van leem, met een binnenplaatsje met een paar kippen en een cavia (die, vertelde Juan grijnzend, misschien ooit het avondeten zou worden). Ons kamertje had een bed met vijf dikke wollen dekens. Die waren nodig: 's nachts vroor het.

Mamá Rosa kookte op een houtvuur in een klein keukentje: quinoasoep, gekookte aardappels (er zijn in Peru meer dan drieduizend soorten) en een gebakken kaasje. Ze spreekt Quechua en een beetje Spaans; wij spreken een beetje Spaans en geen Quechua. Toch hebben we de hele avond gekletst en gelachen, vooral met de kinderen, die Bas leerden hoe je met een touwtje een tol laat draaien.

