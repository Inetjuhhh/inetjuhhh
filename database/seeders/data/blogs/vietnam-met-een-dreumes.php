## Jetlag

Zes uur tijdsverschil. De eerste twee nachten was Sam om drie uur 's nachts klaarwakker, en wilde spelen. We liepen dan maar met hem in de draagzak door de gang van het hotel. Op dag drie was het over. Het advies dat we kregen en dat echt werkte: zo veel mogelijk naar buiten, in het daglicht, en de dutjes laten passen bij de nieuwe tijd.

## Hanoi

We sliepen in de **Old Quarter**, het oude centrum: een doolhof van 36 straten, die elk vroeger hun eigen ambacht hadden. De straat van de zijdeverkopers, de straat van de blikslagers, de straat van het speelgoed. Het verkeer is waanzinnig: duizenden scooters, die alle kanten op rijden, toeteren en nergens stoppen. Oversteken doe je door rustig en in een gelijkmatig tempo te lopen. De scooters gaan om je heen. Met een kinderwagen? Vergeet het. De draagzak was ons beste reisattribuut.

