Het mooiste van Hanoi met een kind: **de mensen**. Vietnamezen zijn dol op kinderen, en een blond jongetje van veertien maanden is een attractie. Overal waar we kwamen, werd Sam geknuffeld, in zijn wangen geknepen, op de foto gezet en volgestopt met snoepjes en stukjes fruit. Een oudere vrouw bij een soepkraampje nam hem gewoon van mijn schoot en liep met hem de straat op om hem aan haar buren te laten zien. Ik schrok eerst. Sam lachte.

## Hoan Kiem

In het hart van de stad ligt het **Hoan Kiem-meer**, het Meer van het Teruggegeven Zwaard, met een rood bruggetje naar een tempel op een eilandje. In het weekend is de weg rondom het meer autovrij, en dan is het één groot feest: kinderen op skates en elektrische autootjes, families die picknicken, oudere dames die aan het touwtjespringen zijn en jongeren die de straatdans oefenen. Sam rende er voor het eerst achter een duif aan. Hij viel om. Hij stond op. Hij rende weer.

## Train Street

Op de beroemde **Train Street** rijdt een trein rakelings langs de huizen, op een paar centimeter van de stoep waar mensen koffie zitten te drinken. Tijdens ons bezoek was het officieel gesloten voor toeristen (veiligheid), maar sommige cafés lieten je toch binnen. Wij keken het met Sam in de draagzak van een afstand, op een stoeltje van een café. Toen de trein langskwam, keek hij met grote ogen, en riep hij: "Tuut!" Zijn eerste echte woord in Vietnam.

