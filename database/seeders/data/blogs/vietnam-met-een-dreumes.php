Amsterdam – Hanoi, met een overstap in Doha. In totaal zeventien uur onderweg. We hadden een **bassinet** aangevraagd, een babybedje dat aan de wand voor je stoel wordt gehangen. Sam was eigenlijk al te groot (het is tot 10 of 11 kilo, hij woog 9,8), maar hij paste er nog net in, en sliep er vijf uur in. Een wonder.

