Toen we aan vrienden vertelden dat we met Sam naar Vietnam gingen, waren de reacties gemengd. "Wat leuk!" van de ene helft. "Is dat niet heel zwaar, met zo'n kleintje?" van de andere helft. En eerlijk: we vroegen het ons zelf ook af. Sam was veertien maanden, liep net een beetje, sliep nog twee keer per dag en stopte alles in zijn mond.

Maar Vietnam was in maart 2022 weer opengegaan voor toeristen, de vluchten waren betaalbaar, en we hadden zin in avontuur. Dus we deden het.

