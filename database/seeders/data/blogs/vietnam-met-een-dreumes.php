## Eten met een dreumes

Vietnamees eten is perfect voor kleine kinderen: veel rijst, noedels, soep, gekookte groente, gegrild vlees en vers fruit, en het meeste is niet pittig (de pepers staan apart op tafel). Sam at **pho** (noedelsoep) met zijn handen, rijstnoedels met kip, en bananen. Heel veel bananen.

