Vorige zomer stond ik op onze zolder tussen de dozen. Dozen met kleding die niemand meer droeg, speelgoed waar de kinderen al jaren niet meer naar keken, een fondueset die we twee keer hadden gebruikt en een broodbakmachine die, eerlijk is eerlijk, nog nooit een brood had gebakken. En ik dacht: waarom hebben we dit allemaal?

Dat moment was het begin van een grote opruimactie. Maar ook van een andere manier van kijken naar wat we eigenlijk belangrijk vinden.

## Opruimen

We begonnen klein. Elke week één kast of één hoek van het huis. Bij alles stelden we onszelf drie vragen:

1. Hebben we dit het afgelopen jaar gebruikt?
2. Zouden we het opnieuw kopen als het nu kapot zou gaan?
3. Maakt het ons blij, of houden we het alleen uit schuldgevoel?

Het resultaat: twaalf vuilniszakken naar de kringloop, een volle aanhanger naar de milieustraat en een stuk of veertig dingen verkocht via Marktplaats. Dat laatste leverde ruim 600 euro op. Genoeg voor de vliegtickets van ons volgende weekendje weg.

## Het gaat niet om de spullen

Wat ik tijdens het opruimen merkte, is dat ik me bijna nergens aan gehecht voelde. Ik kon zonder problemen afscheid nemen van een dure jas, een designlamp of een stapel boeken. Maar het fotoalbum van onze reis door Vietnam, het olifantje dat ik in Udaipur schilderde of het notitieboekje van Siem met alle traptreden in Nepal: die zou ik voor geen goud weggeven.

Toen viel het kwartje. De dingen die ik koester zijn bijna nooit de spullen zelf. Het zijn de herinneringen die eraan vastzitten. En die herinneringen maken we vooral als we samen op pad zijn.

> Niemand ligt op zijn sterfbed te denken: had ik maar een grotere televisie gekocht.

## Andere keuzes

We hebben sindsdien een paar dingen veranderd:

- **Cadeaus**: voor verjaardagen vragen we de kinderen of ze liever een cadeau of een uitje willen. Meestal kiezen ze voor een uitje, zoals een dag naar de dierentuin of een nachtje kamperen.
- **Een reispotje**: elke maand zetten we een vast bedrag opzij, en alles wat we verkopen of overhouden gaat er ook in.
- **Bewuster kopen**: voordat we iets kopen, wachten we een week. Vaak blijkt dat we het toch niet nodig hebben.
- **Minder abonnementen**: we hadden er zeven. Nu nog drie.

## Is het altijd makkelijk?

Nee. Ik ben ook gewoon een mens die soms valt voor een mooie trui in de uitverkoop. En de kinderen vinden het niet altijd leuk dat ze niet hetzelfde speelgoed krijgen als hun vriendjes. Maar als ik zie hoe ze verhalen vertellen over de zeehonden op Texel of de zonsopkomst in Nepal, weet ik dat we de goede keuze maken.

Het is geen wedstrijd minimalisme. We hebben nog steeds een volle keukenla en een bank vol kussens. Maar we kiezen bewuster, en dat voelt goed.

Life is short, so enjoy it. En daarvoor heb je minder nodig dan je denkt.
