Als je in april uit het vliegtuig stapt in **Sevilla**, ruik je het meteen: **azahar**, de bloesem van de sinaasappelbomen. Er staan er meer dan veertigduizend in de straten van de stad, en in het voorjaar bloeien ze allemaal tegelijk. Het ruikt naar honing, jasmijn en een beetje naar zeep. De hele stad ruikt naar vakantie.

## Een Spaans ritme

We waren een beetje bang voor het Spaanse dagritme: lunch om drie uur, avondeten om tien uur. Met een peuter van twee jaar en acht maanden, die gewend is om om zeven uur in bed te liggen, leek ons dat lastig. Maar Spaanse kinderen gaan gewoon mee. Om tien uur 's avonds zie je hele families op de terrassen, met kinderen die rondrennen op de pleinen, en oma die een baby in de kinderwagen wiegt.

Dus pasten we ons aan. Sam deed 's middags een lange siësta (en wij ook, in het koele appartement met de luiken dicht), en 's avonds gingen we pas om half negen eten. Hij lag om tien uur in bed. En sliep 's ochtends gewoon uit tot negen. Na drie dagen was hij een echt Spaans kind.

## Plaza de España

Het bekendste plein van Sevilla is de **Plaza de España**, gebouwd voor de wereldtentoonstelling van 1929. Een enorm halfrond gebouw van baksteen, met torens, galerijen en een gracht met bruggetjes. Langs de muur zijn 48 nisjes, een voor elke Spaanse provincie, met bankjes van beschilderde tegels.

Je kunt er kleine roeibootjes huren op de gracht. Sam mocht "sturen". We zijn vijf keer tegen de kant gebotst, en hebben heel hard gelachen.

## De kathedraal en de Giralda

De **kathedraal** van Sevilla is de grootste gotische kathedraal ter wereld. Binnen staat het graf van Christoffel Columbus, gedragen door vier beelden van koningen. Maar het mooiste vond ik de **Giralda**, de klokkentoren. Het was ooit de minaret van de moskee die hier stond, en je gaat niet via trappen, maar via **35 hellingen** naar boven: ze zijn breed genoeg gemaakt zodat de muezzin er te paard naar boven kon. Met een peuter aan de hand is dat ideaal. Sam liep het hele stuk zelf.

