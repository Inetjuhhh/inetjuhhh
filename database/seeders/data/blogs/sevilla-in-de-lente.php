## Tapas met een peuter

Tapas zijn perfect voor kinderen: kleine hapjes, alles om te delen, en je kunt van alles proberen. Sam's favorieten:

- **Tortilla de patatas**: Spaanse aardappelomelet.
- **Croquetas**: gefrituurde kroketjes met ham of kip.
- **Pan con tomate**: brood met tomaat en olijfolie.
- **Albóndigas**: gehaktballetjes in tomatensaus.
- **Churros con chocolate**, als ontbijt op zondag. Echt waar, dat doen de Sevillanen ook.

