## Het Real Alcázar

Naast de kathedraal ligt het **Real Alcázar**, het koninklijk paleis, nog steeds in gebruik door de Spaanse koninklijke familie. Het is gebouwd in **mudéjarstijl**: christelijke koningen lieten islamitische bouwmeesters een paleis bouwen, met bogen, tegels, fonteinen en houtsnijwerk. De tuinen zijn een droom, met sinaasappelbomen, palmen, fonteinen en pauwen die rondlopen. Sam heeft een uur achter een pauw aan gerend. De pauw heeft het overleefd.

## Las Setas

In de nieuwere wijk staat de **Metropol Parasol**, die de Sevillanen *Las Setas* noemen: de paddenstoelen. Een enorme houten constructie in de vorm van een golvend dak, op zes pilaren. Je kunt erop lopen, over een slingerende loopbrug, met uitzicht over de daken van de stad. Bij zonsondergang is het prachtig.

