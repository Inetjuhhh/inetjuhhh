## Het leven in de lodges

Overnachten doe je in **teahouses**: eenvoudige lodges met houten kamertjes, een gedeelde badkamer en een eetzaal met een houtkachel. 's Avonds zit iedereen rond die kachel: trekkers uit alle landen, gidsen, dragers. Je eet **dal bhat**, linzensoep met rijst, groente en curry. Het mooiste: je krijgt net zo lang bij tot je nee zegt. "Dal bhat power, 24 hour," zegt Dawa.

Hoe hoger je komt, hoe duurder alles wordt, omdat alles op de rug van dragers of ezels naar boven wordt gebracht. Een rol wc-papier kostte in Base Camp drie keer zoveel als in Pokhara.

## Hoogte

Vanaf zo'n drieduizend meter kun je last krijgen van hoogteziekte. Ik kreeg in Deurali hoofdpijn, maar na veel water drinken en een goede nacht was het weg. De regel is: langzaam stijgen, veel drinken, en als je klachten erger worden, ga je terug naar beneden. Altijd.

