Ik ben geen sportief type. Ik fiets naar mijn werk en wandel graag, maar daar houdt het op. Dus toen Bas voorstelde om in Nepal een trektocht van tien dagen te doen, naar meer dan vierduizend meter hoogte, dacht ik eerst dat hij een grapje maakte. Tien dagen later stond ik daar, met tranen in mijn ogen, tussen de bergen.

## Voorbereiding in Pokhara

We begonnen in **Pokhara**, een relaxte stad aan het Phewameer. Daar regelden we onze vergunningen (een ACAP-permit en een TIMS-kaart) en een gids, Dawa, die al vijftien jaar in de bergen liep. Een gids is niet verplicht op deze route, maar wij waren blij met hem: hij wist welke lodges goed waren, vertelde verhalen over elk dorp en hield ons tempo in de gaten.

We namen geen drager. Ieder droeg zijn eigen rugzak van zo'n acht kilo, met slaapzak, warme kleding en een paar Snickers voor noodgevallen.

## De route

We liepen via **Ghorepani** en **Poon Hill** naar het Annapurna Sanctuary, een enorme bergkom omringd door pieken van zeven- en achtduizend meter.

1. **Nayapul – Tikhedhunga**: een makkelijke eerste dag langs rijstterrassen.
2. **Tikhedhunga – Ghorepani**: 3.300 stenen traptreden omhoog. De zwaarste dag van de hele tocht, vond ik.
3. **Poon Hill – Tadapani**: om vijf uur op voor de zonsopkomst op Poon Hill, daarna door rododendronbossen.
4. **Tadapani – Chhomrong**: een prachtig dorp op een helling met uitzicht op de Machapuchare.
5. **Chhomrong – Bamboo**: eerst 2.500 treden naar beneden, en dan weer omhoog. Nepalese "flat" bestaat niet.
6. **Bamboo – Deurali**: door de vallei, langs watervallen.
7. **Deurali – Annapurna Base Camp**: via Machapuchare Base Camp naar 4.130 meter.
8. **Terug** naar Bamboo, Jhinu Danda (met warmwaterbronnen!) en Nayapul.

