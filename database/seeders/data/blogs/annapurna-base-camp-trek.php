## Base Camp

We kwamen op dag zeven rond het middaguur aan in Annapurna Base Camp. Het was bewolkt en ijskoud, en we zagen bijna niks. Ik was een beetje teleurgesteld. Maar de volgende ochtend om zes uur trok de lucht open, en zag ik het: een kring van witte reuzen om ons heen. De **Annapurna I**, de **Machapuchare** met zijn vissenstaart-top, de Hiunchuli. De zon kleurde de toppen eerst roze, dan goud.

Bas sloeg zijn arm om me heen en zei: "Zie je wel, je kon het." Ik huilde een beetje. Van het uitzicht, van trots en van de kou.

