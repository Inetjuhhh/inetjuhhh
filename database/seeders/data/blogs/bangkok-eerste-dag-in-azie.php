## Eten op straat

's Avonds aten we op een plastic krukje langs de weg onze eerste echte pad thai, gebakken in een wok die groter was dan het karretje zelf. Veertig baht. Bas bestelde er meteen nog een. Daarna mango sticky rice, en een fruitshake die zo zoet was dat ik er nu nog van droom.

Jetlag of niet, we lagen pas om half twaalf in bed. Gerrit de gekko zat er nog.

