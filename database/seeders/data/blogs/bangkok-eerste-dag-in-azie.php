## De tuktukchauffeur en zijn "speciale aanbieding"

Op dag één trapten we er natuurlijk meteen in. Een vriendelijke man vertelde ons dat het Grand Palace vandaag gesloten was ("Buddhist holiday!"), maar dat zijn neef ons voor twintig baht naar een paar andere tempels kon brengen. Een uur later stonden we in een edelstenenwinkel, en daarna in een maatpakkenzaak.

We kochten niks, de chauffeur kreeg zijn benzinebonnen van de winkels, en wij hadden een goed verhaal. Maar onthoud het: **het Grand Palace is bijna nooit gesloten.** Iemand die het tegendeel beweert, wil je ergens anders heen hebben.

## Wat Pho en Wat Arun

Uiteindelijk liepen we zelf naar **Wat Pho**, met de beroemde liggende Boeddha van 46 meter lang. Hij is zo groot dat je hem niet in één keer op de foto krijgt. Achter in de tempel zit de oudste massageschool van Thailand, en voor een paar euro kreeg ik daar de pijnlijkste en heerlijkste massage van mijn leven.

Daarna namen we voor vier baht het pontje over de Chao Phraya naar **Wat Arun**, de Tempel van de Dageraad. De toren is bekleed met stukjes porselein in alle kleuren, en als de zon erop valt, glinstert hij. We klommen de steile treden op en keken uit over de rivier, met de longtailboten die eronderdoor scheurden. Ik weet nog dat ik dacht: dit is waarom we reizen.

