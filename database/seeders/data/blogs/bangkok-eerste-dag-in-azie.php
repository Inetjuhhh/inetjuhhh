## Khao San Road: precies zo erg als je denkt (en toch leuk)

Voor de eerste drie nachten hadden we een guesthouse geboekt vlak bij **Khao San Road**, de backpackersstraat van Bangkok. Is het toeristisch? Heel erg. Verkopen ze er gefrituurde schorpioenen op een stokje en T-shirts met "Same same but different"? Zeker. Maar voor een eerste kennismaking met Azië is het eigenlijk perfect: alles is makkelijk, iedereen spreekt een beetje Engels, en je zit op loopafstand van de grote tempels.

Ons kamertje kostte 450 baht per nacht (toen zo'n twaalf euro), met een ventilator, een gedeelde badkamer en een gekko boven de deur die we Gerrit noemden.

