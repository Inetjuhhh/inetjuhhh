### De Pacifische kust

De laatste twee weken gaan we naar de **Pacifische kust**. Eerst naar **Manuel Antonio**, een klein nationaal park met stranden in de jungle, waar de kapucijnaapjes je lunch stelen en de luiaards vlak boven het wandelpad hangen. En daarna naar **Uvita**, met het **Marino Ballena Nationaal Park**, waar een zandbank bij eb de vorm heeft van een walvisstaart. Hier vieren we oud en nieuw, aan het strand.

## Wat het kost

We hebben een **4x4 huurauto** gereserveerd (sommige wegen zijn onverhard), voor ongeveer 1.400 euro voor vier weken, inclusief verzekering. De vluchten kostten zo'n 2.600 euro voor ons drieën, in de kerstvakantie. Voor de accommodaties rekenen we op gemiddeld 110 euro per nacht. Costa Rica is niet goedkoop, zeker niet in vergelijking met Zuidoost-Azië. Maar we hebben er twee jaar voor gespaard.

