### Arenal

Daarna gaan we naar de **Arenal-vulkaan**, een perfecte kegel bij het dorp **La Fortuna**. Hij is sinds 2010 niet meer actief (sorry Sam, geen ontploffing), maar het gebied eromheen is fantastisch: hangbruggen door het regenwoud, een waterval van zeventig meter, en warmwaterbronnen die door de vulkaan worden verwarmd. Hier vieren we kerst, in een lodge met een zwembad en een tuin waar 's ochtends toekans in de bomen zitten (volgens de reviews).

### Monteverde

Dan rijden we de bergen in, naar **Monteverde**, op ruim 1.400 meter hoogte. Hier ligt het beroemde **nevelwoud**: een bos dat bijna altijd in de wolken hangt, vol mossen, varens, orchideeën en kolibries. Op advies van Kevin (zie de reacties op mijn vorige blog) boeken we hier een **nachtwandeling** met een gids, met zaklampjes. Dan zie je tarantula's, slapende vogels, en hopelijk: een **roodoogmakikikker**. Nummer twee op Sam's lijstje.

