### Tortuguero

We beginnen in **Tortuguero**, aan de Caribische kust. Er komt geen weg: je laat de auto achter en neemt een boot door de kanalen. Het is een netwerk van rivieren en lagunes door het regenwoud, waar je vanuit een kano apen, luiaards, kaaimannen en heel veel vogels kunt zien. Het strand is een van de belangrijkste nestplaatsen voor zeeschildpadden ter wereld. In december is het geen hoogseizoen voor schildpadden, maar met wat geluk zien we nog een late groene zeeschildpad. Ik heb Sam gewaarschuwd.

