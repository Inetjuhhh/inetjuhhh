Nog tien weken! De afgelopen maanden hebben we avonden lang op de bank gezeten met een kaart van Costa Rica, een stapel reisgidsen en een lijst met tips van lezers (dank jullie wel, het zijn er inmiddels meer dan zestig!). Het resultaat: een route.

## Onze uitgangspunten

Met een kind van vijf plan je anders dan met z'n tweeën. Dit waren onze regels:

1. **Niet meer dan vier uur per dag in de auto**, en het liefst veel minder. De wegen in Costa Rica zijn bochtig en traag: honderd kilometer kan zomaar drie uur duren.
2. **Minimaal drie nachten op elke plek.** Inpakken, uitpakken, nieuwe bedden: dat is voor een kind (en voor ons) vermoeiend.
3. **Elke paar dagen een "niks"-dag**, met een zwembad of een strand.
4. **Afwisseling**: jungle, vulkaan, nevelwoud, strand.
5. **Geen haast.** Liever minder zien en meer beleven.

