De baai van **Ha Long** is een van de bekendste plekken van Vietnam: bijna tweeduizend eilanden en rotsen van kalksteen die als groene torens uit het water steken. Volgens de legende zijn ze ontstaan toen een draak uit de bergen naar beneden kwam en met zijn staart diepe dalen in het land sloeg, die daarna volstroomden met water.

## Waarom Lan Ha?

Het probleem met Ha Long Bay: iedereen gaat erheen. Elke dag varen er honderden boten uit, vaak allemaal tegelijk naar dezelfde grotten en strandjes. Wij hadden gelezen dat de baai ernaast, **Lan Ha Bay**, aan de oostkant van het eiland **Cat Ba**, net zo mooi is en veel rustiger. Dat klopte.

## Met de boot

We boekten een tocht van twee dagen en een nacht op een kleine houten boot, met zes hutten. We kozen bewust voor een boot met een **reling rondom** en een binnendek met airco. Met een kind dat net loopt en alles wil ontdekken, wil je geen open dek zonder hekje. De bemanning had zelfs een kinderzwemvest voor Sam, die hij de hele dag aanhad. Hij zag eruit als een klein oranje kussen.

Vanuit de haven voeren we tussen de rotsen door, steeds dieper de baai in. Het water was groen en glad, de rotsen waren bedekt met jungle, en hier en daar zag je een drijvend vissersdorpje: houten huisjes op vlotten, met een hond op de veranda en kinderen die in kleine bootjes peddelden.

