De laatste week van onze reis vlogen we van Bali naar **Labuan Bajo**, een havenstadje op het puntje van het eiland Flores. Van daaruit vertrekken de boten naar het Nationaal Park Komodo, het enige gebied ter wereld waar de komodovaraan in het wild leeft.

## De boot

We boekten een "liveaboard": drie dagen en twee nachten op een houten boot, samen met tien andere reizigers en vier bemanningsleden. Geen luxe. We sliepen op matrassen op het bovendek, onder een zeil, met de sterren boven ons en het geklots van het water onder ons. Er was één toilet en een emmer met zeewater om te douchen. Ik heb het fantastisch gevonden.

## Padar

Op dag één, aan het eind van de middag, klommen we naar de top van **Padar**. Het is een steile klim van een half uur, maar boven zie je het mooiste uitzicht van Indonesië: een kronkelend eiland met drie baaien, de ene met wit zand, de andere met zwart en de derde met roze zand. Daaromheen de zee met tientallen kleine eilandjes, en de zon die alles goud kleurde.

## De draken

Op dag twee voeren we naar **Rinca**, waar de meeste varanen leven. Met een parkwachter met een gevorkte stok liepen we door het droge savannelandschap. Na een paar minuten zagen we de eerste: een komodovaraan van bijna drie meter, liggend in de schaduw van een boom bij de keuken van het parkwachtershuis. Ze zien er een beetje lui uit, maar ze kunnen korte stukken twintig kilometer per uur rennen, en hun beet is giftig.

De parkwachter vertelde dat ze een buffel kunnen doden en dan dagenlang achter hem aanlopen tot hij doodgaat. Daarna eten ze in één keer tachtig procent van hun eigen lichaamsgewicht. Bas vroeg of ze ook mensen eten. "Soms," zei de parkwachter. We liepen daarna wat dichter bij hem.

