## Zwemmen en snorkelen

De rest van de tocht bestond vooral uit zwemmen en snorkelen. Bij **Pink Beach** zagen we schildpadden en een rif vol vissen in alle kleuren. Bij **Manta Point** (ja, weer manta's!) zwommen we in een sterke stroming langs tientallen manta's. En bij **Kalong** zagen we bij zonsondergang duizenden vleerhonden uit de mangroves opstijgen, als een zwarte wolk boven het water.

## Terug in Labuan Bajo

Toen we na drie dagen terug in de haven van Labuan Bajo stonden, met zout in ons haar en een zonverbrande neus, had ik het gevoel dat we een maand weg waren geweest.

