## Trang An

Een paar kilometer verderop ligt **Trang An**, een vergelijkbare boottocht, maar groter en rustiger, en Unesco-werelderfgoed. De tocht duurt drie uur, door negen grotten en langs kleine tempels op eilandjes. Een stukje van de film *Kong: Skull Island* is hier opgenomen, en er staat nog een dorpje van het filmdecor. Sam viel na een uur in slaap, in de draagzak, op het ritme van de roeispanen.

## Hang Mua

Het mooiste uitzicht van Ninh Binh heb je vanaf **Hang Mua**: een rotstop met **500 traptreden** naar boven, met bovenop een pagode en een stenen draak die over de rots kronkelt. Van boven zie je de rivier van Tam Coc, de rijstvelden en de rotsen tot aan de horizon.

Bas droeg Sam in de draagzak naar boven. In 35 graden. Ik droeg de tas met water, luiers, fruit en zonnebrand. Ik weet niet wie van ons het zwaarder had. Boven gingen we op de stenen zitten, deelden we een kokosnoot, en wezen we Sam alle eenden en waterbuffels aan. Hij was meer geïnteresseerd in de kokosnoot.

