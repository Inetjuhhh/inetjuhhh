Twee uur ten zuiden van Hanoi ligt de provincie **Ninh Binh**, met een landschap dat ze ook wel "Ha Long Bay op het land" noemen. Dezelfde torens van kalksteen, maar dan midden in de groene rijstvelden, met rivieren die zich ertussendoor slingeren. Wij bleven er vijf dagen. Het werd onze favoriete plek van de reis.

## Ons huisje

We sliepen in een homestay in **Tam Coc**, een dorpje aan de rivier. Ons bungalowtje stond tussen de rijstvelden, met een veranda, een zwembadje en uitzicht op de rotsen. De eigenaresse, chị Hoa, had een dochtertje van twee, en Sam en zij werden in een dag beste vriendjes. Ze spraken geen woord dezelfde taal, maar dat maakte niet uit. Ze speelden de hele dag met de eenden, de kippen en de waterbuffel in het veld naast het huis.

## Varen door Tam Coc

In Tam Coc maak je een boottocht op de rivier **Ngo Dong**, door drie grotten onder de rotsen door. Het bijzondere: de roeisters roeien met hun **voeten**. Ze zitten achter in het bootje, en duwen met hun voeten de riemen voort, terwijl ze met hun handen hun telefoon vasthouden, of een kegelhoed om zich koel te wuiven.

Sam zat tussen ons in, met zijn zwemvest aan, en keek zijn ogen uit. In de grotten werd hij heel stil. Het is er donker, koel, en het water druppelt van het plafond. Toen we aan de andere kant weer het licht in kwamen, riep hij "Ooooh!" Daar kan ik me helemaal bij aansluiten.

