## De weg over de Puerto de las Palomas

Van Zahara naar **Grazalema** rijd je over de **Puerto de las Palomas**, een bergpas op 1.357 meter, met een kronkelweg en uitzicht over de hele Sierra de Grazalema. Grazalema is het natste dorpje van Spanje (hier valt meer regen dan in Londen), en daardoor heel groen. Er worden van oudsher wollen dekens gemaakt. We kochten er een, voor Sam's bed.

