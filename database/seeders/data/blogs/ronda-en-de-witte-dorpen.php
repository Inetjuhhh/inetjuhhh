Na Granada huurden we een auto, en reden we het binnenland van Andalusië in. Tussen Málaga, Sevilla en Cádiz liggen de **pueblos blancos**, de witte dorpen: tientallen dorpjes met witgekalkte huizen tegen de berghellingen, vaak met een kasteeltje of een kerk op de top. We sliepen vier nachten in een oude boerderij, een *cortijo*, bij Ronda, met een zwembad en olijfbomen.

## Ronda

**Ronda** is de bekendste, en de grootste. De stad ligt op een rotsplateau, dat precies in het midden doormidden wordt gespleten door de kloof van **El Tajo**, honderd meter diep. Over de kloof ligt de **Puente Nuevo**, de nieuwe brug, die (ondanks de naam) uit 1793 komt. Hij is 98 meter hoog, en een van de meest gefotografeerde bruggen van Spanje.

Je kunt via een wandelpad naar beneden lopen, naar de bodem van de kloof, voor het beroemde uitzicht op de brug van onderaf. Met Sam in de draagzak deden we het eerste stukje. Het is steil, maar het uitzicht is het waard.

Ronda heeft ook de oudste **arena** van Spanje. Wij zijn er niet naar binnen gegaan. Bas en ik hebben er moeite mee, en Sam is nog geen drie. Over stierengevechten leg ik hem nog niks uit.

## Setenil de las Bodegas

Het gekste dorpje dat ik ooit heb gezien: **Setenil de las Bodegas**. De huizen zijn gebouwd in en onder een enorme overhangende rotswand, langs een riviertje. In sommige straten loop je letterlijk onder een stenen dak. De bewoners gebruiken de rots als achtermuur en als plafond. Het is er lekker koel.

Sam keek omhoog naar de rots boven zijn hoofd en vroeg of die naar beneden zou vallen. Nee, schat. Al eeuwen niet.

