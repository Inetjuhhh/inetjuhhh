## Spaanse speeltuinen

Kleine tip die niemand je vertelt: elk Spaans dorp, hoe klein ook, heeft een **parque infantil**, een speeltuin, meestal bij de kerk of het centrale plein. Om acht uur 's avonds zitten daar alle ouders en grootouders op de bankjes, terwijl de kinderen spelen. Sam speelde in elk dorp met andere kinderen, zonder één woord Spaans te spreken. Op het einde van de week zei hij "¡Hola!" en "¡Vamos!" Bas en ik kunnen inmiddels ook "tobogán" (glijbaan) zeggen.
