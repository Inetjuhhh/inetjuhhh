## Zahara de la Sierra

Het mooiste dorp vonden we **Zahara de la Sierra**: een wit dorp tegen een steile heuvel, met bovenop een Moorse burcht, en daaronder een **stuwmeer** met water in het felste turquoise dat ik ooit heb gezien. We klommen naar de toren (Sam liep zelf, met een stok die hij onderweg had gevonden, en die zijn "zwaard" was), en keken uit over het meer en de bergen.

Daarna zwommen we in het meer, bij een strandje met een snackbar. Het water was koud. Sam vond het niet erg.

