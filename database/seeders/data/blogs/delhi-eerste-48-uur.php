"India is geen land dat je bezoekt, het is een land dat jou overkomt." Dat las ik in een reisgids in het vliegtuig, en ik vond het nogal een dramatische zin. Twaalf uur later stond ik midden in Old Delhi, met een koe naast me, een riksja die tegen mijn kuit tikte en een man die me een kom chai in de hand drukte, en begreep ik wat ze bedoelden.

## Aankomen

We landden 's nachts en hadden via ons hotel een taxi geregeld. Dat raad ik iedereen aan: om drie uur 's nachts wil je niet onderhandelen met tien taxichauffeurs tegelijk. We sliepen in Paharganj, de backpackerswijk bij het station. Het is er rommelig en luidruchtig, maar wel centraal.

## Old Delhi

Op dag één gingen we met de metro (schoon, goedkoop, met een aparte wagon voor vrouwen) naar **Chandni Chowk**, de hoofdstraat van Old Delhi. De straat zelf is druk, maar de zijsteegjes zijn nog veel drukker. Er zijn straatjes alleen voor zilverwerk, straatjes vol bruidsjurken, en een kruidenmarkt waar je zonder te niezen niet doorheen komt.

We namen een fietsriksja met een oude man die Raju heette. Hij fietste ons voor tweehonderd roepie een uur lang door de wirwar, wees ons de beste stalletjes aan en stopte bij de **Jama Masjid**, de grootste moskee van India. Op het enorme binnenplein, waar 25.000 mensen kunnen bidden, was het opeens stil. Duiven, rode zandsteen en drie witte koepels. We klommen in de minaret en keken uit over de daken van Old Delhi.

