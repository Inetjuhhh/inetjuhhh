## Eten in Old Delhi

Raju bracht ons ook naar de straat van de parathas, de **Paranthe Wali Gali**, waar al sinds 1870 gevulde platte broodjes worden gebakken in ghee. Aardappel, bloemkool, paneer, en zelfs banaan. Daarna jalebi's (gefrituurde, kleverige spiraaltjes in suikersiroop) en een lassi in een aardewerken bekertje dat je daarna op de grond kapot gooit.

