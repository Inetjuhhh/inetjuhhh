## Humayun's Tomb en de rust van New Delhi

Op dag twee hadden we behoefte aan ruimte. Die vonden we bij **Humayun's Tomb**, een zestiende-eeuws mausoleum in een enorme tuin. Het wordt ook wel het voorbeeld van de Taj Mahal genoemd, en dat zie je meteen: dezelfde symmetrie, dezelfde koepel, alleen in rood zandsteen. Er waren weinig toeristen, wel veel schoolklassen. Kinderen die met ons op de foto wilden. Heel veel kinderen.

Daarna liepen we door de **Lodhi Gardens**, waar Indiase families picknicken tussen vervallen graftombes, en eindigden we bij de India Gate bij zonsondergang.

## Wat we leerden

- **Neem de tijd om te wennen.** Plan de eerste twee dagen niet vol.
- **Zeg vriendelijk maar beslist nee.** Tegen de tiende man die je naar een "government tourist office" wil brengen.
- **Gebruik de metro.** Snel, goedkoop en een fijne pauze van het verkeer.
- **Lach.** Om de koeien, de toeterende vrachtwagens en de man die je vraagt of Nederland in Duitsland ligt.

Morgen pakken we de trein naar Agra. De Taj Mahal wacht.
