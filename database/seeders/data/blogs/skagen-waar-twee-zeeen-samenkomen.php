## De ondergestoven kerk

Diezelfde wandelende duinen hebben de stad Skagen vroeger veel ellende gebracht. In de zeventiende en achttiende eeuw schoof het zand over de akkers, de huizen en uiteindelijk de kerk van **Sankt Laurentii**. De gemeente moest elke zondag eerst de deur uitgraven om de kerk in te kunnen. In 1795 gaven ze het op. Het schip van de kerk werd afgebroken, en nu staat alleen de witte toren nog, half in het zand, midden in een bos: **Den Tilsandede Kirke**.

