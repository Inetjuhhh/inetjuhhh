**Skagen** is een stadje met gele huizen met rode pannendaken en witte randjes, op het noordelijkste puntje van Jutland. In de negentiende eeuw kwam hier een groep schilders wonen, de **Skagenschilders**, die verliefd werden op het licht. Dat licht is er nog steeds: helder, zacht en blauw, met lange avonden in de zomer en een zon die laag over zee hangt in de herfst.

## Grenen

Vlak buiten Skagen loopt Denemarken uit in een lange, smalle zandpunt: **Grenen**. Hier komen de **Skagerrak** (het deel van de Noordzee tussen Denemarken en Noorwegen) en het **Kattegat** samen. Je ziet het echt: de golven van de twee zeeën rollen vanuit verschillende richtingen op elkaar af en botsen in een lange lijn van schuim.

Je loopt er vanaf de parkeerplaats in een half uurtje heen, over het strand. Wij deden het met Sam in de draagdoek, ingepakt in zijn wollen pakje, een mutsje en een sjaal, en de draagjas van Bas er overheen. Het waaide zo hard dat ik bang was dat hij zou wegvliegen. Hij sliep er dwars doorheen.

Op het puntje trokken we onze schoenen uit en zetten we allebei een voet in elke zee. Het water was ijskoud. Bas hield Sam's sokvoetjes er nog net niet in.

## Råbjerg Mile

Ten zuiden van Skagen ligt de **Råbjerg Mile**, de grootste wandelende duin van Noord-Europa. Hij is een kilometer lang, veertig meter hoog, en schuift elk jaar zo'n vijftien meter naar het noordoosten. Wie er bovenop staat, ziet alleen zand, alsof je in de Sahara bent. Een woestijn in Denemarken.

Met een kinderwagen kom je er niet ver (zand!), dus ook hier ging Sam mee in de draagdoek. Bas klom naar de top, ik bleef met Sam halverwege op een zandrichel zitten. Uitzicht zat.

