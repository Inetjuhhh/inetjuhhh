Maar eerst Ayutthaya.

## De trein voor twintig baht

Ayutthaya ligt zo'n tachtig kilometer ten noorden van Bangkok. Je kunt er met een minibusje heen, maar wij namen de derdeklastrein: houten banken, ventilatoren aan het plafond, open ramen en verkopers die met emmers vol gekoelde drankjes en zakjes plakrijst door de wagons lopen. De rit duurde twee uur en kostte twintig baht. Vijftig cent.

## De oude hoofdstad

Van 1351 tot 1767 was Ayutthaya de hoofdstad van het koninkrijk Siam, en een van de grootste en rijkste steden ter wereld. Er woonden een miljoen mensen, en er kwamen handelaren uit China, Japan, Perzië en Europa. Ook de Nederlanders van de VOC hadden er een handelspost. In 1767 werd de stad door het Birmese leger verwoest. Wat overbleef zijn honderden ruïnes van tempels, paleizen en chedi's, verspreid over een eiland in de rivier. Het is nu Unesco-werelderfgoed.

## Op de fiets

De ruïnes liggen te ver uit elkaar om te lopen, dus huurden we bij ons guesthouse twee fietsen voor vijftig baht per dag. Ayutthaya is plat en rustig, en je fietst van tempel naar tempel over brede wegen en door parken. Dit waren onze favorieten:

- **Wat Mahathat**: hier vind je het beroemde Boeddhahoofd dat door de wortels van een vijgenboom is omsloten. Niemand weet precies hoe het daar terecht is gekomen. Wil je er een foto van, dan moet je door je knieën: je hoofd mag niet hoger zijn dan dat van de Boeddha.
- **Wat Phra Si Sanphet**: drie grote chedi's op een rij, de tempel van het koninklijk paleis.
- **Wat Chaiwatthanaram**: aan de overkant van de rivier, gebouwd in Khmerstijl. Het mooiste bij zonsondergang.
- **Wat Lokayasutharam**: een enorme liggende Boeddha van 42 meter, gewoon in de open lucht.

