De **Preikestolen** (Preekstoel) is een van de bekendste plekken van Noorwegen: een vierkant rotsplateau van 25 bij 25 meter, dat met een loodrechte wand van 604 meter boven het **Lysefjord** uitsteekt. Er komen elk jaar zo'n driehonderdduizend wandelaars. Wij waren drie van hen. Of eigenlijk tweeënhalf.

## De wandeling

Het pad naar de Preikestolen begint bij de parkeerplaats van de **Preikestolen Fjellstue**, en is zo'n vier kilometer lang (enkele reis), met 330 meter hoogteverschil. Reken op twee uur heen en twee uur terug, en met een kind wat langer. Het pad is in de afgelopen jaren flink verbeterd door Nepalese sherpa's, die er stenen trappen hebben aangelegd. Maar het blijft een bergpad: steil, rotsig en op sommige stukken glad.

## Sam in de draagzak

Sam was 22 maanden. Te groot voor een draagdoek, te klein om zelf te lopen. We hadden een **wandeldraagzak** gehuurd, zo'n stevige rugzak met een frame, een zonnekap en een plekje voor een fles water. Bas droeg hem, ik droeg de rest: lunch, water, regenjassen, luiers, een droog setje kleding en een zak rozijnen (cruciaal).

Sam vond het fantastisch. Hij zat hoog op Bas' rug, keek over zijn schouder, en riep naar iedereen die we tegenkwamen "Hoi!". De Noren riepen "Hei!" terug. Hij kreeg in totaal vier stukjes chocola van wildvreemden.

## Halverwege

Halverwege stopten we bij een klein meer, en liet ik Sam een stukje zelf lopen over de vlakke rotsen. Hij gooide steentjes in het water. Dat had hij een uur kunnen doen. Wij moesten hem na tien minuten met een rozijn weer de draagzak in lokken.

## De Preekstoel

En dan kom je om een bocht, en zie je hem. Een plat plateau, als een tafel boven de afgrond. Daaronder het fjord, smal en diep, glinsterend in de zon, met een cruiseschip dat eruitzag als speelgoed. Aan de overkant groene bergen met watervallen.

