## De terugweg

De terugweg was zwaarder, vooral voor mijn knieën. Sam sliep het grootste deel van de tijd in de draagzak, met zijn hoofd tegen Bas' nek. Bij de parkeerplaats hebben we een ijsje gegeten in het café van de Fjellstue. Sam werd wakker, zag het ijsje, en was meteen weer helemaal fit.

## Plan B

