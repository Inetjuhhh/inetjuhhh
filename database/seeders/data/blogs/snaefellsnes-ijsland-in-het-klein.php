Het schiereiland **Snæfellsnes** wordt wel "IJsland in het klein" genoemd. Op een stuk land van negentig kilometer lang vind je bergen, gletsjers, lavavelden, zwarte en gouden stranden, kliffen vol vogels en vissersdorpjes. En het ligt maar twee uur rijden van Reykjavík. De laatste drie dagen van onze reis brachten we hier door.

## Kirkjufell

De bekendste berg van IJsland staat aan de noordkust van het schiereiland: **Kirkjufell**, de Kerkberg. Een perfecte puntige kegel, met daarvoor een waterval in drie trapjes, **Kirkjufellsfoss**. Je hebt hem vast weleens gezien, het is de meest gefotografeerde plek van het land (en hij speelde mee in *Game of Thrones*).

We gingen er 's avonds om elf uur heen, toen de zon laag stond en alles in een gouden licht zette. Er waren maar drie andere mensen. Een van hen was een IJslandse fotograaf die er al twaalf keer was geweest, en nog steeds niet de perfecte foto had.

## Arnarstapi en Hellnar

Aan de zuidkust ligt **Arnarstapi**, een gehucht met een haventje en grillige kliffen van basalt. Langs de kust loopt een wandelpad van een uur naar het buurdorpje **Hellnar**, langs natuurlijke stenen bogen, grotten en duizenden zeevogels: drieteenmeeuwen, noordse sterns en, als je geluk hebt, papegaaiduikers. In Hellnar zit een klein cafeetje met de beste vissoep die ik in IJsland heb gegeten.

De sterns zijn trouwens agressief als je te dicht bij hun nesten komt: ze duiken op je hoofd af. Bas liep het hele stuk met een wandelstok boven zijn hoofd. Ik had een capuchon.

## Búðir

In het lavaveld van **Búðahraun** staat een klein zwart kerkje, helemaal alleen, met een wit kerkhofmuurtje en de gletsjer Snæfellsjökull op de achtergrond. Er loopt een pad door het lavaveld, bedekt met dik, zacht mos. Op sommige plekken zie je oude schuilhutjes, half in de grond gebouwd van lavastenen en graszoden.

