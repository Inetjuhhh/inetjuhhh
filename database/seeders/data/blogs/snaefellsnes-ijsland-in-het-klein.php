## Snæfellsjökull

Aan het puntje van het schiereiland ligt de **Snæfellsjökull**, een vulkaan bedekt met een gletsjer. Jules Verne liet in zijn boek *Reis naar het middelpunt der aarde* de hoofdpersonen hier in de krater afdalen. Op heldere dagen kun je hem zien vanuit Reykjavík, honderdtwintig kilometer verderop.

We liepen niet de berg op (zwanger, gletsjer, nee), maar reden de weg rond het nationaal park, langs het zwarte kiezelstrand van **Djúpalónssandur**. Daar liggen nog roestige stukken van een Brits vissersschip dat hier in 1948 verging, en vier stenen in verschillende groottes. Vroeger moesten vissers hiermee hun kracht bewijzen. De zwaarste weegt 154 kilo. Bas kreeg de lichtste (23 kilo) tot zijn knieën.

## Tot ziens, IJsland

Twee weken IJsland zitten erop. We hebben een vulkaan zien uitbarsten, zeehonden tussen de ijsbergen gezien en de middernachtzon gezien. Ik heb er nog niet één keer de zon onder zien gaan.

Morgen vliegen we naar huis, en dan begint het echte aftellen. Nog tien weken. Het babykamertje is nog niet af, er moet nog een kinderwagen gekocht worden, en we hebben nog geen naam. Bas zegt dat Kirkjufell een mooie naam is. Ik denk het niet.
