Daarna reden we de caldera in, over de zandzee, en liepen we de 250 treden op naar de kraterrand van de Bromo. Je kijkt er recht in een rokend gat, en je hoort de vulkaan rommelen. De lucht ruikt naar zwavel. De Tenggerezen, de mensen die hier wonen, gooien er tijdens het jaarlijkse Kasada-festival offers in: groenten, kippen en geld.

## Op naar Ijen

De rest van de dag zaten we in het busje, via de kust naar het oosten. We sliepen een paar uur in een guesthouse bij een koffieplantage, en om één uur 's nachts ging de wekker alweer.

## Het blauwe vuur

De **Ijen** is beroemd om twee dingen: het grootste zure kratermeer ter wereld en het **blauwe vuur**: zwavelgassen die met blauwe vlammen branden als ze in aanraking komen met lucht. Dat zie je alleen in het donker. Dus liepen we om twee uur 's nachts met een zaklamp en een gasmasker de berg op. Anderhalf uur steil omhoog, en daarna een smal, rotsig pad de krater in.

Beneden zagen we het: blauwe vlammen die als vloeistof over de rotsen kronkelden. Het was onwerkelijk mooi, en tegelijk zat je in een wolk van zwaveldamp die in je ogen en keel prikte.

