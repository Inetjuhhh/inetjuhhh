## De zwaveldragers

Wat me het meest is bijgebleven, zijn de mannen die er werken. Ze breken met ijzeren staven blokken gele zwavel los in de krater, en dragen die in twee manden aan een bamboestok naar boven. Zeventig, tachtig kilo, op hun schouders, op slippers, twee keer per dag. Ze verdienen er een paar euro per tocht mee. Veel van hen hebben geen goed masker.

Toen de zon opkwam, zagen we het meer: een enorme, turquoise plas, dampend in de krater, zo zuur dat het een blikje zou oplossen. Een van de mannen stopte naast ons om uit te rusten. Bas gaf hem een fles water en een pak koekjes. Hij lachte en liet ons zijn schouders zien, vol eelt.

