Oost-Java ligt vol vulkanen, en twee daarvan staan op elk reisschema: de **Bromo** en de **Ijen**. Ze liggen een dag rijden uit elkaar, en voor allebei moet je midden in de nacht op. Wij boekten een driedaagse tour vanuit Malang, met een chauffeur die Agus heette en die de hele dag Westlife meezong.

## Bromo

Om kwart over drie 's nachts zaten we achter in een oude Toyota Land Cruiser die met een rotgang de berg op reed naar het uitzichtpunt **Penanjakan**. Daar stonden we met honderden mensen in het donker te wachten, in alle jassen die we hadden. Het was vijf graden. Ik had niet verwacht dat ik in Indonesië zou rillen.

En toen kwam de zon op. Onder ons lag de **Tengger-caldera**: een enorme oude krater van tien kilometer breed, gevuld met een zee van grijs vulkaanzand. Daarin stonden drie vulkanen naast elkaar: de rokende Bromo, de keurig geribbelde Batok, en daarachter, perfect kegelvormig, de **Semeru**, de hoogste berg van Java, die elke twintig minuten een rookwolk uitblies.

