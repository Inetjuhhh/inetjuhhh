## Ons huisje

Ons sommerhus stond in de duinen, tussen de helmgras en de lage dennen, op vijf minuten lopen van het strand. Binnen: houten muren, grote ramen, een houtkachel en een sauna. Buiten: een terras met een tuinbank, en verder niks. Geen buren te zien, alleen duinen en lucht.

We deden echt helemaal niks. 's Ochtends maakte Bas het vuur aan, en ik voedde Sam onder een deken op de bank met uitzicht op de duinen. We maakten lange strandwandelingen met Sam in de draagdoek, tegen mijn borst, warm ingepakt in een wollen pakje. Hij sliep in de wind, met de zee op de achtergrond, en werd soms wakker van een meeuw. 's Avonds bakten we pannenkoeken en speelden we Rummikub bij het vuur.

## Het strand

Het strand van **Henne** is breed, wit en eindeloos. In oktober was er bijna niemand. Je mag er met de auto op rijden (dat doen de Denen ook echt), maar wij liepen. Kilometers lang, langs schelpen, aangespoelde kwallen en oude Duitse bunkers die half in het zand zijn weggezakt.

## Blåvand

Een dag reden we naar **Blåvand**, het meest westelijke punt van Denemarken, met een grote witte vuurtoren uit 1900. Je kunt de 170 traptreden naar boven lopen (Bas met Sam in de draagdoek, ik met de luiertas), en van boven zie je de zandbanken van het **Horns Rev**, waar de Noordzee tegen de kust slaat.

