Op 3 september om 04.12 uur werd hij geboren: **Sam**. 3.450 gram, 51 centimeter, met een bos donker haar en de handen van zijn vader. (Bas had dus gelijk: het was een meisje... nee hoor, ik had gelijk.) Hij is gezond, hij drinkt goed, en hij slaapt... nou ja. Hij slaapt soms.

De eerste weken waren een waas van voeden, luiers, slapen in blokjes van twee uur en bezoek. Heel veel bezoek. Toen Sam zes weken was, keken Bas en ik elkaar aan en zeiden we tegelijk: we moeten even weg. Niet ver, niet ingewikkeld, gewoon met z'n drieën.

## Waarom Denemarken?

- **Je kunt er met de auto heen.** Geen vliegtuig, geen paspoortgedoe voor een baby van zes weken (al hebben we er wel een aangevraagd).
- **De Denen zijn kampioen in gezellig.** Hun woord *hygge* betekent zoiets als knus, warm, gezellig. Precies wat we wilden.
- **Een sommerhus.** Denemarken heeft tienduizenden vakantiehuisjes in de duinen, van hout, met een houtkachel, een sauna en soms een bubbelbad. Buiten het seizoen zijn ze betaalbaar.

