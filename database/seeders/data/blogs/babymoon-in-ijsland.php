## Waarom een babymoon?

Een babymoon is een laatste reisje met z'n tweeën voor je kindje er is. Het woord vond ik eerst nogal overdreven, maar het idee is mooi. Na anderhalf jaar corona, met een geannuleerd bruiloftsfeest en een huwelijksreis die we per auto moesten doen, wilden we nog één keer echt weg. Iets bijzonders, met wijde landschappen en veel ruimte. Weg van de drukte.

