## Reykjavík

We begonnen met twee dagen **Reykjavík**, de kleinste hoofdstad die ik ken: je loopt in een uur van het ene eind naar het andere. Het is een vrolijk stadje met gekleurde huisjes van golfplaten, straatkunst en heel veel koffietentjes.

Boven de stad uit torent de **Hallgrímskirkja**, een kerk van beton met een gevel die eruitziet als basaltzuilen. Met de lift ga je naar boven, en daar heb je uitzicht over de hele stad, de zee en de bergen. In de kerk staat een enorm orgel met vijfduizend pijpen.

Aan het water staat **Harpa**, het concertgebouw, met een gevel van duizenden glazen honingraten die in het licht van kleur veranderen. En in de **oude haven** liggen walvisboten, staan kleine visrestaurantjes, en eet je bij Bæjarins Beztu de beroemdste hotdog van IJsland. Bas at er drie in twee dagen. "Voor de baby," zei hij.

