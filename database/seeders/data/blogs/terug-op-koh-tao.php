## Een duik voor Bas en mij

Op een ochtend paste een Nederlandse oppas die op het eiland werkte (je vindt ze via de duikscholen) twee uur op Sam, en gingen Bas en ik samen duiken. Voor het eerst in jaren. Bij **Japanese Gardens**, vlak bij **Koh Nang Yuan**, precies de plek waar we tien jaar geleden onze eerste "fun dive" maakten. Ik was zenuwachtig. Maar op twaalf meter lag ik rustig, keek om me heen, en ademde in, en uit.

Er zwom een schildpad voorbij. Echt waar. Misschien wel dezelfde.

