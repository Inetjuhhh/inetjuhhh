Toen de catamaran de haven van **Mae Haad** binnenvoer, pakte Bas mijn hand. We zagen dezelfde steiger, dezelfde duikscholen met vlaggetjes, dezelfde groene heuvels erachter. "Daar heb ik in paniek op twaalf meter gelegen," zei ik. "En daar heb ik je een duim gegeven," zei hij. Sam vroeg waarom we zo raar deden.

## Het eiland nu

Koh Tao is in tien jaar wel veranderd. Er zijn meer hotels, meer restaurants, meer verkeer op de smalle weggetjes. Op **Sairee Beach** staan nu ook een paar luxere resorts. Maar het eiland is nog steeds klein, groen en ontspannen, met overal duikers die in hun wetsuit met een ijsje over straat lopen.

We sliepen dit keer niet aan Sairee, maar aan de rustige oostkant, aan een kleine baai: **Aow Leuk**. Een strandje met fijn zand en kristalhelder, ondiep water, met een rif dat vlak bij de kant begint. Perfect voor een kind.

