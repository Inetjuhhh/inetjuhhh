## Uitzicht

Op onze laatste avond klommen we naar het **John-Suwan Viewpoint** aan de zuidpunt, een kwartiertje klimmen over grote rotsen. Sam deed het helemaal zelf, met een hand in die van Bas. Boven zagen we de zon ondergaan boven twee baaien tegelijk. We hebben er een foto van gemaakt, met z'n drieën, met de telefoon op een steen.

Die foto staat nu op mijn telefoon naast de foto van tien jaar geleden, van ons tweeën op het strand van Sairee. Bas heeft er minder haar. Ik heb meer rimpels. En er staat een jongetje tussen ons, met een snorkel op zijn hoofd.
