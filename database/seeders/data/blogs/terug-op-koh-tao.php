## Sam leert snorkelen

Sam is drie, en kan nog niet zwemmen. Maar met een zwemvest, een kindermasker dat over zijn hele gezicht valt (met een snorkel bovenop) en een papa die naast hem drijft, kon hij toch snorkelen. De eerste keer hield hij het tien seconden vol voor hij proestend boven kwam: "Er zit WATER in!" De tweede keer een minuut. En de derde keer bleef hij liggen. Toen hij weer bovenkwam, riep hij:

"Mama! Er is een VIS met STREPEN! En nog één! En een BLAUWE!"

Hij had **koraalduivels**, **papegaaivissen** en een kleine **blauwe zeester** gezien. Ik heb nog nooit zo'n blij kind gezien. Die avond moest ik in bed alle vissen opnoemen die hij had gezien. Het waren er veel. De volgende ochtend om zes uur stond hij al met zijn masker op zijn hoofd naast ons bed.

