**Cusco** was de hoofdstad van het Incarijk, dat zich op zijn hoogtepunt uitstrekte van Colombia tot Chili. Toen de Spanjaarden in 1533 aankwamen, vonden ze een stad met tempels bedekt met goud. Ze smolten het goud om, braken de tempels af en bouwden er kerken op. Maar de Inca-muren waren zo goed gebouwd dat ze bleven staan, en zo zie je nu overal in de stad Spaanse koloniale gebouwen op fundamenten van perfect gepaste Inca-stenen.

## De stad

We bleven vier dagen in Cusco, om te wennen aan de hoogte (3.400 meter) voor de Inca Trail. We sliepen in **San Blas**, de kunstenaarswijk op een heuvel, met steile straatjes van kinderkopjes, kleine werkplaatsjes en bakkerijen met houtovens.

Elke dag liepen we naar de **Plaza de Armas**, het grote plein met de kathedraal en de Iglesia de la Compañía. Er zitten altijd mensen op de bankjes, kinderen jagen op duiven, en vrouwen in klederdracht met een lammetje in hun armen vragen een sol voor een foto.

Wat je niet moet missen:

- **De steen met twaalf hoeken** in de Calle Hatunrumiyoc. Een enorm blok dat zo precies tegen de stenen eromheen past dat je er geen mes tussen krijgt.
- **Qorikancha**, de oude zonnetempel. De Spanjaarden bouwden er een klooster bovenop, maar de Inca-muren zijn nog te zien.
- **De markt van San Pedro**: vers sap, stapels aardappels en maïs in alle kleuren, en een hal vol eetkraampjes.
- **Sacsayhuamán**, boven de stad: een vesting met zigzagmuren van stenen die tot honderd ton wegen.

## De Heilige Vallei

Op dag drie huurden we een taxi met chauffeur, en reden we door de **Heilige Vallei** van de Urubamba, de vruchtbare vallei waar de Inca's hun maïs verbouwden.

**Moray** is een van de vreemdste plekken die ik heb gezien: enorme cirkelvormige terrassen die als een amfitheater de diepte in gaan. Het temperatuurverschil tussen de bovenste en de onderste ring kan vijftien graden zijn. Wetenschappers denken dat de Inca's hier experimenteerden met gewassen: welke soort groeit het best op welke hoogte?

