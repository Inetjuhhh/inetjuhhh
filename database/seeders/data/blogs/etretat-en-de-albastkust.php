De **Côte d'Albâtre**, de Albastkust, strekt zich uit van Le Havre tot Le Tréport: honderddertig kilometer witte krijtkliffen, tot honderd meter hoog, met kleine badplaatsjes in de dalen ertussen. Het mooiste stukje is bij **Étretat**, en daar brachten we de laatste vier dagen van onze huwelijksreis door.

## De kliffen

Étretat zelf is een klein badplaatsje met een kiezelstrand, een boulevard en een paar vakwerkhuizen. Maar het gaat om wat links en rechts van het strand ligt.

Aan de rechterkant (als je naar zee kijkt) staat de **Falaise d'Amont**, met op de top een kapel en een monument voor twee Franse vliegeniers die hier in 1927 voor het laatst werden gezien. In de klif zit een natuurlijke boog, de **Porte d'Amont**.

Aan de linkerkant staat de beroemdste: de **Falaise d'Aval**, met een nog grotere boog, de **Porte d'Aval**, en daarnaast een vrijstaande naald van krijt in zee, de **Aiguille**, van zeventig meter hoog. Claude Monet schilderde deze kliffen meer dan vijftig keer, bij elk weer en elk licht.

