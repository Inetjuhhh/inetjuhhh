## Fécamp en de Bénédictine

Een dag reden we naar **Fécamp**, een vissersstadje een kwartiertje verderop, met nog hogere kliffen. Hier staat het **Palais Bénédictine**, een soort sprookjeskasteel uit de negentiende eeuw waar de kruidenlikeur Bénédictine wordt gemaakt. Je kunt er een rondleiding krijgen, en proeven. Ik vond het te zoet. Bas nam een fles mee.

## Terugblik

Twee weken Normandië zitten erop. We hebben veertien kazen geproefd, drie flessen calvados gekocht, door modder gelopen en over kliffen gewandeld. We hebben gelachen en gehuild, en heel veel gepraat over de toekomst.

Het was niet de huwelijksreis die we hadden gepland. Maar het was wel precies de huwelijksreis die we nodig hadden. Na een jaar vol afzeggingen voelde het als een cadeau om gewoon weer onderweg te zijn, samen.

