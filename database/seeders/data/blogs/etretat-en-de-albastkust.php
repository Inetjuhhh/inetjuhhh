## Wandelen langs de rand

Het mooiste is om over de kliffen te lopen. Er loopt een pad langs de rand (de **GR21**), met overal uitzichtpunten. We liepen van Étretat over de Falaise d'Aval naar de **Manneporte**, een nog grotere boog die je alleen vanaf boven goed kunt zien. Daarna verder naar het westen, over golvende graslanden, met de zee aan je rechterhand.

Bij eb kun je ook onder de kliffen over het strand lopen, en via een tunnel in de rots naar het volgende strandje. Maar let goed op het tij: het water komt snel op en de kliffen zijn niet te beklimmen.

