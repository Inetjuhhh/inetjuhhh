De **Gouden Cirkel** is een rondrit van zo'n driehonderd kilometer vanaf Reykjavík, langs drie van de bekendste plekken van IJsland. Normaal gesproken rijden er elke dag honderden touringcars. In juni 2021 was het nog rustig: soms stonden we met tien mensen bij een bezienswaardigheid waar er normaal duizend staan.

## Þingvellir

Eerste stop: **Þingvellir**, een nationaal park in een brede kloof. Hier drijven de Noord-Amerikaanse en de Euraziatische plaat uit elkaar, elk jaar zo'n twee centimeter. Je loopt door de **Almannagjá**, een spleet tussen twee rotswanden, letterlijk tussen twee continenten.

Þingvellir is ook de plek waar in het jaar 930 het **Alþingi** werd opgericht, een van de oudste parlementen ter wereld. Elk jaar kwamen de IJslanders hier bijeen om wetten te maken en ruzies te beslechten. Bij de **Lögberg**, de Wetsrots, sprak de wetspreker de wetten uit, uit zijn hoofd.

