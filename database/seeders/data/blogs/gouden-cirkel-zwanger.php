## De Blue Lagoon en de Secret Lagoon

En dan de vraag die iedereen me stelt: ben je naar de **Blue Lagoon** geweest? Nee. Het water van de Blue Lagoon is zo'n 38 tot 40 graden, en zwangere vrouwen wordt aangeraden niet te lang in heel warm water te zitten. Bovendien is het erg duur.

We gingen in plaats daarvan naar de **Secret Lagoon** in Flúðir, een oud natuurlijk zwembad van ruim honderd jaar oud, met een kleine geiser ernaast. Ik zocht een plekje aan de koelste kant op, bleef er niet te lang in en zat de rest van de tijd op de rand met mijn voeten in het water. Prima te doen.

