In het park ligt ook **Silfra**, een spleet gevuld met smeltwater van een gletsjer, zo helder dat je honderd meter ver kunt kijken. Je kunt er snorkelen tussen de continentale platen, in een droogpak. Bas deed het. Ik zat op de kant met een kop thee en vond het prima zo.

## Geysir en Strokkur

In **Haukadalur** ligt het geothermisch gebied waar alle geisers ter wereld hun naam aan te danken hebben: de **Geysir**. Hij spuit tegenwoordig bijna nooit meer, maar zijn buurman **Strokkur** des te vaker: elke vijf tot tien minuten.

Je staat in een kring om een borrelend blauw gat. Het water zakt, het water stijgt, er vormt zich een enorme blauwe bel, en dan BAM: een zuil van kokend water en stoom spuit twintig, dertig meter de lucht in. Iedereen schrikt, elke keer weer, ook al sta je erop te wachten. Ik heb er zeker een uur naar staan kijken.

## Gullfoss

Tien minuten verder ligt **Gullfoss**, de Gouden Waterval. De rivier Hvítá stort zich hier in twee trappen een smalle kloof in, 32 meter diep. Vanaf het uitzichtpunt lijkt het alsof het water in de aarde verdwijnt. Er hangt altijd een wolk van spatwater boven, en als de zon schijnt, zie je een regenboog. Wij zagen er twee.

