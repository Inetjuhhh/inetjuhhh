## Nyhavn

Natuurlijk gingen we naar **Nyhavn**, de oude haven met de gekleurde huizen aan het water, de houten zeilschepen en de terrasjes met dekens op elke stoel. Hans Christian Andersen woonde hier op drie verschillende adressen. Het is druk en toeristisch, maar het blijft een van de mooiste plekken van de stad. We aten er *smørrebrød*: Deens open roggebrood met haring, ei en garnalen, of met rosbief en gebakken uitjes.

## Tivoli

**Tivoli**, het pretpark midden in de stad, bestaat al sinds 1843 en is een van de oudste pretparken ter wereld. Walt Disney kwam hier inspiratie opdoen voor Disneyland. Eind oktober is het ingericht voor Halloween, met duizenden pompoenen en lichtjes in de bomen.

Een baby van acht weken heeft natuurlijk niks aan een achtbaan. Maar wandelen door het park in het donker, tussen de lichtjes en de fonteinen, met warme chocolademelk in je hand en een slapende baby in de kinderwagen, is ook heel fijn. Bas ging één keer in de oudste houten achtbaan, de **Rutschebanen** uit 1914. Ik stond beneden met Sam, en we zwaaiden.

