De laatste drie dagen van onze Deense reis brachten we door in **Kopenhagen**. Ik was er al eens geweest, voor werk, maar met een baby kijk je met andere ogen naar een stad. En Kopenhagen bleek met een baby de prettigste stad die ik ken.

## Een stad voor kinderen

Het begint met de straten: breed, met brede stoepen, en overal liften en hellingen. Bijna elk café heeft een verschoonplek en een kinderstoel. Maar het mooiste vond ik dit: Deense ouders laten hun baby's slapen in de kinderwagen, **buiten**, voor het café, terwijl ze zelf binnen koffie drinken. Ook in de winter, warm ingepakt. Het is in Denemarken heel normaal. We hebben het niet gedaan (te Nederlands, denk ik), maar ik vond het mooi om te zien.

## De bakfiets

Kopenhagen is na Amsterdam de fietsstad van Europa, en hier zie je overal **bakfietsen** (ze heten hier gewoon *Christiania-cykel*). We huurden er een met een babyschaal erin, en fietsten daarmee drie dagen door de stad. Over brede fietspaden, langs het water, door de parken. Sam lag in zijn schaaltje onder een regenkap en keek naar de lucht. Ik denk dat hij het geweldig vond. Of hij sliep. Allebei is prima.

