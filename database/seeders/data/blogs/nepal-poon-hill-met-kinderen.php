## Een gids en een drager

We namen een gids en een drager via een agentschap in Pokhara. Dat kostte bij elkaar ongeveer 60 dollar per dag, plus eten en slapen voor henzelf (dat is vaak bij de prijs inbegrepen). Voor ons was dat de beste beslissing van de reis.

Onze gids Ramesh had zelf drie kinderen en wist precies hoe hij Siem en Noor gemotiveerd moest houden. Hij leerde ze tellen in het Nepalees, wees ze op apen in de bomen en verzon een wedstrijdje wie de meeste gebedsvlaggetjes kon spotten. Onze drager Bikash droeg onze grote tas, zodat wij alleen een kleine rugzak met water, snacks en regenjassen hoefden te dragen. Bovendien was het een hele geruststelling om iemand bij ons te hebben die de omgeving kende, voor het geval er iets mis zou gaan.

## Die trappen

Over de beroemde trap van Ulleri wordt veel geschreven en geloof me: het is niet overdreven. Het zijn ruim drieduizend stenen treden achter elkaar, steil omhoog. Wij maakten er een spelletje van: elke honderd treden mochten de kinderen een M&M. Siem hield het bij in een notitieboekje. Halverwege waren de M&M's op en moesten we overstappen op rozijnen, wat op flink wat protest stuitte.

Het hielp ook enorm om vroeg te beginnen. Om zeven uur 's ochtends is het nog koel, en tegen het middaguur zaten we al op het terras van ons teahouse met een glas warme citroensap.

## Het leven in de teahouses

De teahouses waren voor de kinderen misschien wel het leukste deel. In de eetzaal staat 's avonds een kachel en zitten trekkers uit de hele wereld samen te eten, kaarten en verhalen uit te wisselen. Siem speelde met een Duitse jongen een potje schaak dat twee avonden duurde.

De kamers zijn heel eenvoudig: twee of drie houten bedden, een dun matras en een deken. Het wordt 's nachts koud, dus neem goede slaapzakken mee. Warme douches zijn er soms, maar kosten vaak extra en het water is niet altijd warm. We hebben de kinderen in vier dagen één keer gewassen en niemand heeft geklaagd.

Eten deden we bijna elke dag **dal bhat**: rijst met linzensoep, groentecurry en een pittig zuur. Het mooie is dat je net zo vaak mag bijscheppen als je wilt. Er is een gezegde in Nepal: *dal bhat power, 24 hour*. De kinderen vonden het in het begin wat vreemd, maar aan het eind van de tocht bestelde Noor het zelf.

## Zonsopkomst op Poon Hill

Op dag drie gaat de wekker om half vijf. Met hoofdlampjes op loop je in ongeveer drie kwartier van Ghorepani naar de top van Poon Hill. Het is een drukke klim, want iedereen in het dorp doet het. Onze kinderen waren slaperig en chagrijnig en Noor heeft het eerste stuk op de schouders van haar vader gezeten.

Maar boven was alles vergeten. Voor ons lag een complete rij reuzen: de **Dhaulagiri**, de **Annapurna South** en de spitse **Machapuchare**, de Visstaart, een heilige berg die nooit beklommen mag worden. Toen de zon opkwam, werden de toppen eerst roze, daarna oranje en uiteindelijk verblindend wit. Er werd thee verkocht en we stonden met z'n vieren in een dekentje gewikkeld naar het spektakel te kijken.

> Soms vraag je je af waarom je jezelf en je kinderen zoiets aandoet. En dan sta je daar, en weet je het weer.

