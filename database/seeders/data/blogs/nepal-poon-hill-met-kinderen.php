- **Kies een korte route op lage hoogte.** Poon Hill is ideaal. Ga met jonge kinderen niet hoger dan zo'n 3.500 meter.
- **Neem een gids**, liefst een die ervaring heeft met kinderen.
- **Laat de kinderen hun eigen kleine rugzakje dragen**, met hun eigen water en een knuffel. Dat geeft ze een gevoel van verantwoordelijkheid.
- **Neem veel snacks mee** uit Pokhara. In de bergen worden ze duurder naarmate je hoger komt.
- **Plan een rustdag in Pokhara** na afloop. Een middag op het Phewa-meer in een roeibootje is het perfecte einde.
- **Regel de vergunningen**: voor het Annapurna-gebied heb je een ACAP-permit nodig. Je gids of agentschap kan dat voor je regelen.

