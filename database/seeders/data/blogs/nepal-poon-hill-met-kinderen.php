## Waarom Poon Hill?

De Poon Hill trek is een van de kortste en toegankelijkste tochten in het Annapurna-gebied. Het hoogste punt ligt op 3.210 meter, wat hoog genoeg is voor fantastische uitzichten, maar laag genoeg om weinig risico op hoogteziekte te hebben. Je overnacht in *teahouses*, eenvoudige berghutten met een eetzaal en een kachel, dus je hoeft geen tent of eten mee te sjouwen.

De route die wij liepen:

1. **Dag 1**: Van Pokhara met de jeep naar Ulleri, lopen naar Banthanti.
2. **Dag 2**: Van Banthanti naar Ghorepani (2.860 m).
3. **Dag 3**: Om half vijf naar Poon Hill voor zonsopkomst, daarna verder naar Tadapani.
4. **Dag 4**: Afdalen via Ghandruk en met de jeep terug naar Pokhara.

Veel volwassenen doen deze route in drie dagen, maar met kinderen raad ik vier of zelfs vijf dagen aan. Dan loop je zo'n vijf uur per dag, met genoeg tijd voor pauzes, spelletjes en het aaien van iedere geit die je tegenkomt.

