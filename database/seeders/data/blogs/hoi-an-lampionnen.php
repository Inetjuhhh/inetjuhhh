Van Hanoi namen we het vliegtuig naar Da Nang, en vandaar was het een half uur met de taxi naar **Hoi An**. Normaal neem je hier de trein (de Reunification Express, een prachtige rit langs de kust), maar met een dreumes kozen we voor één uur vliegen in plaats van zeventien uur in de trein.

## Het oude stadje

Hoi An was van de vijftiende tot de negentiende eeuw een van de belangrijkste havens van Zuidoost-Azië. Chinese, Japanse en ook Nederlandse handelaren kwamen hier zijde, porselein en specerijen kopen. Daarna verzandde de rivier, de schepen gingen naar Da Nang en Hoi An viel in slaap. Daardoor is het oude centrum bewaard gebleven: een netwerk van straatjes met gele huizen met houten luiken, Chinese tempels en vergaderhallen, en bougainville die over de muren hangt.

Het oude centrum is grotendeels **autovrij**, en op de meeste uren ook scootervrij. Met een kind is dat een verademing. Sam kon eindelijk zelf lopen, tussen ons in, aan twee handen. Elke drie meter stopte hij om naar iets te wijzen: een kat, een lampion, een vrouw met fruit in twee manden aan een stok.

## De Japanse brug

Het symbool van Hoi An is de **Japanse overdekte brug**, uit de zestiende eeuw, met een klein tempeltje erin. Aan de ene kant waken twee stenen honden, aan de andere kant twee apen. Volgens de overlevering verbond de brug de Japanse en de Chinese wijk met elkaar.

