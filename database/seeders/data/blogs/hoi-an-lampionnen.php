## Lampionnen

Hoi An wordt 's avonds pas echt mooi. Dan gaan overal de **lampionnen** aan: van zijde, in alle kleuren, in de straten, in de bomen en langs de rivier. Op de rivier varen bootjes met lichtjes, en kinderen verkopen papieren lampionnetjes met een kaarsje, die je op het water kunt zetten met een wens.

Wij kochten er een, en lieten hem samen met Sam te water. Hij wilde het lampionnetje terug. We hebben toen nog een tweede gekocht, die hij mocht houden.

## De kleermaker

Hoi An staat bekend om zijn **kleermakers**: er zijn er honderden. Je kiest een stof en een model (of laat een foto zien), je wordt opgemeten, en een dag of twee later is je kleding klaar. Bas liet een pak maken, in donkerblauwe wol, voor het bruiloftsfeest dat we volgend jaar eindelijk gaan geven. Ik liet een jurk maken. En de kleermaakster, mevrouw Lan, maakte ongevraagd een klein overhemdje voor Sam, van de restjes van Bas' stof. "Cadeau," zei ze. Ik heb er een beetje om gehuild.

## Eten in Hoi An

- **Cao lầu**: dikke noedels met varkensvlees, kruiden en krokante stukjes, alleen te krijgen in Hoi An. Het water voor de noedels moet volgens de overlevering uit één specifieke oude put komen.
- **Bánh mì**: het beroemde Vietnamese stokbroodje, een erfenis van de Fransen. Het lekkerste van heel Vietnam haal je bij Bánh Mì Phượng. Sam at de korstjes.
- **Mì Quảng**: brede, gele rijstnoedels met een klein beetje bouillon, garnalen en kruiden.
- **White rose**: kleine dumplings van rijstdeeg met garnalen, die eruitzien als witte rozen.

