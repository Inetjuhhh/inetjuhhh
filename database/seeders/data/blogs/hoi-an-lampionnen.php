## Het strand

Hoi An ligt vlak bij de kust. We fietsten (Sam in het kinderzitje) door de rijstvelden naar het strand van **An Bang**, met strandstoelen, rieten parasols en kleine visrestaurants. 's Middags lag Sam in de schaduw te slapen, en wij in een strandstoel. Bas noemde het "de beste middag van de reis". Ik denk dat hij gelijk had.
