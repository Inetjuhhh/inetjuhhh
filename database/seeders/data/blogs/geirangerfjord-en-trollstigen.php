## Ørnesvingen

Aan de noordkant van Geiranger loopt de weg met elf haarspeldbochten omhoog: de **Ørnevegen**, de Adelaarsweg. Bij de bocht **Ørnesvingen** is een uitzichtpunt met een glazen balkon over het fjord. Het uitzicht is misschien wel het mooiste van heel Noorwegen. Sam vond vooral het grote cruiseschip in het fjord interessant. "Boot!" riep hij, met zijn neus tegen het glas.

## De Trollstigen

En dan de **Trollstigen**, de Trollenladder: een van de bekendste wegen ter wereld. Elf haarspeldbochten tegen een bijna loodrechte bergwand, met een stijging van tien procent, langs de waterval **Stigfossen**. Hij is zo smal dat twee campers elkaar bijna niet kunnen passeren, en er is een maximale lengte van 13,1 meter.

Onze camper was zeven meter. Bas reed. Ik zat ernaast met mijn ogen dicht en mijn hand op het dashboard. Sam sliep. Bovenaan staat een groot bezoekerscentrum met uitzichtplatforms die over de afgrond hangen. Van daaruit zie je de weg in de diepte, als een grijs lint dat zich door het dal slingert.

