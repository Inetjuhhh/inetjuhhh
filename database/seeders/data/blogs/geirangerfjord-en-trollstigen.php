Na de Preikestolen reden we in een paar dagen langs de westkust naar het noorden, over bergpassen en langs het **Hardangerfjord** (vol fruitbomen en kersenkraampjes) en het **Sognefjord**, het langste fjord van Noorwegen. Maar het fjord waar we het meest naar hadden uitgekeken, was het **Geirangerfjord**.

## De weg naar Geiranger

Je kunt Geiranger op twee manieren bereiken: over de weg, of met de veerboot. Wij kwamen over de weg vanuit het zuiden, over de bergpas van **Dalsnibba**. Bovenaan ligt nog sneeuw, ook in juli, en Sam zag voor het eerst in zijn leven sneeuw. Hij was er een beetje bang voor. Daarna gooide hij een sneeuwbal tegen Bas' hoofd, en was hij niet meer bang.

Vanaf Dalsnibba gaat de weg in haarspeldbochten omlaag naar het dorp Geiranger, aan het einde van het fjord. Bij het uitzichtpunt **Flydalsjuvet** heb je het beroemde uitzicht: een rotspunt boven het dal, met het fjord in de diepte.

## Het fjord

Het Geirangerfjord is vijftien kilometer lang, smal, en omringd door bergen van meer dan 1.400 meter hoog, met watervallen die van de steile wanden naar beneden storten. Het staat op de Unesco-werelderfgoedlijst. Het mooiste zie je het vanaf het water.

We namen de **veerboot van Geiranger naar Hellesylt**, een tocht van een uur door het hele fjord. Halverwege vaar je langs de **Zeven Zussen**: zeven watervallen naast elkaar, die ruim 250 meter van de rotswand naar beneden vallen. Aan de overkant hangt een andere waterval, de **Vrijer**, die volgens de legende de zussen probeerde te versieren, maar steeds werd afgewezen. Uit verdriet ging hij aan de drank. Je kunt zelfs de vorm van een fles in de waterval zien, zegt men. Wij zagen hem niet.

